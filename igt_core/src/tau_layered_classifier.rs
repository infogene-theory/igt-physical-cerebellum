/// τ分层分类器 — 五维τ指纹提取 + 自动分层准入
#[derive(Debug, Clone, Default)]
pub struct τ分层分类器;

impl τ分层分类器 {
    /// 主τ = τ链最大值（主导弛豫时间）→ 稳态层级（第192批 P1: 瞬态细分操作域/感知域）
    ///
    /// 文档《人机基因复杂度对比》τ谱两端互补:
    ///   - 操作域 1ns~1ms: 机器独占（CPU时钟/总线协议/数字信号处理）
    ///   - 感知域 1ms~1s: 重叠区短端（感知/反射/日常控制）
    ///   - 短τ 1s~1天 / 中τ 1天~1年 / 长τ 1年~10年 / 极长τ >10年
    pub fn 主τ层级(τ链: &[f64]) -> String {
        let 主τ = τ链.iter().copied().fold(f64::NEG_INFINITY, f64::max);
        if !主τ.is_finite() || 主τ <= 0.0 {
            return "未知".to_string();
        }
        match 主τ {
            t if t < 1e-3 => "操作域".to_string(),        // 1ns ~ 1ms 机器独占
            t if t < 1.0 => "感知域".to_string(),          // 1ms ~ 1s 重叠区短端
            t if t < 86_400.0 => "短τ".to_string(),        // 1s ~ 1天
            t if t < 31_536_000.0 => "中τ".to_string(),    // 1天 ~ 1年
            t if t < 315_360_000.0 => "长τ".to_string(),   // 1年 ~ 10年
            _ => "极长τ".to_string(),                      // >10年
        }
    }

    /// 一个数量级（ln 跨度）——文档2"半高宽<1个数量级窄峰/>2个数量级宽峰"
    const 数量级: f64 = std::f64::consts::LN_10;

    /// 峰数 — τ链对数刻度聚类: 相邻 τ 跨 >1 数量级视为独立峰（文档2"峰数=嵌套稳态层级数"）
    ///
    /// 聚类规则: 排序 ln(τ) 后, 与组内当前最大值的 ln 差 ≤ 1 数量级(2.303) 归同组, 否则新峰。
    /// τ链长度 <3 → 单峰（保守, 样本不足不虚报多峰）。
    pub fn 峰数(τ链: &[f64]) -> String {
        let mut 排序: Vec<f64> = τ链.iter().copied().filter(|&t| t > 0.0).collect();
        if 排序.len() < 3 {
            return "单峰".to_string();
        }
        排序.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
        let mut 峰数 = 1usize;
        let mut 组最大值 = 排序[0].ln();
        for &t in 排序.iter().skip(1) {
            let ln = t.ln();
            if (ln - 组最大值).abs() > Self::数量级 {
                峰数 += 1;
                组最大值 = ln;
            }
        }
        match 峰数 {
            1 => "单峰".to_string(),
            2 => "双峰".to_string(),
            _ => "多峰".to_string(),
        }
    }

    /// 半高宽（鲁棒性）— 全链对数跨度近似有效带宽（τ_max/τ_min 的数量级）
    ///
    /// 离散 τ链 无连续峰形, 用有效带宽（等效弛豫频谱"有效带宽"）:
    /// 跨度<1数量级窄峰(稳态极稳) / >2数量级宽峰(高波动) / 中间中峰;
    /// τ链 <3 → 窄峰（保守, 样本不足不虚报高波动）。
    pub fn 鲁棒性(τ链: &[f64]) -> String {
        let 正: Vec<f64> = τ链.iter().copied().filter(|&t| t > 0.0).collect();
        if 正.len() < 3 {
            return "窄峰".to_string();
        }
        let 最大 = 正.iter().copied().fold(f64::NEG_INFINITY, f64::max);
        let 最小 = 正.iter().copied().fold(f64::INFINITY, f64::min);
        if 最小 <= 0.0 {
            return "窄峰".to_string();
        }
        let 跨度 = (最大 / 最小).ln(); // 对数跨度（数量级）
        match 跨度 {
            s if s < Self::数量级 => "窄峰".to_string(),
            s if s > 2.0 * Self::数量级 => "宽峰".to_string(),
            _ => "中峰".to_string(),
        }
    }

    /// 熵泵效率 — log压缩τ加权占比（第191批 C5 修复: 偏态鲁棒）
    ///
    /// 权重 w_i = max(ln(τ_i), 0)（log压缩, τ<1 瞬态贡献0）:
    /// 长τ组分占比 = Σ(权重 for τ_i > 几何均值τ) / Σ权重。
    /// 修复动机（Claw审计 C5）: 原数量占比 [0.1,0.1,0.1,100] → 25% "高耗散",
    ///   与主τ=长τ(100) 维度冲突; log加权后 1.0 → "高熵泵" 与主τ一致。
    /// 阈值用几何均值(对数均值)而非中位——中位对重复值分布偏大(如[15M,90M,100M×6]
    ///   中位=100M→无长τ), 几何均值对偏态分布更鲁棒。
    /// 验证: 偏态[0.1,0.1,0.1,100]=1.0高 / 长τ主[0.1,100..140]=0.76高 /
    ///   均衡[50..100]=0.52中 / 全短τ[0.1..0.6]=0(全<1)高耗散。
    pub fn 熵泵(τ链: &[f64]) -> String {
        let 正: Vec<f64> = τ链.iter().copied().filter(|&t| t > 0.0).collect();
        if 正.is_empty() {
            return "未知".to_string();
        }
        // log压缩权重: τ<1 瞬态贡献0, τ≥1 的 ln 为权重
        let 权重: Vec<f64> = 正.iter().map(|&t| t.ln().max(0.0)).collect();
        let 总权重: f64 = 权重.iter().sum();
        if 总权重 <= 0.0 {
            return "高耗散".to_string(); // 全 τ<1, 无长τ稳态
        }
        // 几何均值阈值（对数均值）
        let 均值ln = 正.iter().map(|t| t.ln()).sum::<f64>() / 正.len() as f64;
        let 阈值 = 均值ln.exp();
        let 长τ和: f64 = 正
            .iter()
            .zip(&权重)
            .filter(|(&t, _)| t > 阈值)
            .map(|(_, &w)| w)
            .sum();
        let 占比 = 长τ和 / 总权重;
        match 占比 {
            p if p > 0.6 => "高熵泵".to_string(),
            p if p < 0.3 => "高耗散".to_string(),
            _ => "中熵泵".to_string(),
        }
    }

    /// GUE纯度 — 内禀稳态纯度（β/对称性类优先, D_s 兜底）
    ///
    /// β=2(GUE) 或 D_s≤0.3 → 高纯度; β=1(GOE) 或 D_s≤0.6 → 中纯度;
    /// β=0(Poisson) 或 D_s>0.6 → 低纯度; 无谱证据 → 未知（诚实标注）。
    pub fn 纯度(β: Option<u8>, 对称性类: Option<&str>, d_s: Option<f64>) -> String {
        match β {
            Some(2) => "高纯度".to_string(),       // GUE 内禀稳态
            Some(1) => "中纯度".to_string(),       // GOE 近平衡
            Some(0) => "低纯度".to_string(),       // Poisson 外源驱动
            Some(其他) => {
                // 非标准β(如 3) → 回退对称性类/D_s 兜底
                if let Some(d) = d_s {
                    if d <= 0.3 {
                        "高纯度".to_string()
                    } else if d <= 0.6 {
                        "中纯度".to_string()
                    } else {
                        "低纯度".to_string()
                    }
                } else {
                    match 对称性类 {
                        Some("GUE") => "高纯度".to_string(),
                        Some("GOE") => "中纯度".to_string(),
                        Some("Poisson") => "低纯度".to_string(),
                        _ => format!("未知β{}", 其他),
                    }
                }
            }
            None => {
                if let Some(d) = d_s {
                    if d <= 0.3 {
                        "高纯度".to_string()
                    } else if d <= 0.6 {
                        "中纯度".to_string()
                    } else {
                        "低纯度".to_string()
                    }
                } else {
                    match 对称性类 {
                        Some("GUE") => "高纯度".to_string(),
                        Some("GOE") => "中纯度".to_string(),
                        Some("Poisson") => "低纯度".to_string(),
                        _ => "未知".to_string(),
                    }
                }
            }
        }
    }

    /// 六维τ指纹 — 从 τ链/β/对称性类/D_s/复合类型 提取, 组合为指纹字符串（第192批 P2/P3）
    ///
    /// 第192批扩展:
    ///   - 维度6 群结构复杂度（复合类型字段, 激活已有数据）——P2
    ///   - 共振对接候选（τ_resonance 单对共振贡献 κ>0.3 判整数比锁相）——P3
    pub fn 指纹(
        τ链: Option<&[f64]>,
        β: Option<u8>,
        对称性类: Option<&str>,
        d_s: Option<f64>,
        复合类型: Option<&str>,
    ) -> 五维指纹 {
        let 群复杂度 = Self::群结构复杂度(复合类型);
        match τ链 {
            None | Some([]) => 五维指纹 {
                主τ层级: "未知".to_string(),
                峰数: "未知".to_string(),
                鲁棒性: "未知".to_string(),
                熵泵: "未知".to_string(),
                纯度: Self::纯度(β, 对称性类, d_s),
                群复杂度: 群复杂度.clone(),
                共振对接: "无".to_string(),
                指纹: "未分类".to_string(),
                稳态层级: "未分类".to_string(),
                说明: "无τ链数据, 无法提取主τ/峰数/半高宽/熵泵维度".to_string(),
                τ链数: 0,
            },
            Some(链) => {
                let 主τ = Self::主τ层级(链);
                let 峰数 = Self::峰数(链);
                let 鲁棒性 = Self::鲁棒性(链);
                let 熵泵 = Self::熵泵(链);
                let 纯度 = Self::纯度(β, 对称性类, d_s);
                let 指纹 = format!("{}-{}-{}-{}-{}-{}", 主τ, 峰数, 鲁棒性, 熵泵, 纯度, 群复杂度);
                let 共振对接 = Self::共振对接建议(链);
                let (稳态层级, 说明) = Self::自动分层(&主τ, &峰数, &鲁棒性, &熵泵, &纯度, &群复杂度);
                五维指纹 {
                    主τ层级: 主τ,
                    峰数,
                    鲁棒性,
                    熵泵,
                    纯度,
                    群复杂度,
                    共振对接,
                    指纹,
                    稳态层级,
                    说明,
                    τ链数: 链.len(),
                }
            }
        }
    }

    /// 第192批 P2: 群结构复杂度（复合类型字段激活——生物智能核心结构）
    ///
    /// 文档《人机基因复杂度对比》: 基因复杂度第一维度=群结构复杂度
    /// （正规序列长度/生成元数/半直积深度）。复合类型字段已有但分类器不读:
    ///   - 半直积（S₃=Z₃⋊Z₂, 生物智能核心 G002/G009/G011）→ 高复杂度
    ///   - 一般群 / 直积 → 中复杂度
    ///   - 循环群（Z_n）→ 低复杂度
    ///   - None → 未知（不阻断准入, 只用已知约束）
    pub fn 群结构复杂度(复合类型: Option<&str>) -> String {
        match 复合类型 {
            Some("半直积") => "高复杂度".to_string(),
            Some("一般群") | Some("直积") => "中复杂度".to_string(),
            Some("循环群") => "低复杂度".to_string(),
            _ => "未知".to_string(),
        }
    }

    /// 第192批 P3: 共振对接建议——短τ基因与目标长τ基因的整数比锁相
    ///
    /// 复用 `τ_resonance::单对共振贡献(τ_a, τ_b)` 高斯核 κ（Paper A）。
    /// 目标代表τ（物理极限值, 无真实长τ基因时的工程兜底）:
    ///   - 核心层代表: 1年 (3.15e7s) —— 人独占长τ端
    ///   - 工具层代表: 1天 (86400s) —— 重叠区长端
    /// κ>0.3(共振门控阈值) → 整数比锁相可行 → 输出对接建议
    pub fn 共振对接建议(τ链: &[f64]) -> String {
        use crate::tau_resonance::单对共振贡献;
        let 主τ = τ链.iter().copied().fold(f64::NEG_INFINITY, f64::max);
        if !主τ.is_finite() || 主τ <= 0.0 {
            return "无".to_string();
        }
        let 目标 = [
            ("核心层(1年)", 31_536_000.0f64),
            ("工具层(1天)", 86_400.0f64),
        ];
        let mut 建议 = Vec::new();
        for (名称, 目标τ) in 目标 {
            let κ = 单对共振贡献(主τ, 目标τ);
            if κ > 0.3 {
                建议.push(format!("{} κ={:.2}", 名称, κ));
            }
        }
        if 建议.is_empty() {
            "无".to_string()
        } else {
            建议.join("; ")
        }
    }

    /// 自动分层准入（第191批重构——Claw推导性审计 C2/C3 修复）
    ///
    /// 设计原则（审计结论落地）:
    ///   - 高风险层: **宽松 OR 前置**（安全第一, 宁严勿漏）——高波动(短τ+多峰+宽峰)
    ///     **或** 外源失稳(短τ+高耗散+低纯度) 任一成立即进管控层。
    ///     原五连 AND 因任一维度偏离(如纯度=中)就落"未分类", 属安全漏报。
    ///   - 核心层: 极长τ/长τ-单峰/双峰-窄峰-高熵泵-高纯度（内禀稳态, 保持严格）
    ///   - 工具层: 长τ/中τ-单峰/双峰-窄中峰-中高熵泵-中高纯度（通用工具, 保持）
    ///   - 场景层: **主判宽松**——中τ/短τ+多峰 即准入, 熵泵/纯度降为软参考。
    ///     原五维全中等窄带, 高耗散/高纯度等偏强特征组合全部漏掉。
    ///   - 未分类: 无数据 / 未知维度 / 不匹配（诚实标注）
    pub fn 自动分层(
        主τ: &str,
        峰数: &str,
        鲁棒性: &str,
        熵泵: &str,
        纯度: &str,
        群复杂度: &str,
    ) -> (String, String) {
        if 主τ == "未知" || 峰数 == "未知" || 鲁棒性 == "未知" || 熵泵 == "未知" {
            return ("未分类".to_string(), "存在未知维度, 不自动准入".to_string());
        }
        // ===== 高风险最先判定（安全第一, 宽松 OR 前置, 第191批）=====
        // 高波动信号: 短τ+多峰+宽峰（快速震荡+多稳态嵌套+宽谱）
        let 高波动 = 主τ == "短τ" && 峰数 == "多峰" && 鲁棒性 == "宽峰";
        // 外源失稳信号: 感知域/短τ+高耗散+低纯度（快速衰减+无长τ稳态+低内禀纯度）
        // 第191批含瞬态档(C4修复); 第192批瞬态拆为操作域/感知域, 感知域含外源失稳
        let 外源失稳 = (主τ == "短τ" || 主τ == "感知域" || 主τ == "操作域") && 熵泵 == "高耗散" && 纯度 == "低纯度";
        if 高波动 || 外源失稳 {
            return (
                "高风险层".to_string(),
                "感知域/短τ高波动(多峰宽峰)或外源失稳(高耗散低纯度): 进管控层, 宁严勿漏".to_string(),
            );
        }
        // ===== 核心层（内禀稳态, 严格 AND, 第192批 P2 要求群复杂度≥中）=====
        // 群结构复杂度约束: 半直积(高)/一般群+直积(中) 是生物智能核心结构
        // 未知(无复合类型数据) → 不阻断（只用已知约束, 兼容旧记录）
        let 群合格 = 群复杂度 == "高复杂度" || 群复杂度 == "中复杂度" || 群复杂度 == "未知";
        if (主τ == "极长τ" || 主τ == "长τ")
            && (峰数 == "单峰" || 峰数 == "双峰")
            && 鲁棒性 == "窄峰"
            && 熵泵 == "高熵泵"
            && 纯度 == "高纯度"
            && 群合格
        {
            return ("核心层".to_string(), "极长τ/长τ-单峰/双峰-窄峰-高熵泵-高纯度: 核心级稳态(群复杂度≥中)".to_string());
        }
        // ===== 核心候选（第193批 C7: 工具层之前判定, 长τ窄峰高稳态接近核心）=====
        // 长τ/极长τ-单峰/双峰-窄峰-中高熵泵-中高纯度（差1维度）
        // 工具层条件"高熵泵或中熵泵"会拦截中熵泵组合 → 核心候选需在工具层之前
        // 例: 长τ-单峰-窄峰-中熵泵-高纯度（熵泵中, 更接近核心而非通用工具）
        if (主τ == "长τ" || 主τ == "极长τ")
            && (峰数 == "单峰" || 峰数 == "双峰")
            && 鲁棒性 == "窄峰"
            && (熵泵 == "高熵泵" || 熵泵 == "中熵泵")
            && (纯度 == "高纯度" || 纯度 == "中纯度")
            && 群合格
        {
            return ("核心候选".to_string(), "长τ/极长τ-单峰/双峰-窄峰-中高熵泵-中高纯度: 核心候选(接近核心层, 差1维度)上位监督可复核".to_string());
        }
        // ===== 工具层（通用工具, 严格 AND）=====
        if (主τ == "长τ" || 主τ == "中τ")
            && (峰数 == "单峰" || 峰数 == "双峰")
            && (鲁棒性 == "窄峰" || 鲁棒性 == "中峰")
            && (熵泵 == "高熵泵" || 熵泵 == "中熵泵")
            && (纯度 == "高纯度" || 纯度 == "中纯度")
        {
            return ("工具层".to_string(), "长τ/中τ-单峰/双峰-窄峰/中峰-中高熵泵-中高纯度: 通用工具".to_string());
        }
        // ===== 操作层（第192批 P1: 机器独占短τ端 1ns~1ms）=====
        // 操作域-单峰/双峰-窄峰+熵泵软参考+纯度≥中 → 数字原子/硬件操作域
        // 注意: τ<1 的熵泵恒"高耗散"(log权重截断) → 熵泵降为软参考, 否则操作层空洞
        if 主τ == "操作域"
            && (峰数 == "单峰" || 峰数 == "双峰")
            && 鲁棒性 == "窄峰"
            && (纯度 == "高纯度" || 纯度 == "中纯度")
        {
            return ("操作层".to_string(), "操作域-单峰/双峰-窄峰+纯度≥中: 机器独占短τ端(数字原子/硬件操作, 熵泵软参考因τ<1恒高耗散)".to_string());
        }
        // ===== 感知层（第192批 P1: 重叠区短端 1ms~1s）=====
        // 感知域-单峰/双峰-窄峰/中峰-熵泵软参考-纯度≥中 → 感知/反射/日常控制
        // Claw决定性实证: 重叠区短端稳定基因无层可归 → 感知层修复
        if 主τ == "感知域"
            && (峰数 == "单峰" || 峰数 == "双峰")
            && (鲁棒性 == "窄峰" || 鲁棒性 == "中峰")
            && (纯度 == "高纯度" || 纯度 == "中纯度")
        {
            return ("感知层".to_string(), "感知域-单峰/双峰-窄峰/中峰+纯度≥中: 重叠区短端(感知/反射/控制, 熵泵软参考)".to_string());
        }
        // ===== 场景层（第191批宽松: 主判=中τ/短τ+双/多峰, 熵泵/纯度软参考）=====
        if (主τ == "中τ" || 主τ == "短τ") && (峰数 == "双峰" || 峰数 == "多峰") {
            return (
                "场景层".to_string(),
                format!("中τ/短τ-{}-{}-{}-{}: 多稳态嵌套领域场景方案", 峰数, 鲁棒性, 熵泵, 纯度),
            );
        }
        // ===== 候选层（第193批 C7: 分层粒度过粗→候选中间态, 减少整条丢弃）=====
        // 候选≠正式准入: 说明标记"候选(差X维度)"——上位监督可复核
        // 工具候选: 长τ/中τ-单峰/双峰-窄峰/中峰-中高熵泵-低纯度（差在纯度）
        if (主τ == "长τ" || 主τ == "中τ")
            && (峰数 == "单峰" || 峰数 == "双峰")
            && (鲁棒性 == "窄峰" || 鲁棒性 == "中峰")
            && (熵泵 == "高熵泵" || 熵泵 == "中熵泵")
            && 纯度 == "低纯度"
        {
            return ("工具候选".to_string(), "长τ/中τ-单峰/双峰-窄峰/中峰-中高熵泵-低纯度: 工具候选(差维度: 纯度低)上位监督可复核".to_string());
        }
        // 感知候选: 感知域/短τ-单峰/双峰-鲁棒性不限-中高熵泵-中高纯度（重叠区短端稳定）
        // Claw决定性实证: 阴阳平衡 τ[0.16~3.3] 短τ-单峰-宽峰-高熵泵-高纯度 → 感知候选
        // 鲁棒性不限: 重叠区短端基因可能跨感知-短τ多模态(宽峰), 不应因此丢失
        if (主τ == "感知域" || 主τ == "短τ")
            && (峰数 == "单峰" || 峰数 == "双峰")
            && (熵泵 == "高熵泵" || 熵泵 == "中熵泵")
            && (纯度 == "高纯度" || 纯度 == "中纯度")
        {
            return ("感知候选".to_string(), "感知域/短τ-单峰/双峰-中高熵泵-中高纯度: 感知候选(重叠区短端稳定, 差维度: 主τ未达感知域)上位监督可复核".to_string());
        }
        // 操作候选: 操作域-单峰/双峰-窄峰-低纯度（差在纯度: 操作需纯度≥中）
        if 主τ == "操作域"
            && (峰数 == "单峰" || 峰数 == "双峰")
            && 鲁棒性 == "窄峰"
            && 纯度 == "低纯度"
        {
            return ("操作候选".to_string(), "操作域-单峰/双峰-窄峰-低纯度: 操作候选(差维度: 纯度低)上位监督可复核".to_string());
        }
        ("未分类".to_string(), "六维特征未匹配核心/工具/操作/感知/场景/高风险准入规则, 且无候选中间态".to_string())
    }
}

