    /// 第191批（Claw审计 R2）: 逆元完备度便捷入口与计算等价
    #[test]
    fn test_综合熵债_从逆元完备度() {
        // 逆元完备度=1.0(完美对称) → S=1 → D_total = (1-1)×0.6 + 0.25×0.4 = 0.10
        let r = 统一熵债计算器::综合熵债_从逆元完备度(1.0, 0.25);
        assert!((r.d_total - 0.10).abs() < 1e-9, "逆元1.0 D_s0.25 → 0.10, 实际: {}", r.d_total);
        // 等价性: 综合熵债_从逆元完备度(x, ds) == 计算(x, ds)
        let a = 统一熵债计算器::综合熵债_从逆元完备度(0.7, 0.3);
        let b = 统一熵债计算器::计算(0.7, 0.3);
        assert!((a.d_total - b.d_total).abs() < 1e-9, "便捷入口应与计算等价: {} vs {}", a.d_total, b.d_total);
        // 逆元完备度=0(完全破缺) → S=0 → D_total = (1-0)×0.6 + 0×0.4 = 0.6
        let c = 统一熵债计算器::综合熵债_从逆元完备度(0.0, 0.0);
        assert!((c.d_total - 0.6).abs() < 1e-9, "逆元0 D_s0 → 0.6, 实际: {}", c.d_total);
    }

    /// 第193批（Claw审计 R1）: V8熵产率→V10 D_total 换算桥
    #[test]
    fn test_从熵产率换算() {
        // σ=0 → D_s替代=0 → D_total=(1-S)×0.6
        let r = 统一熵债计算器::从熵产率换算(1.0, 0.0, 1.0);
        assert!((r.d_total - 0.0).abs() < 1e-9, "σ=0 S=1 → 0, 实际: {}", r.d_total);
        // σ=阈值 → D_s替代=1.0 → D_total=(1-1)×0.6 + 1×0.4 = 0.4
        let r2 = 统一熵债计算器::从熵产率换算(1.0, 1.0, 1.0);
        assert!((r2.d_total - 0.4).abs() < 1e-9, "σ=阈值 S=1 → 0.4, 实际: {}", r2.d_total);
        // σ=2×阈值 → clamp 1.0
        let r3 = 统一熵债计算器::从熵产率换算(0.0, 2.0, 1.0);
        assert!((r3.d_total - 1.0).abs() < 1e-9, "σ=2阈值 S=0 → 1.0(clamp), 实际: {}", r3.d_total);
        // 阈值=0 防护
        let r4 = 统一熵债计算器::从熵产率换算(0.5, 0.1, 0.0);
        assert!(r4.d_total.is_finite(), "阈值0不应 panic/NaN");
    }
