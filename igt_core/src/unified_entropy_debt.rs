        assert!((r.结构对称度_s - 0.0).abs() < 1e-9);
        assert!((r.谱偏离度_d_s - 1.0).abs() < 1e-9);
        assert!((r.d_total - 1.0).abs() < 1e-9, "clamp 后 D_total=1.0, 实际: {}", r.d_total);
