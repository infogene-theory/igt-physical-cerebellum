/// 造波记录（审计: 时间戳/区域/温度/时长, D8 §7.3 强制）
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 造波记录 {
    pub 时间戳: f64, // 秒（epoch）
    pub 区域索引: usize,
    pub 方式: 造波方式,
    pub 温度: f64,
    pub 时长秒: f64,
    pub 面积cm2: f64,
}

/// 造波安全校验（D8 §7.3 工程强制护栏）——超限拒绝
pub fn 校验造波(
    方式: 造波方式,
    温度: f64,
    时长秒: f64,
    面积cm2: f64,
    护栏: &造波护栏参数,
) -> Result<(), String> {
    if 面积cm2 > 护栏.面积上限 {
        return Err(format!(
            "造波面积 {}cm² 超限（上限 {}cm²）——拒绝",
            面积cm2, 护栏.面积上限
        ));
    }
    match 方式 {
        造波方式::热敷 => {
            if 温度 > 护栏.热敷温度上限 {
                return Err(format!(
                    "热敷温度 {}°C 超限（上限 {}°C, 皮肤安全边界）——拒绝",
                    温度, 护栏.热敷温度上限
                ));
            }
            if 时长秒 > 护栏.热敷时长上限 {
                return Err(format!(
                    "热敷时长 {}s 超限（上限 {}s）——拒绝",
                    时长秒, 护栏.热敷时长上限
                ));
            }
        }
        造波方式::冷敷 => {
            if 温度 < 护栏.冷敷温度下限 {
                return Err(format!(
                    "冷敷温度 {}°C 低于下限（{}°C, 冻伤边界）——拒绝",
                    温度, 护栏.冷敷温度下限
                ));
            }
            if 时长秒 > 护栏.冷敷时长上限 {
                return Err(format!(
                    "冷敷时长 {}s 超限（上限 {}s）——拒绝",
                    时长秒, 护栏.冷敷时长上限
                ));
            }
        }
        造波方式::按压 => {
            // 按压不阻断血流——时长上限同冷敷（保守）
            if 时长秒 > 护栏.冷敷时长上限 {
                return Err(format!(
                    "按压时长 {}s 超限（上限 {}s, 不阻断血流）——拒绝",
                    时长秒, 护栏.冷敷时长上限
                ));
            }
        }
    }
    Ok(())
}

/// 模式检查（D8 §7.3: 仅校准场景启用主动造波, 日常监测禁用）
pub fn 允许主动造波(模式: 造波模式) -> bool {
    模式 == 造波模式::校准
}

