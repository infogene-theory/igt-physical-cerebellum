/// 区域空间邻接图（D8 §4.2 先验注入）——邻接 + 区域间距（cm）
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 区域邻接图 {
    /// 邻接矩阵: adj[i][j] = true 表示区域 i、j 解剖相邻
    pub 邻接: Vec<Vec<bool>>,
    /// 区域间距（cm, 用于扩散速度）
    pub 距离: Vec<Vec<f64>>,
}

/// 扩散方向
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum 扩散方向 {
    /// i → j（j 响应滞后 i）
    区域I到J,
    /// j → i（i 响应滞后 j）
    区域J到I,
    /// 同步（无显著延迟, 共同驱动）
    同步,
}

/// 扩散判定
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 扩散判定 {
    pub 区域i: usize,
    pub 区域j: usize,
    pub 方向: 扩散方向,
    /// 时间延迟（秒, 互相关峰值偏移·Δt; 同步为 0）
    pub 时间延迟: f64,
    /// 扩散速度（cm/min = 距离/延迟; 同步为 0）
    pub 扩散速度: f64,
    /// 峰值互相关（置信度）
    pub 置信度: f64,
    pub 描述: String,
}

/// 扩散分析——邻接区域对互相关延迟 → 扩散方向 + 速度
///
/// 慢速扩散（P30 判据: 分钟级）: 异常区域与邻近区域响应有时间延迟。
/// 方向由延迟符号给出（先变者 → 后变者）; 速度 = 距离/延迟。
pub fn 扩散分析(
    区域时序: &[Vec<f64>],
    邻接: &区域邻接图,
    Δt: f64,
) -> Vec<扩散判定> {
    let n = 区域时序.len().min(邻接.邻接.len());
    if n < 2 || Δt <= 0.0 {
        return Vec::new();
    }
    let 时序长 = 区域时序.first().map(|t| t.len()).unwrap_or(0);
    if 时序长 < 16 {
        return Vec::new();
    }
    let mut 判定 = Vec::new();
    for i in 0..n {
        for j in (i + 1)..n {
            if !邻接.邻接.get(i).and_then(|r| r.get(j)).copied().unwrap_or(false) {
                continue; // 邻接先验: 非解剖相邻区域不做扩散判定（V2）
            }
            let a = &区域时序[i];
            let b = &区域时序[j];
            // 互相关峰值延迟（lag 范围 ±10% 窗口）
            let 最大lag = (时序长 as f64 * 0.1) as usize;
            let mut 最佳lag = 0isize;
            let mut 最佳相关 = 0.0f64;
            let 范围 = -(最大lag as isize)..=最大lag as isize;
            for lag in 范围 {
                let 相关 = 互相关延迟(a, b, lag);
                if 相关 > 最佳相关 {
                    最佳相关 = 相关;
                    最佳lag = lag;
                }
            }
            let 方向 = if 最佳lag.abs() <= 1 {
                扩散方向::同步
            } else if 最佳lag > 0 {
                扩散方向::区域I到J // a 先, b 滞后 → i→j
            } else {
                扩散方向::区域J到I
            };
            let 时间延迟 = 最佳lag.abs() as f64 * Δt;
            let 距离 = 邻接.距离.get(i).and_then(|r| r.get(j)).copied().unwrap_or(0.0);
            let 扩散速度 = if 时间延迟 > 1e-9 && 距离 > 0.0 {
                距离 / (时间延迟 / 60.0) // cm/min
            } else {
                0.0
            };
            let 描述 = format!(
                "区域{}→{}: 延迟 {:.2}s, 速度 {:.2}cm/min, 相关 {:.2}",
                i,
                j,
                时间延迟,
                扩散速度,
                最佳相关
            );
            判定.push(扩散判定 {
                区域i: i,
                区域j: j,
                方向,
                时间延迟,
                扩散速度,
                置信度: 最佳相关.clamp(0.0, 1.0),
                描述,
            });
        }
    }
    判定
}

/// 互相关延迟——序列 b 相对 a 偏移 lag 的皮尔逊相关（lag>0: b 滞后 a）
fn 互相关延迟(a: &[f64], b: &[f64], lag: isize) -> f64 {
    let n = a.len();
    let 起点 = if lag >= 0 { 0 } else { (-lag) as usize };
    let 终点 = if lag >= 0 { n - lag as usize } else { n };
    if 终点 <= 起点 || 终点 - 起点 < 4 {
        return -1.0;
    }
    let 段a = &a[起点..终点];
    let 段b = &b[(起点 as isize + lag) as usize..(终点 as isize + lag) as usize];
    let 均值a = 段a.iter().sum::<f64>() / 段a.len() as f64;
    let 均值b = 段b.iter().sum::<f64>() / 段b.len() as f64;
    let 协 = 段a
        .iter()
        .zip(段b.iter())
        .map(|(x, y)| (x - 均值a) * (y - 均值b))
        .sum::<f64>();
    let 方差a = 段a.iter().map(|x| (x - 均值a).powi(2)).sum::<f64>();
    let 方差b = 段b.iter().map(|x| (x - 均值b).powi(2)).sum::<f64>();
    if 方差a <= 1e-12 || 方差b <= 1e-12 {
        return -1.0;
    }
    (协 / (方差a * 方差b).sqrt()).clamp(-1.0, 1.0)
}

