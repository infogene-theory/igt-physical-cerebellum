/// 区域聚合——像素掩膜 → 区域平均温度时序
///
/// - `帧序列`: 每帧 `Vec<f64>` 为全部像素温度（帧长一致）
/// - `掩膜`: 每区域的有效像素索引列表（`掩膜[r]` = 区域 r 的像素索引）
/// - `背景温度`: 有效像素排除（与背景差 < ±2°C 视为背景）
///
/// 返回: 每区域温度时序（每区域长度 = 帧数; 无有效像素的区域该帧用全局均值插值）
pub fn 区域聚合(
    帧序列: &[Vec<f64>],
    掩膜: &[Vec<usize>],
    背景温度: Option<f64>,
) -> Option<Vec<Vec<f64>>> {
    if 帧序列.is_empty() || 掩膜.is_empty() {
        return None;
    }
    let 帧长 = 帧序列[0].len();
    if 帧序列.iter().any(|f| f.len() != 帧长) {
        return None;
    }
    let mut 区域时序 = vec![Vec::with_capacity(帧序列.len()); 掩膜.len()];
    for 帧 in 帧序列 {
        let 全局均值: f64 = 帧.iter().sum::<f64>() / 帧长 as f64;
        for (r, 像素) in 掩膜.iter().enumerate() {
            let mut 和 = 0.0;
            let mut 数 = 0usize;
            for &p in 像素 {
                if p >= 帧长 {
                    continue;
                }
                let 有效 = match 背景温度 {
                    Some(bg) => (帧[p] - bg).abs() >= 2.0, // 排除背景（±2°C 内）
                    None => true,
                };
                if 有效 {
                    和 += 帧[p];
                    数 += 1;
                }
            }
            区域时序[r].push(if 数 > 0 { 和 / 数 as f64 } else { 全局均值 });
        }
    }
    Some(区域时序)
}

// ============================================================================
// 区域主导 τ（解析信号包络 log-linear 回归）
// ============================================================================

/// 区域主导 τ——解析信号包络 log|z(t)| 线性回归斜率 → τ = -1/斜率
///
/// 依据: 衰减模 |z(t)| = |c|·e^{-t/τ} → ln|z| = ln|c| - t/τ（D7 精度边界 <15%）
pub fn 区域主导τ(时序: &[f64], Δt: f64) -> Option<f64> {
    if 时序.len() < 20 || Δt <= 0.0 {
        return None;
    }
    // 去 DC 基线（对齐 D7: 全序列均值被前段主导 → 中段残留; 中段均值 → z DC≈0）
    let 边界 = (时序.len() / 10).max(2); // Hilbert 边界伪影（对齐 D7）
    let 中段均值 = 时序[边界..时序.len() - 边界].iter().sum::<f64>()
        / (时序.len() - 2 * 边界) as f64;
    let 去均值: Vec<f64> = 时序.iter().map(|x| x - 中段均值).collect();
    let z = 解析信号(&去均值);
    let 幅值列表: Vec<(f64, f64)> = (边界..时序.len() - 边界)
        .map(|k| {
            let a = (z[k].re * z[k].re + z[k].im * z[k].im).sqrt();
            (k as f64 * Δt, a)
        })
        .collect();
    let 峰值 = 幅值列表.iter().map(|p| p.1).fold(0.0f64, f64::max);
    // 幅值阈值截断（对齐 D7 0.05·峰值）: 衰减尾段幅值 <5% 峰值后噪声主导 log 回归 → τ 高估
    let mut 点: Vec<(f64, f64)> = 幅值列表
        .iter()
        .filter(|p| p.1 > (峰值 * 0.05).max(1e-9))
        .map(|p| (p.0, p.1.ln()))
        .collect();
    if 点.len() < 8 {
        return None;
    }
    // 最小二乘线性回归 y = a + b·x, τ = -1/b（b < 0 衰减）
    let n = 点.len() as f64;
    let x̄ = 点.iter().map(|p| p.0).sum::<f64>() / n;
    let ȳ = 点.iter().map(|p| p.1).sum::<f64>() / n;
    let 分子 = 点.iter().map(|p| (p.0 - x̄) * (p.1 - ȳ)).sum::<f64>();
    let 分母 = 点.iter().map(|p| (p.0 - x̄).powi(2)).sum::<f64>();
    if 分母.abs() < 1e-12 {
        return None;
    }
    let b = 分子 / 分母;
    if b >= 0.0 {
        return None; // 非衰减 → 无物理 τ
    }
    let τ = -1.0 / b;
    if τ.is_finite() && τ > 0.0 {
        Some(τ)
    } else {
        None
    }
}

