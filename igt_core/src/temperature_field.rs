/// 异常类型（P30 判定）
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum 异常类型 {
    /// 病灶点: τ 变短（代谢活跃、回归快——炎症/感染/富血供）
    病灶点,
    /// 堵点: τ 变长（传导受阻、回归慢——狭窄/血栓/淋巴障碍）
    堵点,
    /// 急性损伤: 高度局域化 + 中心-梯度 + 秒级出现
    急性损伤,
    /// 环境干扰: 全身同步（不报警）
    环境干扰,
}

impl std::fmt::Display for 异常类型 {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let s = match self {
            异常类型::病灶点 => "病灶点(τ变短)",
            异常类型::堵点 => "堵点(τ变长)",
            异常类型::急性损伤 => "急性损伤(高度局域)",
            异常类型::环境干扰 => "环境干扰(全身同步)",
        };
        write!(f, "{}", s)
    }
}

