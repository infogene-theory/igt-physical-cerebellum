/// 温度场分析输入
pub struct 温度场分析输入<'a> {
    /// 区域温度时序（每区域等长）
    pub 区域时序: &'a [Vec<f64>],
    /// 每区域基准 τ（个人基准/常模, 秒）
    pub 基准τ: &'a [f64],
    /// 每区域面积占比（和≈1）
    pub 面积比: &'a [f64],
    /// 采样间隔（秒）
    pub Δt: f64,
    /// 异常偏离阈值（默认 0.15, 对齐 D7 精度边界）
    pub 偏离阈值: Option<f64>,
}

/// 温度场时空分析——区域 τ 对照基准 → 异常 → 时空判据 → 异常类型
pub fn 温度场分析(输入: &温度场分析输入) -> 温度场时空结果 {
    let 阈值 = 输入.偏离阈值.unwrap_or(0.15);
    let n_区域 = 输入.区域时序.len();
    let 时序长 = 输入.区域时序.first().map(|t| t.len()).unwrap_or(0);

    // 1. 每区域主导 τ
    let mut 观测τ: Vec<Option<f64>> = Vec::with_capacity(n_区域);
    for 时序 in 输入.区域时序 {
        观测τ.push(区域主导τ(时序, 输入.Δt));
    }

    // 2. 异常区域（|偏离| > 阈值 → 短/长）
    let mut 异常区域 = Vec::new();
    let mut 异常面积 = 0.0;
    for i in 0..n_区域 {
        let Some(τ) = 观测τ[i] else { continue };
        let 基准 = 输入.基准τ.get(i).copied().unwrap_or(0.0);
        if 基准 <= 0.0 {
            continue;
        }
        let 偏离率 = (τ - 基准) / 基准;
        if 偏离率.abs() < 阈值 {
            continue;
        }
        let 面积 = 输入.面积比.get(i).copied().unwrap_or(1.0 / n_区域 as f64).max(0.0);
        异常面积 += 面积;
        异常区域.push(区域异常 {
            区域索引: i,
            观测τ: τ,
            基准τ: 基准,
            偏离率,
            方向: if 偏离率 < 0.0 { "短" } else { "长" }.to_string(),
            置信度: (偏离率.abs() / (阈值 * 2.0)).clamp(0.0, 1.0),
        });
    }

    // 3. 局域化程度 = 异常面积比（P30 <5%）
    let 局域化程度 = 异常面积;

    // 4. 同步性 = 异常区域 vs 正常区域 温度互相关（P30 <0.3 局域）
    let 同步性 = 温度互相关(输入.区域时序, &异常区域);

    // 5. 异常类型（P30 §5.2）: 环境干扰(全身同步>0.8) > 急性损伤(高度局域+τ短) > 病灶/堵点
    let 异常类型 = if 异常区域.is_empty() {
        异常类型::环境干扰 // 无异常区域 → 标记环境（不报警语义: 调用方按 局域化=0 处理）
    } else if 同步性 > 0.8 {
        异常类型::环境干扰
    } else if 局域化程度 < 0.05 && 异常区域.iter().any(|a| a.方向 == "短") {
        异常类型::急性损伤
    } else if 异常区域.iter().all(|a| a.方向 == "短") {
        异常类型::病灶点
    } else if 异常区域.iter().all(|a| a.方向 == "长") {
        异常类型::堵点
    } else {
        // 混合方向 → 病灶点优先（回归快侧主导）
        异常类型::病灶点
    };

    // 空间梯度（异常区 vs 全局平均温差, 简化: 最后帧）
    let 空间梯度: Vec<f64> = if 时序长 > 0 {
        let 末帧均值: Vec<f64> = (0..n_区域)
            .map(|i| {
                let t = &输入.区域时序[i];
                if t.is_empty() { 0.0 } else { *t.last().unwrap() }
            })
            .collect();
        let 全局 = if 末帧均值.is_empty() { 0.0 } else { 末帧均值.iter().sum::<f64>() / 末帧均值.len() as f64 };
        异常区域.iter().map(|a| 末帧均值[a.区域索引] - 全局).collect()
    } else {
        Vec::new()
    };

    let 说明 = format!(
        "温度场时空分析: 异常{}区域, 局域化={:.3}, 同步性={:.2}, 判定={}",
        异常区域.len(),
        局域化程度,
        同步性,
        异常类型
    );

    温度场时空结果 {
        异常区域,
        局域化程度,
        空间梯度,
        扩散速度: 0.0, // κ 时间延迟接入后填充（V2）
        同步性,
        异常类型,
        说明,
    }
}

/// 异常区域 vs 正常区域 温度互相关（皮尔逊, 滑动窗口）
fn 温度互相关(区域时序: &[Vec<f64>], 异常区域: &[区域异常]) -> f64 {
    let 异常索引: std::collections::HashSet<usize> =
        异常区域.iter().map(|a| a.区域索引).collect();
    let 正常索引: Vec<usize> = (0..区域时序.len())
        .filter(|i| !异常索引.contains(i))
        .collect();
    if 异常区域.is_empty() || 正常索引.is_empty() {
        return 0.0; // 无异常/无正常对照
    }
    let 时序长 = 区域时序.first().map(|t| t.len()).unwrap_or(0);
    if 时序长 < 4 {
        return 0.0;
    }
    // 异常区域平均温度序列
    let 异常均值: Vec<f64> = (0..时序长)
        .map(|k| {
            let 和: f64 = 异常区域
                .iter()
                .map(|a| 区域时序[a.区域索引][k])
                .sum();
            和 / 异常区域.len() as f64
        })
        .collect();
    // 每正常区域与异常均值相关, 取最大（全身同步时任一正常区相关高）
    let mut 最大相关 = 0.0f64;
    for &j in &正常索引 {
        let 正常均值: Vec<f64> = (0..时序长).map(|k| 区域时序[j][k]).collect();
        let r = 皮尔逊(&异常均值, &正常均值);
        最大相关 = 最大相关.max(r);
    }
    最大相关
}

/// 皮尔逊相关系数
fn 皮尔逊(a: &[f64], b: &[f64]) -> f64 {
    let n = a.len().min(b.len());
    if n < 3 {
        return 0.0;
    }
    let 均值a = a[..n].iter().sum::<f64>() / n as f64;
    let 均值b = b[..n].iter().sum::<f64>() / n as f64;
    let 协 = (0..n).map(|i| (a[i] - 均值a) * (b[i] - 均值b)).sum::<f64>();
    let 方差a = (0..n).map(|i| (a[i] - 均值a).powi(2)).sum::<f64>();
    let 方差b = (0..n).map(|i| (b[i] - 均值b).powi(2)).sum::<f64>();
    if 方差a <= 1e-12 || 方差b <= 1e-12 {
        return 0.0;
    }
    (协 / (方差a * 方差b).sqrt()).clamp(-1.0, 1.0)
}

