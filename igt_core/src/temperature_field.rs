//! 温度场时空模块（D8, 2026-08-24, P29/P30 医学热成像 τ 谱方法工程化）
//!
//! 核心思想（P29）: 观测维度切换——从"静态温度值"（信噪比 20-30%）切换到
//! "动态弛豫时间 τ"（本征属性, 信噪比 >85%）。数学基础 dΔT/dt = -LΔT 与 core
//! 非厄米谱框架同构。
//!
//! 混合降维（D8 §3, 理论已确认）:
//! - 区域通道层: ~20 解剖区域平均温度时序 → 复EDMD（跨模态耦合/τ 谱）
//! - 像素级后处理层: 对 τ 异常区域做局域化检测（面积<5%）/空间梯度/同步性
//!
//! 本模块实现:
//! - `区域聚合`: 像素掩膜 → 区域平均温度时序（排除背景/边缘伪影）
//! - `区域主导τ`: 单区域时序 → 解析信号包络 log-linear 回归 → τ（D7 精度边界 <15%）
//! - `温度场分析`: 区域 τ 对照基准 → 异常区域 → 时空判据（局域化/同步性/扩散）
//!   → 异常类型（病灶点 τ短 / 堵点 τ长 / 急性损伤 / 环境干扰）
//!
//! 依据: P29（方法学）/ P30（病灶/堵点/急性损伤 三判据）/ D7（τ 精度）/ D5+D6（机制）。

