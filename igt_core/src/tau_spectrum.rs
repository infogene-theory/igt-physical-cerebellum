//! 本征 τ 谱——准闭合系统识别两步法·第二步（B3+B4）
//!
//! 依据: 《群论与黎曼谱：准闭合系统识别的两步法工程实现 v1.0》§第二步
//! - 本征 τ 谱提取: 从系统内禀涨落序列提取所有本征弛豫模式
//! - 输出按弛豫时间从长到短排序的本征 τ 序列 + 模态强度
//! - τ₀ 标定: 基准 τ₀ = 强度最高、弛豫时间最长的主 τ 峰
//! - τ 间距分布: 相邻 τ 的对数间距统计（蒸馏流水线 A 动力学编码特征）
//! - 多尺度 τ 峰分组: 长τ(核心节律)/中τ/短τ(子节律) 层级——应用层
//!   "τ峰错位"检测 + 蒸馏 A4 层级嵌套拆解的原料
//!
//! 底层复用: `relaxation_spectrum::从时序提取`（STFT → 峰值检测 → 合并去重），
//! 本模块做衰减系数 → 弛豫时间映射 + τ 排序 + 统计 + 层级分组。
//!
//! ARCH-1 v1.2 §9（谱链 ω/γ 维度分离约定, 宪法级）:
//!   - **τ = 1/衰减系数σ = 1/γ（秒）≠ 1/f**（1/f 是振荡周期——慢振荡可快衰减, 两维独立）
//!   - ω（振荡频率维度）与 γ（耗散率维度）两维独立测量: 本模块 τ 只表征耗散维度
//!   - **历史标注**: 本模块 2026-08-28 前存在 τ=1/f 违例（理论侧【续14】违例1）, 已修正为 τ=1/σ

#![allow(non_snake_case)]

use serde::{Deserialize, Serialize};

use crate::relaxation_spectrum::{弛豫频谱, STFT配置, 从时序提取};

/// 单个本征 τ 分量
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct τ分量 {
    /// 弛豫时间 τ = 1/衰减系数σ（秒）——ARCH-1 v1.2 §9.1: **τ=1/γ≠1/f**（1/f 是振荡周期）
    pub 弛豫时间: f64,
    /// 模态强度（归一化振幅 [0,1]）
    pub 强度: f64,
    /// 振荡频率 f (Hz)——ω 维度（与 γ 耗散维度独立, 同ω共振取本字段）
    pub 频率: f64,
    /// 衰减系数 σ/γ (1/s)——耗散维度（τ 的唯一决定量）
    pub 衰减系数: f64,
}

/// τ 间距分布统计——相邻本征 τ 的对数间距特征
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct τ间距统计 {
    /// 对数间距均值 <ln(τ_{i+1}/τ_i)>
    pub 对数间距均值: f64,
    /// 对数间距标准差（间距分布集中度——谱规律性指标）
    pub 对数间距标准差: f64,
    /// 间距样本数
    pub 间距数: usize,
}

/// 多尺度 τ 峰层级——长/中/短分组
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct τ层级分组 {
    /// 层级标签
    pub 层级: String,
    /// 组内 τ 范围 [最小, 最大]
    pub τ范围: (f64, f64),
    /// 组中心 τ（几何平均）
    pub 中心τ: f64,
    /// 组内峰值强度（最大振幅）
    pub 峰值强度: f64,
}

/// 本征 τ 谱——B3 输出
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 本征τ谱 {
    /// 本征 τ 分量（按弛豫时间从长到短排序）
    pub τ分量列表: Vec<τ分量>,
    /// τ 峰数量（独立本征弛豫模式数）
    pub τ峰数: usize,
    /// 基准 τ₀（B4: 强度最高且弛豫最长的主峰）
    pub τ0: f64,
    /// τ₀ 对应强度
    pub τ0强度: f64,
    /// τ 间距分布统计
    pub τ间距: τ间距统计,
    /// 多尺度 τ 峰层级分组（长/中/短）
    pub 多尺度分组: Vec<τ层级分组>,
}

/// 多尺度分组的边界（对数等分 3 层: 长/中/短）
pub const 层级标签: [&str; 3] = ["长τ(核心节律)", "中τ", "短τ(子节律)"];

impl 本征τ谱 {
    /// 从时序提取本征 τ 谱（B3 + B4 一站式）
    ///
    /// 流程: STFT(relaxation) → 频率→τ 映射 → τ 降序排序 → τ₀ 标定 →
    ///       τ 间距统计 → 多尺度分组
    pub fn 从时序提取(信号: &[f64], 配置: &STFT配置) -> 本征τ谱 {
        let 频谱: 弛豫频谱 = 从时序提取(信号, 配置);

        // 1. 衰减系数 → 弛豫时间（τ = 1/σ, ARCH-1 v1.2 §9.1 τ=1/γ≠1/f）
        //    T-21a 修复: 原 τ=1/f 违例（理论侧【续14】违例1）——σ 数据 relaxation 已按
        //    A(t+Δt)=A·e^{−σΔt} 独立测得（L196-205 先例）, 本处改映射即可
        //    过滤: σ>1e-9（σ 非正=无衰减信息不可给 τ, 防除零）; 频率过滤保留
        //    （relaxation 峰值检测的 DC 抑制语义——τ分量.频率 继续供 ω 维度使用）
        let mut 分量: Vec<τ分量> = 频谱
            .分量列表
            .iter()
            .filter(|c| c.频率 > 1e-9 && c.衰减系数 > 1e-9)
            .map(|c| τ分量 {
                弛豫时间: 1.0 / c.衰减系数,
                强度: c.振幅,
                频率: c.频率,
                衰减系数: c.衰减系数,
            })
            .collect();

        // 2. τ 降序排序（长 → 短）
        分量.sort_by(|a, b| {
            b.弛豫时间
                .partial_cmp(&a.弛豫时间)
                .unwrap_or(std::cmp::Ordering::Equal)
        });

        // 3. τ₀ 标定（B4）——强度最高且弛豫时间最长的主峰（弛豫=1/σ 语义, ARCH-1 v1.2 §9.1）
        //    规则: 取强度最高的峰；若存在强度 ≥ 最高强度 60% 且 τ 更长的峰，取更长的
        let (τ0, τ0强度) = Self::标定τ0(&分量);

        // 4. τ 间距分布统计
        let τ间距 = Self::τ间距分布(&分量);

        // 5. 多尺度分组
        let 多尺度分组 = Self::多尺度τ分组(&分量);

        本征τ谱 {
            τ分量列表: 分量,
            τ峰数: 频谱.独立成分数,
            τ0,
            τ0强度,
            τ间距,
            多尺度分组,
        }
    }

    /// τ₀ 标定——强度最高且弛豫时间最长的主 τ 峰
    ///
    /// 规则（文档: "强度最高、弛豫时间最长的主 τ 峰"）:
    /// - 基础: 强度最大的峰
    /// - 修正: 若存在强度 ≥ 最大强度×0.6 且 τ ≥ 基础τ₀ 的峰，取其中最长的
    ///   （核心节律通常强度高且慢——如昼夜节律 24h 是代谢谱的最长强峰）
    pub fn 标定τ0(分量: &[τ分量]) -> (f64, f64) {
        if 分量.is_empty() {
            return (0.0, 0.0);
        }
        let 最大强度 = 分量
            .iter()
            .map(|c| c.强度)
            .fold(f64::MIN, f64::max);
        let 基础 = 分量
            .iter()
            .filter(|c| (c.强度 - 最大强度).abs() < 1e-12)
            .next()
            .copied()
            .unwrap_or(分量[0]);

        // 寻找强度足够（≥60% 最大）且弛豫最长的峰
        let 候选: Vec<&τ分量> = 分量
            .iter()
            .filter(|c| c.强度 >= 最大强度 * 0.6 && c.弛豫时间 >= 基础.弛豫时间)
            .collect();
        if let Some(最长) = 候选.first() {
            (最长.弛豫时间, 最长.强度)
        } else {
            (基础.弛豫时间, 基础.强度)
        }
    }

    /// τ 间距分布——相邻 τ 的对数间距 <ln(τ_{i+1}/τ_i)>
    pub fn τ间距分布(分量: &[τ分量]) -> τ间距统计 {
        if 分量.len() < 2 {
            return τ间距统计 {
                对数间距均值: 0.0,
                对数间距标准差: 0.0,
                间距数: 0,
            };
        }
        let mut 对数间距 = Vec::with_capacity(分量.len() - 1);
        for i in 0..分量.len() - 1 {
            // 分量已按 τ 降序，τ_i ≥ τ_{i+1}，比值 ≥ 1
            let 比值 = 分量[i].弛豫时间 / 分量[i + 1].弛豫时间;
            if 比值 > 1e-9 {
                对数间距.push(比值.ln());
            }
        }
        if 对数间距.is_empty() {
            return τ间距统计 {
                对数间距均值: 0.0,
                对数间距标准差: 0.0,
                间距数: 0,
            };
        }
        let 均值 = 对数间距.iter().sum::<f64>() / 对数间距.len() as f64;
        let 方差 = 对数间距
            .iter()
            .map(|x| (x - 均值) * (x - 均值))
            .sum::<f64>()
            / 对数间距.len() as f64;
        τ间距统计 {
            对数间距均值: 均值,
            对数间距标准差: 方差.sqrt(),
            间距数: 对数间距.len(),
        }
    }

    /// 多尺度 τ 分组——对数等分 3 层（长/中/短）
    ///
    /// 文档: 长 τ 峰对应核心基因节律，短 τ 峰对应子基因节律。
    /// 用于应用层"τ峰错位"检测（短τ无序扰动长τ）与蒸馏 A4 层级嵌套拆解。
    pub fn 多尺度τ分组(分量: &[τ分量]) -> Vec<τ层级分组> {
        if 分量.is_empty() {
            return Vec::new();
        }
        let 最大τ = 分量.first().map(|c| c.弛豫时间).unwrap_or(1.0);
        let 最小τ = 分量.last().map(|c| c.弛豫时间).unwrap_or(1.0);
        if 最小τ <= 0.0 || 最大τ <= 最小τ {
            return Vec::new();
        }
        // 对数等分 3 个内部分割点（从长τ到短τ——与 τ分量列表 降序一致）
        let log_min = 最小τ.ln();
        let log_max = 最大τ.ln();
        let 步长 = (log_max - log_min) / 3.0;
        // 分割点: 边界[0] > 边界[1] > 边界[2]（τ 降序）
        let 边界: Vec<f64> = (1..=3).map(|i| (log_max - 步长 * i as f64).exp()).collect();

        // 分层范围（边缘组开放边界, 避免浮点边界遗漏端点 τ）
        let 范围: [(f64, f64); 3] = [
            (边界[0], f64::MAX),        // 长τ(核心节律): (b0, ∞)
            (边界[1], 边界[0]),         // 中τ: (b1, b0]
            (0.0, 边界[1]),            // 短τ(子节律): (0, b1]
        ];

        (0..3)
            .map(|层| {
                let (lo, hi) = 范围[层];
                let 组内: Vec<&τ分量> = 分量
                    .iter()
                    .filter(|c| c.弛豫时间 >= lo && c.弛豫时间 <= hi)
                    .collect();
                if 组内.is_empty() {
                    τ层级分组 {
                        层级: 层级标签[层].to_string(),
                        τ范围: (lo, hi),
                        中心τ: (lo * hi).sqrt(),
                        峰值强度: 0.0,
                    }
                } else {
                    let 中心τ = 组内
                        .iter()
                        .map(|c| c.弛豫时间.ln())
                        .sum::<f64>()
                        / 组内.len() as f64;
                    let 峰值强度 = 组内.iter().map(|c| c.强度).fold(f64::MIN, f64::max);
                    τ层级分组 {
                        层级: 层级标签[层].to_string(),
                        τ范围: (lo, hi),
                        中心τ: 中心τ.exp(),
                        峰值强度,
                    }
                }
            })
            .collect()
    }
}

