    /// τ₀ 标定规则——强度最高且弛豫最长（构造合成数据直接测标定函数）
    #[test]
    fn test_τ0标定规则() {
        // 构造: 强短峰 + 弱长峰（长峰强度=强峰60%，应选长峰）
        let 分量 = vec![
            τ分量 { 弛豫时间: 100.0, 强度: 0.6, 频率: 0.01, 衰减系数: 0.01 },
            τ分量 { 弛豫时间: 10.0, 强度: 0.9, 频率: 0.1, 衰减系数: 0.1 },
        ];
        let (τ0, 强度) = 本征τ谱::标定τ0(&分量);
        assert_eq!(τ0, 100.0, "长峰强度≥60%应被选为主峰");
        assert_eq!(强度, 0.6);

        // 短峰强度不足（<60%）→ 选强度最高的短峰
        let 分量2 = vec![
            τ分量 { 弛豫时间: 100.0, 强度: 0.3, 频率: 0.01, 衰减系数: 0.01 },
            τ分量 { 弛豫时间: 10.0, 强度: 0.9, 频率: 0.1, 衰减系数: 0.1 },
        ];
        let (τ0_2, _) = 本征τ谱::标定τ0(&分量2);
        assert_eq!(τ0_2, 10.0, "长峰强度不足60%应选强度最高的峰");
    }

    /// [T-21a] 数值断言: 合成已知 (f₀, σ₀) 阻尼振荡 → τ≈1/σ₀（非 1/f₀）+ 频率≈f₀
    /// 物理正确性锁定（派发单阶段四.1）: τ=1/γ 与 ω 两维独立——慢振荡可快衰减
    #[test]
    fn test_T21a_τ等于1除σ而非1除f() {
        let 采样率 = 10.0; // 10Hz 采样
        let f0 = 0.5; // 0.5Hz 振荡（τ_true=1/f₀=2s, 若用旧违例语义 τ 将取 2s）
        let σ0 = 0.05; // 衰减率 0.05 1/s → τ_true=1/σ₀=20s
        let n = 4000; // 400s 信号
        let 信号: Vec<f64> = (0..n)
            .map(|i| {
                let t = i as f64 / 采样率;
                (-σ0 * t).exp() * (2.0 * std::f64::consts::PI * f0 * t).sin()
            })
            .collect();
        let 谱 = 本征τ谱::从时序提取(&信号, &测试配置(采样率, 256));
        assert!(谱.τ峰数 >= 1);
        let 主 = 谱
            .τ分量列表
            .iter()
            .max_by(|a, b| a.强度.partial_cmp(&b.强度).unwrap())
            .unwrap();
        // τ 应接近 1/σ₀=20s（半高宽法估计有偏差, 容差放宽）——而非 1/f₀=2s
        assert!(
            (主.弛豫时间 - 20.0).abs() < 15.0,
            "τ≈1/σ₀=20s, 实际: {}",
            主.弛豫时间
        );
        assert!(主.弛豫时间 > 5.0, "τ 应远离 1/f₀=2s（旧 τ=1/f 违例语义）");
        // 频率应接近 f₀（ω 维度独立保留）
        assert!((主.频率 - f0).abs() < 0.3, "频率≈f₀=0.5Hz, 实际: {}", 主.频率);
    }

