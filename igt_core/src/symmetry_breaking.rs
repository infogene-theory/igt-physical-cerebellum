/// 破缺判据 — P13 §6.1-6.3 + P39 §3（T-7 升级: P39 三相 + 层级化）
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum 破缺判据 {
    /// P39 独立模相: κ<κ_EP, 两模分离, 对称态
    独立相,
    /// P39 临界预警: κ≈κ_EP（margin<10%κ_EP）, 临界慢化
    临界预警,
    /// P39 τ分裂相: κ>κ_EP, 一长τ一短τ, 对称破缺
    τ分裂相,
    /// 多层谱隙（相邻层 τ 差一个数量级以上, P13 §5.3）
    层级化,
}

impl 破缺判据 {
    pub fn 名称(&self) -> &'static str {
        match self {
            破缺判据::独立相 => "独立相",
            破缺判据::临界预警 => "临界预警",
            破缺判据::τ分裂相 => "τ分裂相",
            破缺判据::层级化 => "层级化",
        }
    }
}

/// τ 谱分组（层级）
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct τ组 {
    /// 组内模索引
    pub 模索引: Vec<usize>,
    /// 组特征 τ（几何均值）
    pub τ均值: f64,
}

/// 对称破缺检测结果
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 对称破缺结果 {
    /// 谱隙 Δ（sorted τ 最大相邻相对 gap）
    pub 谱隙_Δ: f64,
    /// τ 谱简并度（CV=std/mean, 简并→小, 分裂→大）
    pub τ谱简并度: f64,
    /// 检测到的 τ 层级分组
    pub τ谱分组: Vec<τ组>,
    /// 戈德斯通模式（破缺后短τ模式索引集合）
    pub 戈德斯通模式: Vec<usize>,
    /// 破缺判据
    pub 破缺判据: 破缺判据,
    /// P39 G-11: 每对模 κ_EP^(ij)=½√[(Δω)²+(Δγ)²]（T-7 新增）
    pub κ_EP_临界值: Vec<Vec<f64>>,
    /// P39 G-11: 临界裕度 margin^(ij)=κ_EP^(ij)-κ_ij（T-7 新增）
    pub 临界裕度: Vec<Vec<f64>>,
    /// P39 G-11: 恢复时间估计 τ_rec∝1/|κ-κ_EP|^{1/2}（T-7 新增, EP 临界慢化）
    pub 恢复时间估计: Vec<Vec<f64>>,
    /// P39 G-11: 物理推论——同频同耗散模最敏感（Δω=Δγ=0 → κ_EP=0）, 多样性是稳定性来源（T-7 新增）
    pub 最敏感模对: Option<(usize, usize)>,
    /// 谱信息充足（D1 联动: 对角近似时不足, 不静默判定）
    pub 谱信息充足: bool,
    /// 说明
    pub 说明: String,
}

/// 对称破缺检测器（现象检测, P13）
pub struct 对称破缺检测器 {
    /// 谱隙显著性阈值（相对平均 τ 的 gap 占比）
    pub 谱隙阈值: f64,
    /// 层级判据: 相邻层 τ 倍数
    pub 层级倍数: f64,
}

impl Default for 对称破缺检测器 {
    fn default() -> Self {
        Self { 谱隙阈值: 0.5, 层级倍数: 10.0 }
    }
}

impl 对称破缺检测器 {
    /// 对称破缺检测入口
    /// `l_非对角显著`: D1 依赖联动——复L 非对角是否显著（对角近似 → false → 谱信息不足）
    pub fn 检测(&self, l_非对角显著: bool, 分解: &非厄米谱分解) -> 对称破缺结果 {
    let 谱信息充足 = l_非对角显著;
    // 稳定模 τ 收集（γ<0 → τ>0 有限）
    let mut 模: Vec<(usize, f64)> = 分解
        .模
        .iter()
        .enumerate()
        .filter(|(_, m)| m.τ.is_finite() && m.τ > 0.0)
        .map(|(i, m)| (i, m.τ))
        .collect();
    模.sort_by(|a, b| a.1.partial_cmp(&b.1).unwrap_or(std::cmp::Ordering::Equal));

    let 说明;
    if !谱信息充足 {
        说明 = "谱信息不足（D1 未修复态: 对角近似复L 给虚假本征值）——不静默判定破缺".to_string();
        return 对称破缺结果 {
            谱隙_Δ: 0.0,
            τ谱简并度: f64::NAN,
            τ谱分组: vec![],
            戈德斯通模式: vec![],
            破缺判据: 破缺判据::独立相,
            κ_EP_临界值: vec![],
            临界裕度: vec![],
            恢复时间估计: vec![],
            最敏感模对: None,
            谱信息充足: false,
            说明,
        };
    }
    if 模.len() < 2 {
        说明 = "稳定模不足2, 无法判定谱隙".to_string();
        return 对称破缺结果 {
            谱隙_Δ: 0.0,
            τ谱简并度: f64::NAN,
            τ谱分组: vec![],
            戈德斯通模式: vec![],
            破缺判据: 破缺判据::独立相,
            κ_EP_临界值: vec![],
            临界裕度: vec![],
            恢复时间估计: vec![],
            最敏感模对: None,
            谱信息充足: true,
            说明,
        };
    }

    // τ 谱简并度（CV）
    let 均值 = 模.iter().map(|(_, t)| *t).sum::<f64>() / 模.len() as f64;
    let 方差 = 模.iter().map(|(_, t)| (t - 均值) * (t - 均值)).sum::<f64>() / 模.len() as f64;
    let 简并度 = 方差.sqrt() / 均值.max(1e-12);

    // 谱隙 Δ: sorted τ 最大相邻相对 gap
    let mut 最大gap = 0.0f64;
    for w in 模.windows(2) {
        let gap = (w[1].1 - w[0].1) / w[0].1.max(1e-12);
        if gap > 最大gap {
            最大gap = gap;
        }
    }
    let Δ = 最大gap;

    // τ 层级分组（log10 聚类: 相邻差 ≥ 层级倍数 → 分层）
    let mut 分组: Vec<τ组> = Vec::new();
    for &(i, t) in 模.iter() {
        let 所属 = 分组.iter_mut().find(|g| {
            let 比值 = (t / g.τ均值.max(1e-12)).max(g.τ均值 / t.max(1e-12));
            比值 < self.层级倍数
        });
        match 所属 {
            Some(g) => {
                g.模索引.push(i);
                // 几何均值更新
                let lg = g.模索引.len() as f64;
                let 和对数: f64 = g.模索引.iter().map(|&x| 分解.模[x].τ.ln()).sum();
                g.τ均值 = (和对数 / lg).exp();
            }
            None => {
                分组.push(τ组 { 模索引: vec![i], τ均值: t });
            }
        }
    }

    // 破缺判据（P39 三相映射: 现象检测阶段简并→独立相, 破缺→τ分裂相）
    let 判据 = if 分组.len() >= 3 && Δ > self.谱隙阈值 {
        破缺判据::层级化
    } else if Δ > self.谱隙阈值 && 简并度 > 0.5 {
        破缺判据::τ分裂相
    } else {
        破缺判据::独立相
    };

    // 戈德斯通模式: 最短 τ 组（破缺后短τ激发模式）
    let 最短组 = 分组.iter().min_by(|a, b| a.τ均值.partial_cmp(&b.τ均值).unwrap_or(std::cmp::Ordering::Equal));
    let 戈德斯通模式 = if 判据 != 破缺判据::独立相 {
        最短组.map(|g| g.模索引.clone()).unwrap_or_default()
    } else {
        vec![]
    };

    说明 = format!(
        "τ谱{}: Δ={:.3}, CV={:.2}, {}层分组, 戈德斯通模{}个",
        判据.名称(), Δ, 简并度, 分组.len(), 戈德斯通模式.len()
    );

    对称破缺结果 {
        谱隙_Δ: Δ,
        τ谱简并度: 简并度,
        τ谱分组: 分组,
        戈德斯通模式,
        破缺判据: 判据,
        κ_EP_临界值: vec![],
        临界裕度: vec![],
        恢复时间估计: vec![],
        最敏感模对: None,
        谱信息充足: true,
        说明,
    }
    }

    /// P39 G-11（**类 I · EP 裸参数**, P39 §14.2 三类对象取法表）事前临界预测:
    /// 从复 L 计算每对裸模 κ_EP^(ij)=½√[(Δω)²+(Δγ)²]（对角元差）、
    /// 实际**裸耦合 κ_ij=|L[i,j]|（同基非对角元, 禁本征矢投影）**、
    /// 临界裕度 margin=κ_EP−κ_ij、三相判断（独立相/临界预警/τ分裂相）+ 恢复时间（EP 慢化）。
    ///
    /// **★ 输入基契约（钉死, D5+D6）**：`l` 必须表达在**未耦合参考基（物理通道基/裸模基）**
    /// ——其对角元才是无耦合固有本征值 λ_n=ω_n−iγ_n；**若上游传入已旋转/本征基的 L，
    /// 对角元不再是裸模、κ_EP 失效**。类 I 必须读裸元：简并 EP 处含耦合本征矢恰把裸参数
    /// 经 w†δLv 投影归零（见反例守卫），故**禁投影**。
    /// （对照：类 III「集体模—集体模图边」走 `kappa_channel::κ测量=w†δLv`，对象不同、勿混用。）
    /// D1 联动: L 非对角部分不显著（<1e-6）时返回 谱信息充足=false，不静默判定。
    pub fn 临界预测(
        &self,
        l: &DMatrix<NComplex<f64>>,
        分解: &非厄米谱分解,
    ) -> 对称破缺结果 {
        let n = 分解.模数;
        // D1 联动: δL（L 非对角部分）是否显著
        let mut 非对角最大 = 0.0f64;
        for i in 0..n {
            for j in 0..n {
                if i != j {
                    let z = l[(i, j)];
                    非对角最大 = 非对角最大.max((z.re * z.re + z.im * z.im).sqrt());
                }
            }
        }
        let 谱信息充足 = 非对角最大 > 1e-6;
        if !谱信息充足 {
            return 对称破缺结果 {
                谱隙_Δ: 0.0,
                τ谱简并度: f64::NAN,
                τ谱分组: vec![],
                戈德斯通模式: vec![],
                破缺判据: 破缺判据::独立相,
                κ_EP_临界值: vec![],
                临界裕度: vec![],
                恢复时间估计: vec![],
                最敏感模对: None,
                谱信息充足: false,
                说明: "谱信息不足（D1 未修复态: 复L 对角近似给虚假本征值）——不静默给出κ_EP临界预测".to_string(),
            };
        }
        if n < 2 {
            return 对称破缺结果 {
                谱隙_Δ: 0.0,
                τ谱简并度: f64::NAN,
                τ谱分组: vec![],
                戈德斯通模式: vec![],
                破缺判据: 破缺判据::独立相,
                κ_EP_临界值: vec![],
                临界裕度: vec![],
                恢复时间估计: vec![],
                最敏感模对: None,
                谱信息充足: true,
                说明: "模不足2, 无法做对模临界预测".to_string(),
            };
        }

        // 每对裸模 (i,j): κ_EP^(ij) + κ_ij（裸元） + margin + 恢复时间 + 三相判断
        let mut κ_ep = vec![vec![0.0f64; n]; n];
        let mut 裕度 = vec![vec![0.0f64; n]; n];
        let mut 恢复 = vec![vec![0.0f64; n]; n];
        let mut 全局判据 = 破缺判据::独立相;
        let mut 最敏感对: Option<(usize, usize)> = None;
        let mut 最敏感值 = f64::INFINITY;

        for i in 0..n {
            for j in (i + 1)..n {
                // P39 两模模型: λ₁=ω₁-iγ₁ 为无耦合固有本征值（= 裸基 L 对角元）;
                // κ_EP 由固有频率/耗散差决定, 不得用耦合后本征值（已含分裂, 自洽性破坏）
                let λi = l[(i, i)];
                let λj = l[(j, j)];
                let Δω = λi.re - λj.re;
                let Δγ = λi.im - λj.im;
                // P39 §3 定理: κ_EP=½√[(Δω)²+(Δγ)²] = ½|λ_i-λ_j|
                let kep = 0.5 * (Δω * Δω + Δγ * Δγ).sqrt();

                // 类 I 实际裸耦合 κ_ij = |L[i,j]|（同基非对角元, 禁本征矢投影;
                // 简并 EP 处含耦合本征矢会把裸参数投影归零, 见反例守卫）。非对称的
                // |L[j,i]| 反向边归 G-12 非对称判据, 此处逐对取 |L[i,j]|（i<j）。
                let κij = l[(i, j)].norm();

                let margin = kep - κij;
                let τrec = if margin.abs() < 1e-12 {
                    f64::INFINITY // EP 临界点: 恢复时间发散
                } else {
                    1.0 / margin.abs().sqrt()
                };

                κ_ep[i][j] = kep;
                κ_ep[j][i] = kep;
                裕度[i][j] = margin;
                裕度[j][i] = margin;
                恢复[i][j] = τrec;
                恢复[j][i] = τrec;

                // 三相判断（P39 表1）: margin<0 τ分裂相 / margin/κ_EP<10% 临界预警 / margin>0 独立相
                let 相 = if margin < 0.0 {
                    破缺判据::τ分裂相
                } else if kep > 1e-12 && margin / kep < 0.1 {
                    破缺判据::临界预警
                } else {
                    破缺判据::独立相
                };
                // 全局判据取最严重: τ分裂相 > 临界预警 > 独立相
                全局判据 = match (&全局判据, &相) {
                    (_, &破缺判据::τ分裂相) => 破缺判据::τ分裂相,
                    (&破缺判据::τ分裂相, _) => 破缺判据::τ分裂相,
                    (_, &破缺判据::临界预警) => 破缺判据::临界预警,
                    (&破缺判据::临界预警, _) => 破缺判据::临界预警,
                    _ => 破缺判据::独立相,
                };

                // 物理推论: 同频同耗散模最敏感（κ_EP 最小）
                if kep < 最敏感值 {
                    最敏感值 = kep;
                    最敏感对 = Some((i, j));
                }
            }
        }

        let 全局名称 = 全局判据.名称();
        对称破缺结果 {
            谱隙_Δ: 0.0,
            τ谱简并度: f64::NAN,
            τ谱分组: vec![],
            戈德斯通模式: vec![],
            破缺判据: 全局判据,
            κ_EP_临界值: κ_ep,
            临界裕度: 裕度,
            恢复时间估计: 恢复,
            最敏感模对: 最敏感对,
            谱信息充足: true,
            说明: format!(
                "κ_EP临界预测完成: {} 相（最敏感模对{:?}, 同频同耗散最敏感; 多样性=稳定性来源）",
                全局名称, 最敏感对
            ),
        }
    }
}

