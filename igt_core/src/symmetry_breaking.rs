//! 对称破缺检测（D5, 2026-08-23）— P13 对称破缺与τ层级化
//!
//! 理论依据:
//!   - P13 §2.2: "谱分离就是对称破缺的结果！对称破缺产生了谱隙、慢变量、层级"
//!   - P13 §6.1-6.3: 谱隙出现 / τ分裂 / 戈德斯通模式; §5.3: 层级差一个数量级
//!   - P22 §6.3: 谱隙 Δ = min(τ_S⁻¹)-max(τ_F⁻¹)
//!
//! 工程范围（发起人确认）: 只检测**现象**（谱隙/τ分裂/戈德斯通/层级化）,
//! 不计算临界值 κ_c 本身的理论（留给理论侧）。
//!
//! 依赖 D1（完整复L 本征值 {ω_n,γ_n} 准确）: D1 未修复时对角近似给虚假
//! 本征值 → 破缺判定失真; 本模块检测谱信息充足性, 不足时返回 谱信息不足。

