    /// ★ T-74 反例守卫（把"类 I 必须读裸元、禁投影"钉死, P39 §14.2）:
    /// 简并对称两模 L=[[-i,0.1],[0.1,-i]] 下——
    ///   ① 裸基非对角元 |L[0,1]| = 0.1（EP 裸耦合参数, 类 I 要的量）;
    ///   ② 含扰本征基投影 |w0†δL v1| ≈ 0（<1e-12）——耦合已把本征矢旋成 (1,±1)/√2,
    ///      投影在简并 EP 处解析归零。
    /// 二者**不可互换**: 若类 I 误用投影, κ_ij≡0 会把"已破缺"误判成"独立相"（旧脆弱假绿根因）。
    #[test]
    fn 测试_P39V1a_类I裸元与投影不可互换守卫() {
        let l = L矩阵_of(&[(0.0, -1.0), (0.0, -1.0)], &[(0, 1, 0.1, 0.0)]);
        // ① 裸基非对角元
        let 裸元 = l[(0, 1)].norm();
        assert!((裸元 - 0.1).abs() < 1e-12, "裸元 |L[0,1]|=0.1: {}", 裸元);

        // ② 含扰本征基投影 κ_01 = w0†δL v1（δL=L−diag）
        let 分 = 非厄米谱求解器::default().分解(&l).unwrap();
        let n = 分.模数;
        let mut 投 = NComplex::new(0.0, 0.0);
        for a in 0..n {
            for b in 0..n {
                if a == b {
                    continue; // δL 去对角
                }
                let w0 = NComplex::new(分.模[0].w[a], 分.模[0].w虚[a]);
                let v1 = NComplex::new(分.模[1].v[b], 分.模[1].v虚[b]);
                投 += w0.conjugate() * l[(a, b)] * v1;
            }
        }
        assert!(
            投.norm() < 1e-12,
            "简并 EP 处含扰投影应解析归零（类 I 不可用）: {}", 投.norm()
        );
    }

