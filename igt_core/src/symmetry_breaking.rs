    // ==================== T-7 P39 G-11 κ_EP 临界预测（D5+D6 v1.1 §8 V1a/V5） ====================

    /// V1a: κ_EP 临界预测（**类 I 裸基**, P39 §14.2）——κ_EP=½√[(Δω)²+(Δγ)²],
    /// 实际耦合 κ_ij=|L[i,j]|（裸元）= κ_EP−margin; 三相判断
    #[test]
    fn 测试_P39V1a_κEP临界预测() {
        // 模0: ω=0.0, γ=-2.0; 模1: ω=0.5, γ=-0.5 → Δω=0.5, Δγ=1.5 → κ_EP=½√2.5≈0.790569
        let 求解 = 非厄米谱求解器::default();
        let kep期望 = 0.5 * (0.5f64 * 0.5 + 1.5 * 1.5).sqrt();

        // (a) 裸耦合 κ=0.3 < κ_EP → 独立相
        let l_a = L矩阵_of(&[(0.0, -2.0), (0.5, -0.5)], &[(0, 1, 0.3, 0.0)]);
        let 分解a = 求解.分解(&l_a).unwrap();
        let 结果a = 对称破缺检测器::default().临界预测(&l_a, &分解a);
        assert!(结果a.谱信息充足);
        assert_eq!(结果a.破缺判据, 破缺判据::独立相, "{}", 结果a.说明);
        let kep_a = 结果a.κ_EP_临界值[0][1];
        assert!((kep_a - kep期望).abs() < 1e-9, "κ_EP={} 期望={}", kep_a, kep期望);
        let kij_a = kep_a - 结果a.临界裕度[0][1]; // κ_ij = κ_EP − margin
        assert!((kij_a - 0.3).abs() < 1e-9, "(a) 裸耦合 κ_ij=|L01|=0.3: {}", kij_a);
        assert!(结果a.临界裕度[0][1] > 0.0, "独立相 margin>0: {}", 结果a.临界裕度[0][1]);

        // (b) 裸耦合 κ=0.79 ≈ κ_EP=0.790569（EP 邻域）→ **确定性临界预警**
        //   （类 I 读裸元后 margin=+5.69e-4 >0 但 margin/κ_EP≈7.2e-4 <10%, 不再两相皆可）
        let l_b = L矩阵_of(&[(0.0, -2.0), (0.5, -0.5)], &[(0, 1, 0.79, 0.0)]);
        let 分解b = 求解.分解(&l_b).unwrap();
        let 结果b = 对称破缺检测器::default().临界预测(&l_b, &分解b);
        assert_eq!(
            结果b.破缺判据, 破缺判据::临界预警,
            "(b) 裸元口径下应确定性临界预警（margin 小正）: {}", 结果b.说明
        );
        let kij_b = 结果b.κ_EP_临界值[0][1] - 结果b.临界裕度[0][1];
        assert!((kij_b - 0.79).abs() < 1e-9, "(b) 裸耦合 κ_ij=|L01|=0.79: {}", kij_b);
        let 相对裕度 = 结果b.临界裕度[0][1] / 结果b.κ_EP_临界值[0][1];
        assert!(
            (0.0..0.1).contains(&相对裕度),
            "(b) margin∈(0,10%κ_EP) 方为临界预警: {:.3e}", 相对裕度
        );
        assert!(
            结果b.恢复时间估计[0][1] > 1.0,
            "近临界恢复时间应大（临界慢化）: {}", 结果b.恢复时间估计[0][1]
        );

        // (c) 裸耦合 κ=1.5 > κ_EP → τ分裂相
        let l_c = L矩阵_of(&[(0.0, -2.0), (0.5, -0.5)], &[(0, 1, 1.5, 0.0)]);
        let 分解c = 求解.分解(&l_c).unwrap();
        let 结果c = 对称破缺检测器::default().临界预测(&l_c, &分解c);
        assert_eq!(结果c.破缺判据, 破缺判据::τ分裂相, "{}", 结果c.说明);
        let kij_c = 结果c.κ_EP_临界值[0][1] - 结果c.临界裕度[0][1];
        assert!((kij_c - 1.5).abs() < 1e-9, "(c) 裸耦合 κ_ij=|L01|=1.5: {}", kij_c);
        assert!(结果c.临界裕度[0][1] < 0.0, "τ分裂相 margin<0: {}", 结果c.临界裕度[0][1]);
        // 恢复时间: τ_rec=1/|margin|^{1/2} 有限正
        assert!(结果c.恢复时间估计[0][1].is_finite() && 结果c.恢复时间估计[0][1] > 0.0);
    }

