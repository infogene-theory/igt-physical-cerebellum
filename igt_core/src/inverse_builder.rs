/// 逆元构建器 — 从两侧 τ 谱构造联合耗散算子并检验逆元
#[derive(Debug, Clone, Copy)]
pub struct 逆元构建器 {
    /// 模-反模配对容差 ε（|λ_n+λ_m|<ε 视为配对）
    pub 配对容差: f64,
}

impl Default for 逆元构建器 {
    fn default() -> Self {
        Self { 配对容差: 0.2 }
    }
}

impl 逆元构建器 {
    /// 新建（默认配对容差 0.2）
    pub fn 新建() -> Self {
        Self::default()
    }

    /// 构建联合耗散算子 L_total = [[L_you, K], [K^T, L_engine]]
    ///
    /// # 参数
    /// - `用户τ`: 用户侧 τ 谱（HRV/认知，恒正；耗散模 1/τ>0 → 对角 -1/τ）
    /// - `引擎τ`: Engine 侧 τ 谱（可为负=反模/增长模，1/τ<0 → 对角 -1/τ>0 逆元注入）
    /// - `耦合`: 耦合矩阵 K（用户数 × 引擎数，用户输出→Engine 输入强度）
    ///
    /// 耦合尺寸不匹配时按 min 截断（缺省 0）。
    pub fn 构建联合算子(&self, 用户τ: &[f64], 引擎τ: &[f64], 耦合: &DMatrix<f64>) -> 联合耗散算子 {
        let n = 用户τ.len();
        let m = 引擎τ.len();
        let total = n + m;
        let mut l = DMatrix::<f64>::zeros(total, total);

        // 对角块: L_you / L_engine（弛豫率 -1/τ，τ≤0 视为反模/异常→0 保护）
        for (i, τ) in 用户τ.iter().enumerate() {
            l[(i, i)] = if *τ > 1e-9 { -1.0 / τ } else { 0.0 };
        }
        for (j, τ) in 引擎τ.iter().enumerate() {
            let 对角 = if τ.abs() > 1e-9 { -1.0 / τ } else { 0.0 };
            l[(n + j, n + j)] = 对角;
        }

        // 耦合块: K 与 K^T
        let mut 耦合平方和 = 0.0_f64;
        let mut 耦合对数 = 0_usize;
        for i in 0..n.min(耦合.nrows()) {
            for j in 0..m.min(耦合.ncols()) {
                let k = 耦合[(i, j)];
                l[(i, n + j)] = k;
                l[(n + j, i)] = k; // K^T（对称耦合假设，可调）
                耦合平方和 += k * k;
                耦合对数 += 1;
            }
        }

        // 耦合强度 = Frobenius 均值（K 非对角块）
        let 耦合强度 = if 耦合对数 > 0 {
            (耦合平方和 / 耦合对数 as f64).sqrt()
        } else {
            0.0
        };

        联合耗散算子 {
            用户数: n,
            引擎数: m,
            联合矩阵: Self::矩阵转嵌套(&l),
            耦合强度,
        }
    }

    /// 复特征值（实矩阵 Schur 分解；小矩阵显式公式）
    pub fn 复特征值(&self, a: &DMatrix<f64>) -> Vec<(f64, f64)> {
        let n = a.nrows();
        if n == 0 {
            return vec![];
        }
        if n == 1 {
            return vec![(a[(0, 0)], 0.0)];
        }
        if n == 2 {
            return Self::特征值2x2(a[(0, 0)], a[(0, 1)], a[(1, 0)], a[(1, 1)]);
        }
        // 一般 n：nalgebra Schur 复特征值（仅小型矩阵，n ≤ 128）
        let schur = nalgebra::linalg::Schur::new(a.clone());
        schur
            .complex_eigenvalues()
            .iter()
            .map(|λ| (λ.re, λ.im))
            .collect()
    }

    /// 2×2 矩阵特征值（判别式法，避免 Schur 开销与排序不稳定）
    fn 特征值2x2(a: f64, b: f64, c: f64, d: f64) -> Vec<(f64, f64)> {
        let tr = a + d;
        let det = a * d - b * c;
        let disc = tr * tr - 4.0 * det;
        if disc >= 0.0 {
            let sqrt_disc = disc.sqrt();
            vec![
                ((tr + sqrt_disc) / 2.0, 0.0),
                ((tr - sqrt_disc) / 2.0, 0.0),
            ]
        } else {
            let sqrt_neg = (-disc).sqrt() / 2.0;
            let re = tr / 2.0;
            vec![(re, sqrt_neg), (re, -sqrt_neg)]
        }
    }

    /// 联合谱三检验 → 逆元构建结果
    ///
    /// ①联合稳定性: 全部 Re(λ) < 0（扰动后回归联合稳态）
    /// ②模-反模配对: 贪心匹配 |λ_n+λ_m|<容差
    /// ③配对覆盖率: 配对数 / 本征值对数 → 谱对称性
    /// 逆元形成度 = 0.5×稳定度 + 0.5×配对覆盖率
    pub fn 构建(&self, 用户τ: &[f64], 引擎τ: &[f64], 耦合: &DMatrix<f64>) -> 逆元构建结果 {
        let 联合算子 = self.构建联合算子(用户τ, 引擎τ, 耦合);
        self.从矩阵分析(
            &Self::嵌套转矩阵(&联合算子.联合矩阵),
            联合算子.用户数,
            联合算子.引擎数,
            联合算子.耦合强度,
        )
    }

    /// 第270批: 从给定联合矩阵直接做三检验（供逆元建议器模拟造波后复用）
    ///
    /// 输入已构造好的联合耗散矩阵 L_total、块规模与耦合强度 → 与 `构建` 相同的
    /// ①联合稳定性 ②模-反模配对 ③配对覆盖率 → 逆元形成度 + 优化建议。
    pub fn 从矩阵分析(&self, 矩阵: &DMatrix<f64>, 用户数: usize, 引擎数: usize, 耦合强度: f64) -> 逆元构建结果 {
        let 本征值 = self.复特征值(矩阵);

        if 本征值.is_empty() {
            return 逆元构建结果 {
                联合本征值: vec![],
                联合稳定: true,
                最大实部: f64::NEG_INFINITY,
                配对: vec![],
                配对覆盖率: 0.0,
                逆元形成度: 0.0,
                优化建议: vec!["联合谱为空（τ谱为空或全退化），无法构建逆元".to_string()],
                联合算子: 联合耗散算子 { 用户数, 引擎数, 联合矩阵: Self::矩阵转嵌套(矩阵), 耦合强度 },
            };
        }

        // ①联合稳定性
        let 最大实部 = 本征值.iter().map(|(re, _)| *re).fold(f64::NEG_INFINITY, f64::max);
        let 联合稳定 = 最大实部 < 0.0;
        let 稳定度 = if 联合稳定 { 1.0 } else { 1.0 / (1.0 + 最大实部) };

        // ②模-反模配对（贪心：每个未配对模找最小残差反模）
        let mut 配对: Vec<模反模配对> = vec![];
        let mut 已配对 = vec![false; 本征值.len()];
        for i in 0..本征值.len() {
            if 已配对[i] {
                continue;
            }
            let (re_i, im_i) = 本征值[i];
            let mut best: Option<(usize, f64)> = None;
            for j in (i + 1)..本征值.len() {
                if 已配对[j] {
                    continue;
                }
                let (re_j, im_j) = 本征值[j];
                let 残差 = ((re_i + re_j).powi(2) + (im_i + im_j).powi(2)).sqrt();
                if best.map_or(true, |(_, r)| 残差 < r) {
                    best = Some((j, 残差));
                }
            }
            if let Some((j, 残差)) = best {
                if 残差 <= self.配对容差 {
                    配对.push(模反模配对 { 模索引: i, 反模索引: j, 残差 });
                    已配对[i] = true;
                    已配对[j] = true;
                }
            }
        }

        // ③配对覆盖率（本征值对数）
        let 本征值对数 = 本征值.len() / 2;
        let 配对覆盖率 = if 本征值对数 > 0 {
            配对.len() as f64 / 本征值对数 as f64
        } else {
            0.0
        };

        // 逆元形成度
        let 逆元形成度 = (0.5 * 稳定度 + 0.5 * 配对覆盖率).clamp(0.0, 1.0);

        // 优化建议
        let mut 优化建议 = vec![];
        if !联合稳定 {
            if 最大实部 > 1e-9 {
                优化建议.push(format!(
                    "存在正实部模({:.3})，为增长/反模——需增强耦合K或注入逆操作使回归负实部(联合稳定)",
                    最大实部
                ));
            } else {
                优化建议.push("联合谱接近稳定边界(最大实部≈0)，建议微调K避免扰动越界".to_string());
            }
        }
        if 配对覆盖率 < 0.5 {
            优化建议.push(format!(
                "模-反模配对不足(覆盖率{:.2}<0.5)——调整耦合矩阵K增强共振耦合，使谱出现互补对",
                配对覆盖率
            ));
        }
        if 优化建议.is_empty() {
            优化建议.push("逆元形成良好：联合稳定+模-反模配对充足".to_string());
        }

        逆元构建结果 {
            联合本征值: 本征值,
            联合稳定,
            最大实部,
            配对,
            配对覆盖率,
            逆元形成度,
            优化建议,
            联合算子: 联合耗散算子 { 用户数, 引擎数, 联合矩阵: Self::矩阵转嵌套(矩阵), 耦合强度 },
        }
    }

    // ===== 矩阵 <-> 嵌套 Vec 转换（序列化/调试；第270批供逆元建议器复用） =====

    pub(crate) fn 矩阵转嵌套(l: &DMatrix<f64>) -> Vec<Vec<f64>> {
        (0..l.nrows())
            .map(|i| (0..l.ncols()).map(|j| l[(i, j)]).collect())
            .collect()
    }

    pub(crate) fn 嵌套转矩阵(nested: &[Vec<f64>]) -> DMatrix<f64> {
        let n = nested.len();
        let m = if n > 0 { nested[0].len() } else { 0 };
        let mut l = DMatrix::<f64>::zeros(n, m);
        for i in 0..n {
            for j in 0..nested[i].len().min(m) {
                l[(i, j)] = nested[i][j];
            }
        }
        l
    }
}

