    /// T-181（统一令 §4.3）：状态空间本征值 → 复 L 权威表示的边界换算
    #[test]
    fn 测试_权威换算_稳定模() {
        // 状态空间约定：re=增长率=-0.05（稳定负）、im=振荡频率 ±0.5
        let m = 权威本征模::从状态空间本征值(-0.05, 0.5);
        assert!((m.λ_im - (-0.05)).abs() < 1e-12, "λ_im=re（增长率稳定负）");
        assert!((m.γ - 0.05).abs() < 1e-12, "γ=−λ_im=0.05（耗散率稳定正）");
        assert!((m.ω - 0.5).abs() < 1e-12, "ω=|im|=0.5");
        assert!((m.τ.unwrap() - 20.0).abs() < 1e-9, "τ=1/γ=20s");
        assert!(m.稳定());
        // 负虚部频率取绝对值，ω 一致
        let m2 = 权威本征模::从状态空间本征值(-0.05, -0.5);
        assert!((m2.ω - 0.5).abs() < 1e-12);
    }

    #[test]
    fn 测试_权威换算_增长模不伪造τ() {
        // re=+0.2（增长模）⇒ γ=-0.2<0 非稳定，τ=None（不用增长率倒数冒充弛豫 τ）
        let m = 权威本征模::从状态空间本征值(0.2, 0.0);
        assert!((m.γ - (-0.2)).abs() < 1e-12);
        assert!(!m.稳定());
        assert_eq!(m.τ, None);
        // 临界零增长率同样不给 τ
        assert_eq!(权威本征模::从状态空间本征值(0.0, 0.3).τ, None);
    }
