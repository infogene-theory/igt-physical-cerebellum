/// 模-反模配对（λ_n + λ_m ≈ 0）
#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
pub struct 模反模配对 {
    /// 模索引（联合谱中）
    pub 模索引: usize,
    /// 反模索引
    pub 反模索引: usize,
    /// |λ_n + λ_m|（配对残差，越小配对越好）
    pub 残差: f64,
}

