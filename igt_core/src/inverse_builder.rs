/// 联合耗散算子 — 用户侧与 Engine 侧 τ 谱的耦合块矩阵
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 联合耗散算子 {
    /// 用户侧节点数（L_you 对角块规模）
    pub 用户数: usize,
    /// Engine 侧节点数（L_engine 对角块规模）
    pub 引擎数: usize,
    /// 联合矩阵 L_total（(用户数+引擎数)×(用户数+引擎数)，供调试/序列化）
    pub 联合矩阵: Vec<Vec<f64>>,
    /// 耦合强度（K 非对角块 Frobenius 均值）
    pub 耦合强度: f64,
}

// ============================================================================
