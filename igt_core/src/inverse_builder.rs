/// 复 L 权威表示下的单个本征模（消费方取 ω/γ/τ 一律用本结构，禁止再各自 `-1/re`/`|im|` 临时换算）。
///
/// - `ω`：振荡频率（非负，= 状态空间本征值虚部绝对值）；
/// - `λ_im`：复 L 本征值虚部＝增长率（**稳定为负**；= 状态空间本征值的实部 re）；
/// - `γ`：耗散率（**稳定为正**，γ = −λ_im）；
/// - `τ`：弛豫时间（稳定模 τ = 1/γ = −1/λ_im > 0；非稳定/零增长率给 None，不伪造）。
///
/// 统一令：权威内部表示 λ=ω−iγ（Im λ=λ_im 稳定负）；状态空间约定（Re=增长率/Im=频率）
/// 仅允许在边界经本函数换算，不落库、不作为 core 间传递的权威谱。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 权威本征模 {
    /// 振荡频率 ω（Hz，非负）
    pub ω: f64,
    /// 复 L 本征值虚部 λ_im（增长率；稳定负）
    pub λ_im: f64,
    /// 耗散率 γ = −λ_im（稳定正）
    pub γ: f64,
    /// 弛豫时间 τ = 1/γ（仅稳定模 γ>0 有值）
    pub τ: Option<f64>,
}

impl 权威本征模 {
    /// 是否稳定模（γ>0 ⇔ λ_im<0）
    pub fn 稳定(&self) -> bool {
        self.γ > 0.0
    }

    /// ★ 唯一换算入口：状态空间实矩阵本征值 `(re=增长率, im=振荡频率)` → 复 L 权威表示。
    ///
    /// 这是统一令 §4.3 要求的"在边界一次导出 ω/γ/τ"——inverse_builder 内部矩阵/存储数值
    /// **一个字节不改**，仅在此把状态空间约定（Re=增长率/Im=频率）映射到权威约定：
    /// `λ_im = re`、`γ = −re`、`ω = |im|`、稳定模 `τ = 1/γ = −1/re`。
    pub fn 从状态空间本征值(re: f64, im: f64) -> Self {
        let λ_im = re;
        let γ = -re;
        let τ = if γ > 1e-12 { Some(1.0 / γ) } else { None };
        Self { ω: im.abs(), λ_im, γ, τ }
    }
}

impl 逆元构建结果 {
    /// 联合谱整链换算：把 `联合本征值`（状态空间约定 (增长率, 频率)）一次性映射为
    /// 复 L 权威表示 `Vec<权威本征模>`，顺序与 `联合本征值` 一一对应。
    pub fn 权威谱(&self) -> Vec<权威本征模> {
        self.联合本征值
            .iter()
            .map(|(re, im)| 权威本征模::从状态空间本征值(*re, *im))
            .collect()
    }
}

