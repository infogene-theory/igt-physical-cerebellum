//! 逆元构建器 — 第209批（2026-08-17）
//!
//! 理论依据:
//!   - 《IGT Agent _ Engine 新开发计划》阶段三"逆元构建模块":
//!     构造联合耗散算子 L_total → 检验模-反模配对（λ_n + λ_m ≈ 0）→ 评估逆元形成程度
//!   - 《IGT Engine：以生命体为对标核的逆元构建路径》:
//!     用户侧 L_you（HRV/认知 τ 谱）与 Engine 侧 L_engine 耦合构成联合耗散系统;
//!     逆元条件 = ①联合稳定(所有本征值实部<0) ②模-反模配对 ③联合谱对称性
//!
//! 核心定位（补齐"文档2 → V10"最缺的一环——逆元构建的直接数值实现）:
//!   把用户侧 τ 谱(对角块 L_you=-1/τ_i) 与 Engine 侧 τ 谱(对角块 L_engine=-1/τ_j)
//!   拼成联合块矩阵 L_total = [[L_you, K], [K^T, L_engine]]
//!   → Schur 复特征值 → 联合谱 → 三检验:
//!     ①联合稳定性(全部 Re(λ)<0, 扰动后回归联合稳态)
//!     ②模-反模配对(|λ_n+λ_m|<容差, 逆元的谱表现)
//!     ③配对覆盖率(谱对称性) → 逆元形成度评分 + 优化建议(调 K)
//!
//! 工程语义:
//!   - 用户侧 τ 恒正(耗散模, 1/τ>0 → 对角负实部=稳定回归)
//!   - Engine 侧 τ 可负(反模/增长模, 1/τ<0 → 对角正实部=逆元注入,
//!     用于抵消用户侧单向趋势, 是"逆操作"的谱表现)
//!   - 模-反模配对严格要求 trace≈0(特征值实部之和为0), 纯耗散系统(对角全负)
//!     无法严格配对 → 配对覆盖率反映"临界稳定/共振耦合"程度, 诚实量化
//!
//! [T-21a] 复本征值存储约定显式标注（ARCH-1 v1.2 §9.3-4）:
//!   **实矩阵对角化自然约定: Re(λ)=增长率（耗散系统为负, 稳定判据 Re<0 物理正确）/
//!   Im(λ)=振荡频率 ω**——联合矩阵 L_total 是实矩阵（对角 −1/τ + 耦合块 K/K^T）,
//!   复特征值由实矩阵 Schur 分解自然产生。
//!   与术语表 v3.2 显示约定（λ=ω−iγ, Re=ω/Im=−γ）的换算:
//!     v3.2.ω = 本约定 |Im|、v3.2.γ = −本约定 Re（PM 已核实"联合稳定=Re<0"判据物理正确,
//!     属标注缺失非数值用反——**不迁移存储约定**, 消费方按本约定取 ω=|Im|、γ=−Re）
//!   [T-21a] 历史标注: 2026-08-28 前本模块未显式标注存储约定, 与术语表 v3.2 显示约定
//!     不一致曾引发"实虚部疑似用反"质疑（理论侧【续14】）——已核实澄清并标注

