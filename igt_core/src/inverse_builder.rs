/// 逆元构建结果 — 联合谱分析 + 逆元形成度
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 逆元构建结果 {
    /// 联合谱复本征值（实部, 虚部）
    ///
    /// [T-21a] 存储约定（ARCH-1 v1.2 §9.3-4）: **Re=增长率/Im=振荡频率 ω**（实矩阵自然约定）;
    /// 与术语表 v3.2（λ=ω−iγ）换算: v3.2.ω=|Im|、v3.2.γ=−Re
    pub 联合本征值: Vec<(f64, f64)>,
    /// 联合稳定性（全部 Re(λ) < 0）
    pub 联合稳定: bool,
    /// 最大实部（>0 表示存在增长模，需逆元注入）
    pub 最大实部: f64,
    /// 模-反模配对列表
    pub 配对: Vec<模反模配对>,
    /// 配对覆盖率（配对数 / 本征值对数）
    pub 配对覆盖率: f64,
    /// 逆元形成度 ∈ [0,1]（= 0.5×稳定度 + 0.5×配对覆盖率）
    pub 逆元形成度: f64,
    /// 优化建议（调整耦合 K）
    pub 优化建议: Vec<String>,
    /// 联合耗散算子（含块矩阵）
    pub 联合算子: 联合耗散算子,
}

