    /// 模-反模配对: 用户 τ=0.5(耗散 -2) + 引擎 τ=-0.5(反模 +2), 零耦合
    /// L=[[-2,0],[0,+2]] → 特征值 ±2, 完美配对 λ_n+λ_m=0
    #[test]
    fn 测试_构建_完美配对() {
        let b = 逆元构建器 { 配对容差: 0.1 };
        let 用户τ = vec![0.5]; // 1/τ=2 → 对角 -2
        let 引擎τ = vec![-0.5]; // 反模: 对角 +2
        let 耦合 = DMatrix::from_row_slice(1, 1, &[0.0]);
        let 结果 = b.构建(&用户τ, &引擎τ, &耦合);
        assert_eq!(结果.配对.len(), 1, "应精确配对一个模-反模对");
        assert!((结果.配对[0].残差).abs() < 1e-9);
        assert!((结果.配对覆盖率 - 1.0).abs() < 1e-9);
        // 稳定度=1/(1+2)=0.333 → 形成度 = 0.5×0.333+0.5×1.0 = 0.667
        assert!((结果.逆元形成度 - 0.667).abs() < 0.01, "形成度应≈0.667: {}", 结果.逆元形成度);
    }

