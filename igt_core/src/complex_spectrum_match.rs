    #[test]
    fn 测试_谱等价判定_椭圆判据() {
        let 右向量 = vec![vec![1.0, 0.0, 0.0], vec![0.0, 1.0, 0.0], vec![0.0, 0.0, 1.0]];
        let p = [0.4, 0.3, 0.3];
        // 甲: λ_im 均值 -1.5 集中（σ_γ≈0.41，σ_γ 为椭圆系综结果历史字段名，语义＝虚部方差）→ τ_ellipse≈0.95
        let 甲本征 = [(0.0, -1.0), (3.0, -1.5), (6.0, -2.0)];
        // 乙: λ_im 均值 -1.5 相同但展开大（σ_γ≈1.22）→ τ_ellipse≈0.45
        // 复谱距离≈0.10<0.15（三元通过）但椭圆|Δ|≈0.50>0.3 → 不等价
        let 乙本征 = [(0.0, 0.0), (3.0, -1.5), (6.0, -3.0)];
        let r = 谱等价判定(&甲本征, &右向量, &p, &乙本征, &右向量, &p);
        assert!(r.复谱距离 < 0.15, "构造应三元复谱距离通过: {}", r.复谱距离);
        assert!(r.子空间夹角 > 0.8 && r.参与度余弦 > 0.9, "构造应三元通过");
        assert!(!r.谱等价, "三元通过但椭圆不一致应不等价: {}", r.判定);
        assert!(r.椭圆一致性.is_some());
        assert!(r.椭圆一致性.unwrap() > 0.3, "应检出椭圆差异: {}", r.椭圆一致性.unwrap());
        // 椭圆一致 → 谱等价
        let 乙近 = [(0.1, -1.1), (2.9, -1.6), (6.1, -1.9)];
        let r2 = 谱等价判定(&甲本征, &右向量, &p, &乙近, &右向量, &p);
        assert!(r2.谱等价, "三元+椭圆一致应等价: {}", r2.判定);
        assert!(r2.τ_ellipse_甲.is_some() && r2.τ_ellipse_乙.is_some());
        // 不足3（既有行为）→ 椭圆不设卡, 三元判定保持
        let 小 = [(1.0, -0.5), (2.0, -0.3)];
        let r3 = 谱等价判定(&小, &右向量, &p, &小, &右向量, &p);
        assert!(r3.谱等价, "不足3不设卡, 三元判定保持: {}", r3.判定);
        assert!(r3.椭圆一致性.is_none());
    }

    #[test]
    fn 测试_矩阵逆() {
        let m = vec![vec![2.0, 0.0], vec![0.0, 4.0]];
        let inv = 矩阵逆(&m).unwrap();
        assert!((inv[0][0] - 0.5).abs() < 1e-9);
        assert!((inv[1][1] - 0.25).abs() < 1e-9);
        // 奇异 → None
        let 奇异 = vec![vec![1.0, 2.0], vec![2.0, 4.0]];
        assert!(矩阵逆(&奇异).is_none());
    }
