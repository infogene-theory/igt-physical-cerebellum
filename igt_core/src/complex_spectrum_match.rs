/// 复谱距离（P22 §10.5 判据①）— 两复谱 {λ_n=(ω,λ_im)} 的贪心最近邻配对距离
///
/// ★ 2026-09-23 γ 符号统一令 §4.1/§5：复谱点的第二维为**本征值虚部 λ_im**（稳定<0，权威内部表示）；
///   耗散率 γ=−λ_im（稳定>0）为派生量。本模块原以 γ 命名第二维（统一令前旧口径），现按令改名 λ_im，
///   **距离数学不变（欧氏距离对第二维符号不敏感，仅命名/口径澄清）**。
///
/// 方法：对甲谱每个点找乙谱最近点（欧氏，ω/λ_im 双维），平均最近距离；
/// 归一化：除以两谱归一化尺度（min/max 包围盒对角线）→ [0,1]。
/// 0=完全重合，1=完全分离。
pub fn 复谱距离(甲: &[(f64, f64)], 乙: &[(f64, f64)]) -> f64 {
    if 甲.is_empty() || 乙.is_empty() {
        return 1.0;
    }
    // 归一化尺度：两谱合并包围盒对角线
    let mut min_ω = f64::INFINITY;
    let mut max_ω = f64::NEG_INFINITY;
    let mut min_λ_im = f64::INFINITY;
    let mut max_λ_im = f64::NEG_INFINITY;
    for (ω, λ_im) in 甲.iter().chain(乙.iter()) {
        min_ω = min_ω.min(*ω);
        max_ω = max_ω.max(*ω);
        min_λ_im = min_λ_im.min(*λ_im);
        max_λ_im = max_λ_im.max(*λ_im);
    }
    let 尺度 = ((max_ω - min_ω).powi(2) + (max_λ_im - min_λ_im).powi(2)).sqrt().max(1e-9);
    // 贪心最近邻（每甲点 → 最近乙点，乙点可复用——谱点集配对近似）
    let 总距离: f64 = 甲
        .iter()
        .map(|&(ωa, λ_ima)| {
            乙.iter()
                .map(|&(ωb, λ_imb)| ((ωa - ωb).powi(2) + (λ_ima - λ_imb).powi(2)).sqrt())
                .fold(f64::INFINITY, f64::min)
        })
        .sum();
    (总距离 / 甲.len() as f64 / 尺度).min(1.0)
}

/// 子空间夹角（P22 §10.5 判据②）— 两右向量列空间的投影重叠度
///
/// 方法：甲子空间 V1（m1 列）向乙子空间 V2（m2 列）的投影 F 范数²/秩：
///   overlap = ‖P1 P2‖_F² / min(m1, m2)
/// 其中 P1=V1(V1^T V1)^{-1}V1^T 投影矩阵；结果∈[0,1]（0=正交，1=同一子空间）。
/// 与维度无关的归一化（秩=min(m1,m2) 满秩情形上限）。
pub fn 子空间夹角(右向量甲: &[Vec<f64>], 右向量乙: &[Vec<f64>]) -> f64 {
    let m1 = 右向量甲.len();
    let m2 = 右向量乙.len();
    if m1 == 0 || m2 == 0 {
        return 0.0;
    }
    let n = 右向量甲[0].len();
    if 右向量乙[0].len() != n {
        return 0.0; // 维度不一致
    }
    // 投影矩阵 P1 = V1(V1^T V1)^{-1} V1^T（n×n）
    let p1 = 投影矩阵(右向量甲, n);
    let p2 = 投影矩阵(右向量乙, n);
    // ‖P1 P2‖_F²
    let mut 范数2 = 0.0;
    for i in 0..n {
        for j in 0..n {
            let 元素: f64 = (0..n).map(|k| p1[i][k] * p2[k][j]).sum();
            范数2 += 元素 * 元素;
        }
    }
    let 秩 = m1.min(m2) as f64;
    (范数2 / 秩).min(1.0)
}

/// 投影矩阵（列空间正交投影）
fn 投影矩阵(列: &[Vec<f64>], n: usize) -> Vec<Vec<f64>> {
    // V^T V（m×m）
    let m = 列.len();
    let mut vtv = vec![vec![0.0; m]; m];
    for i in 0..m {
        for j in 0..m {
            vtv[i][j] = (0..n).map(|k| 列[i][k] * 列[j][k]).sum();
        }
    }
    // (V^T V)^{-1}（高斯消元）
    let inv = match 矩阵逆(&vtv) {
        Some(i) => i,
        None => return vec![vec![0.0; n]; n], // 退化 → 零投影
    };
    // P = V (V^T V)^{-1} V^T
    let mut p = vec![vec![0.0; n]; n];
    for i in 0..n {
        for j in 0..n {
            let mut 和 = 0.0;
            for a in 0..m {
                for b in 0..m {
                    和 += 列[a][i] * inv[a][b] * 列[b][j];
                }
            }
            p[i][j] = 和;
        }
    }
    p
}

/// 矩阵求逆（高斯-约当，小矩阵）
fn 矩阵逆(m: &[Vec<f64>]) -> Option<Vec<Vec<f64>>> {
    let n = m.len();
    if n == 0 || m[0].len() != n {
        return None;
    }
    let mut a = m.to_vec();
    let mut inv = vec![vec![0.0; n]; n];
    for i in 0..n {
        inv[i][i] = 1.0;
    }
    for col in 0..n {
        // 选主元
        let mut 主 = col;
        for r in col + 1..n {
            if a[r][col].abs() > a[主][col].abs() {
                主 = r;
            }
        }
        if a[主][col].abs() < 1e-12 {
            return None;
        }
        a.swap(col, 主);
        inv.swap(col, 主);
        let 主元 = a[col][col];
        for j in 0..n {
            a[col][j] /= 主元;
            inv[col][j] /= 主元;
        }
        for r in 0..n {
            if r != col {
                let 因子 = a[r][col];
                if 因子.abs() > 1e-15 {
                    for j in 0..n {
                        a[r][j] -= 因子 * a[col][j];
                        inv[r][j] -= 因子 * inv[col][j];
                    }
                }
            }
        }
    }
    Some(inv)
}

/// 参与度余弦（P22 §10.5 判据③）— 两 p_obs 向量的余弦相似度
///
/// 维度不一致时按公共维度计算（谱模数不同的基因比较可观度分布形状）；
/// 公共维度为空 → 0。
pub fn 参与度余弦(甲: &[f64], 乙: &[f64]) -> f64 {
    let 公共 = 甲.len().min(乙.len());
    if 公共 == 0 {
        return 0.0;
    }
    let 甲模: f64 = 甲.iter().take(公共).map(|x| x * x).sum::<f64>().sqrt();
    let 乙模: f64 = 乙.iter().take(公共).map(|x| x * x).sum::<f64>().sqrt();
    if 甲模 <= 1e-12 || 乙模 <= 1e-12 {
        return 0.0;
    }
    let 内积: f64 = (0..公共).map(|i| 甲[i] * 乙[i]).sum();
    (内积 / (甲模 * 乙模)).clamp(0.0, 1.0)
}

/// 椭圆参数 τ_ellipse（第271批, P22§6.4）——复本征值对的椭圆系综参数
///
/// 本征值对 ≥3 才可拟合（非厄米谱求解器::椭圆系综）; 不足 → None（不设卡, 数据诚实）。
pub fn 椭圆参数(本征值: &[(f64, f64)]) -> Option<f64> {
    if 本征值.len() < 3 {
        return None;
    }
    use crate::nonhermitian_spectrum::非厄米谱求解器;
    match 非厄米谱求解器::default().椭圆系综(本征值) {
        Ok(椭圆) => Some(椭圆.τ_ellipse),
        Err(_) => None,
    }
}

/// 椭圆一致性（第271批, P22§10.5 第4判据）——两复谱 τ_ellipse 的差值
///
/// 两侧本征值都 ≥3 → Some(|Δτ_ellipse|); 任一侧不足 → None（不设卡）。
/// 阈值 0.3 对齐椭圆β校验边界（P22§6.4 连续替代 GOE/GUE/Poisson 三分）。
pub fn 椭圆一致性(甲: &[(f64, f64)], 乙: &[(f64, f64)]) -> Option<f64> {
    match (椭圆参数(甲), 椭圆参数(乙)) {
        (Some(ta), Some(tb)) => Some((ta - tb).abs()),
        _ => None,
    }
}

/// 谱等价判定结果（P22 §10.5 三元组 + 第271批椭圆第4判据）
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
pub struct 谱等价结果 {
    /// 复谱距离（判据①，<0.15 满足）
    pub 复谱距离: f64,
    /// 子空间夹角（判据②，>0.8 满足）
    pub 子空间夹角: f64,
    /// 参与度余弦（判据③，>0.9 满足）
    pub 参与度余弦: f64,
    /// 甲谱椭圆参数 τ_ellipse（第271批; None=本征值<3 不可算）
    #[serde(default)]
    pub τ_ellipse_甲: Option<f64>,
    /// 乙谱椭圆参数 τ_ellipse
    #[serde(default)]
    pub τ_ellipse_乙: Option<f64>,
    /// 椭圆一致性 |Δτ_ellipse|（None=任一侧不足3不设卡; <0.3 满足）
    #[serde(default)]
    pub 椭圆一致性: Option<f64>,
    /// 谱等价（三元组全满足 ∧ 椭圆判据通过或不可算）
    pub 谱等价: bool,
    /// 判定说明
    pub 判定: String,
}

/// 谱等价综合判定（P22 §10.5 + 第271批椭圆第4判据）
///
/// 输入两组非厄米谱产物：
///   甲/乙: {本征值: &[(ω,λ_im)], 右向量: &[Vec<f64>], p_obs: &[f64]}
/// 三元组全满足，且（两侧本征值≥3 时）椭圆参数 τ_ellipse 一致（|Δ|<0.3）
/// → 谱等价（同基因不同实例，可去重/可复用）。
/// 椭圆判据"任一侧本征值<3 → 不设卡"（数据诚实, 既有测试零破坏）。
pub fn 谱等价判定(
    甲本征值: &[(f64, f64)],
    甲右向量: &[Vec<f64>],
    甲p_obs: &[f64],
    乙本征值: &[(f64, f64)],
    乙右向量: &[Vec<f64>],
    乙p_obs: &[f64],
) -> 谱等价结果 {
    let 复谱距离 = 复谱距离(甲本征值, 乙本征值);
    let 子空间夹角 = 子空间夹角(甲右向量, 乙右向量);
    let 参与度余弦 = 参与度余弦(甲p_obs, 乙p_obs);
    let 椭圆一致性 = 椭圆一致性(甲本征值, 乙本征值);
    // 第271批: 椭圆第4判据——两侧≥3本征值才设卡(<0.3); 不可算不设卡
    let 椭圆通过 = match 椭圆一致性 {
        Some(Δ) => Δ < 0.3,
        None => true,
    };
    let 谱等价 = 复谱距离 < 0.15 && 子空间夹角 > 0.8 && 参与度余弦 > 0.9 && 椭圆通过;
    let τ_ellipse_甲 = 椭圆参数(甲本征值);
    let τ_ellipse_乙 = 椭圆参数(乙本征值);
    let 判定 = if 谱等价 {
        match 椭圆一致性 {
            Some(Δ) => format!(
                "谱等价：复谱距离 {:.3}<0.15 ∧ 子空间夹角 {:.3}>0.8 ∧ 参与度余弦 {:.3}>0.9 ∧ 椭圆一致性 {:.3}<0.3",
                复谱距离, 子空间夹角, 参与度余弦, Δ
            ),
            None => format!(
                "谱等价：复谱距离 {:.3}<0.15 ∧ 子空间夹角 {:.3}>0.8 ∧ 参与度余弦 {:.3}>0.9（椭圆判据不可算不设卡）",
                复谱距离, 子空间夹角, 参与度余弦
            ),
        }
    } else {
        match 椭圆一致性 {
            Some(Δ) => format!(
                "谱不等价：复谱距离 {:.3}（<0.15）/ 子空间夹角 {:.3}（>0.8）/ 参与度余弦 {:.3}（>0.9）/ 椭圆一致性 {:.3}（<0.3）",
                复谱距离, 子空间夹角, 参与度余弦, Δ
            ),
            None => format!(
                "谱不等价：复谱距离 {:.3}（<0.15）/ 子空间夹角 {:.3}（>0.8）/ 参与度余弦 {:.3}（>0.9）",
                复谱距离, 子空间夹角, 参与度余弦
            ),
        }
    };
    谱等价结果 {
        复谱距离,
        子空间夹角,
        参与度余弦,
        τ_ellipse_甲,
        τ_ellipse_乙,
        椭圆一致性,
        谱等价,
        判定,
    }
}

