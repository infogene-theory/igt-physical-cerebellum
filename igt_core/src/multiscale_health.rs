/// 自由能牌色 — 生存τ分级（自由能文档 §4.2）
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum 牌色 {
    /// <3月：红牌，生存优先，所有外层建议让位于"获取自由能"
    红,
    /// 3-12月：黄牌，限制高风险逆元（创业/转型需谨慎）
    黄,
    /// 12-60月：绿牌，有缓冲执行中长期逆元
    绿,
    /// >60月（5年）：深绿，可投入文明级长τ项目
    深绿,
}

impl 牌色 {
    pub fn 说明(self) -> &'static str {
        match self {
            牌色::红 => "红牌: 生存优先, 外层建议让位于自由能获取",
            牌色::黄 => "黄牌: 限制高风险逆元(创业/转型需谨慎)",
            牌色::绿 => "绿牌: 有缓冲执行中长期逆元",
            牌色::深绿 => "深绿: 可投入文明级长τ项目",
        }
    }
}

/// 生存τ = 储蓄/月耗散（单位：月）。耗散≤0 或非法输入 → None。
pub fn 生存τ月(储蓄: f64, 月耗散: f64) -> Option<f64> {
    if 月耗散 <= 1e-9 || !储蓄.is_finite() || !月耗散.is_finite() || 储蓄 < 0.0 {
        return None;
    }
    Some(储蓄 / 月耗散)
}

/// 生存τ → 牌色分级
pub fn 生存τ牌(生存τ_月: f64) -> 牌色 {
    if 生存τ_月 < 3.0 {
        牌色::红
    } else if 生存τ_月 < 12.0 {
        牌色::黄
    } else if 生存τ_月 < 60.0 {
        牌色::绿
    } else {
        牌色::深绿
    }
}

