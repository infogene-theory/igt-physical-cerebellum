/// 单层状态输入（Agent 侧采集后传入）
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 层状态 {
    pub 尺度: 扰动尺度,
    /// 该层结构熵债 D_s（0=完全健康，≥0.6 严重失稳）
    pub d_s: f64,
    /// 自由能储备 E_free（None=无数据，不惩罚该维度）
    pub 自由能储备: Option<f64>,
    /// 自由能需求 E_need（None=无数据）
    pub 自由能需求: Option<f64>,
}

/// 单层裕度输出
#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
pub struct 层裕度 {
    pub 尺度: 扰动尺度,
    /// 节律裕度 M^τ = max(0, 1 - D_s/0.6)
    pub m_tau: f64,
    /// 自由能裕度 M^E = min(1, E_free/E_need)（无数据=1）
    pub m_e: f64,
    /// 总裕度 M_s = M^τ × M^E
    pub m_s: f64,
    /// 建议权重 w_s = M_s × ∏内层M_r（连续降权，非开关）
    pub w_s: f64,
}

// ============================================================================
// 五层权重引擎
// ============================================================================

/// D_s 归零阈值（≥此值节律裕度为 0）
pub const D_S红牌阈值: f64 = 0.6;

/// 计算五层裕度与建议权重
///
/// 输入须覆盖全部五尺度（缺层用 D_s=0 + 无自由能数据的默认态补齐）。
/// 返回按内→外序的层裕度；w_s = M_s × 所有更内层 M_s 的连乘。
pub fn 计算五层权重(状态: &[层状态; 5]) -> [层裕度; 5] {
    let mut 出 = Vec::with_capacity(5);
    let mut 内层连乘 = 1.0f64;
    for (i, s) in 状态.iter().enumerate() {
        let m_tau = 节律裕度(s.d_s);
        let m_e = 自由能裕度(s.自由能储备, s.自由能需求);
        let m_s = m_tau * m_e;
        let w_s = m_s * 内层连乘;
        出.push(层裕度 {
            尺度: 全尺度[i],
            m_tau,
            m_e,
            m_s,
            w_s,
        });
        内层连乘 *= m_s;
    }
    let mut arr = [层裕度 {
        尺度: 扰动尺度::身体,
        m_tau: 0.0,
        m_e: 0.0,
        m_s: 0.0,
        w_s: 0.0,
    }; 5];
    arr.copy_from_slice(&出);
    arr
}

/// 节律裕度 M^τ = max(0, 1 - D_s/0.6)
pub fn 节律裕度(d_s: f64) -> f64 {
    (1.0 - d_s / D_S红牌阈值).max(0.0)
}

/// 自由能裕度 M^E = min(1, E_free/E_need)；任一为 None 或非法输入 → 1.0（不惩罚）
pub fn 自由能裕度(储备: Option<f64>, 需求: Option<f64>) -> f64 {
    match (储备, 需求) {
        (Some(e), Some(n)) if n > 1e-9 && e.is_finite() => (e / n).min(1.0),
        _ => 1.0,
    }
}

