/// 扰动尺度 — 五层，数组序固定为内→外（权重链依赖此序）
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum 扰动尺度 {
    身体,
    亲密,
    组织,
    国家,
    文明,
}

/// 全部五尺度（内→外固定序）
pub const 全尺度: [扰动尺度; 5] = [
    扰动尺度::身体,
    扰动尺度::亲密,
    扰动尺度::组织,
    扰动尺度::国家,
    扰动尺度::文明,
];

impl 扰动尺度 {
    /// 尺度索引（0=身体最内，4=文明最外）
    pub fn 索引(self) -> usize {
        match self {
            扰动尺度::身体 => 0,
            扰动尺度::亲密 => 1,
            扰动尺度::组织 => 2,
            扰动尺度::国家 => 3,
            扰动尺度::文明 => 4,
        }
    }

    /// 展示名
    pub fn 名称(self) -> &'static str {
        match self {
            扰动尺度::身体 => "身体",
            扰动尺度::亲密 => "亲密",
            扰动尺度::组织 => "组织",
            扰动尺度::国家 => "国家",
            扰动尺度::文明 => "文明",
        }
    }
}

