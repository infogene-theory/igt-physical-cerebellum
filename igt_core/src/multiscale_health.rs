/// 失稳类型（多尺度框架 §3.3）——决定逆元方向完全不同
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum 失稳类型 {
    /// 个别模跑出椭圆，S 可能下降 → 调节自己
    个人失稳,
    /// 整个椭圆漂移（所有模 γ 同向增大），S 不变 → 认知重构+定位调整，
    /// 不要用个人逆元对抗宏观场（会耗尽）
    环境剧变,
    /// 无明显失稳信号
    无明显失稳,
}

/// 谱漂移观测输入
#[derive(Debug, Clone)]
pub struct 谱漂移观测 {
    /// 各本征模的 γ 变化量（正=回归变快/紧绷，负=松弛）
    pub 各模γ变化: Vec<f64>,
    /// D_s 变化量（正=熵债上升）
    pub d_s变化: f64,
    /// S（结构度）变化量（正=结构增强，负=结构受损）
    pub s变化: f64,
}

/// 判别失稳类型
///
/// 环境剧变: γ 方向一致率≥0.8 且 γ 中位数上升 且 S 稳定(|ΔS|<0.05)
/// 个人失稳: γ 方向分裂(一致率<0.5) 且 有模显著紧绷 且 S 下降
pub fn 判别失稳类型(观测: &谱漂移观测) -> 失稳类型 {
    if 观测.各模γ变化.len() < 2 {
        return 失稳类型::无明显失稳;
    }
    let 上升数 = 观测.各模γ变化.iter().filter(|g| **g > 0.0).count();
    let 一致率 = 上升数 as f64 / 观测.各模γ变化.len() as f64;
    let mut 排序γ = 观测.各模γ变化.clone();
    排序γ.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
    let 中位γ = 排序γ[排序γ.len() / 2];
    let s稳定 = 观测.s变化.abs() < 0.05;

    if 一致率 >= 0.8 && 中位γ > 0.0 && s稳定 {
        return 失稳类型::环境剧变;
    }
    let 一致率低 = 一致率 < 0.5;
    let 有紧绷 = 观测.各模γ变化.iter().any(|g| *g > 0.0);
    if 一致率低 && 有紧绷 && 观测.s变化 < 0.0 {
        return 失稳类型::个人失稳;
    }
    失稳类型::无明显失稳
}

