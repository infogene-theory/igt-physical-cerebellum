    /// ④⑤ 照料者模式: 老人不可逆 × 照料者状态 → 预警对象=输出方
    #[test]
    fn 测试_照料者预警() {
        // 老人基线: 单调退化(不可逆)
        let 老人序列: Vec<f64> = (0..12).map(|i| 0.15 + 0.35 * (i as f64 / 11.0)).collect();
        let 老人 = 判别可逆性(&老人序列);
        assert_eq!(老人.可逆性, 可逆性::不可逆失稳);

        // ④ 照料者高企上升 → 耗竭风险高 + 接纳性建议
        let 照料者恶化: Vec<f64> = (0..10).map(|i| 0.30 + 0.25 * (i as f64 / 9.0)).collect();
        let 预警 = 照料者预警(&老人, &照料者恶化);
        assert_eq!(预警.预警对象, "照料者(输出方)");
        assert!(预警.耗竭风险 > 0.5, "耗竭风险应高: {}", 预警.耗竭风险);
        assert_eq!(预警.逆元建议, Some(逆元类型::接纳性逆元));
        assert!(预警.说明.contains("不在老人身上"), "点明逆元位置: {}", 预警.说明);

        // ⑤ 照料者平稳低熵债 → 风险低 + 无建议
        let 照料者平稳 = vec![0.15, 0.18, 0.14, 0.16, 0.15, 0.17, 0.14, 0.16];
        let 预警2 = 照料者预警(&老人, &照料者平稳);
        assert!(预警2.耗竭风险 < 0.2, "平稳照料者风险低: {}", 预警2.耗竭风险);
        assert!(预警2.逆元建议.is_none());
        assert!(预警2.说明.contains("尚低") || 预警2.说明.contains("监测"), "{}", 预警2.说明);

        // 对照: 老人可回归 → 走常规通道
        let 老人平稳 = vec![0.2, 0.3, 0.15, 0.25, 0.2, 0.3, 0.15, 0.25];
        let 老人可回归 = 判别可逆性(&老人平稳);
        let 预警3 = 照料者预警(&老人可回归, &照料者恶化);
        assert_eq!(预警3.逆元建议, None, "可回归失稳不走接纳性");
        assert!(预警3.说明.contains("可回归"));
    }
