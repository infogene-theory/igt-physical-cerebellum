/// 照料者预警结果 — 失稳主体 ≠ 预警受益主体
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 照料者预警 {
    /// 预警对象恒为输出方（照料者）——老人没垮照料者先垮才是真正的失稳边缘
    pub 预警对象: String,
    /// 耗竭风险 0..1（趋势强度 × 当前 D_s 相对失稳阈值的比例，截断）
    pub 耗竭风险: f64,
    /// 逆元建议
    pub 逆元建议: Option<逆元类型>,
    pub 说明: String,
}

/// 照料者预警 — 单向抽取结构（衰老照料）下的预警与逆元
///
/// 原理（不可逆失稳文档 §二/§四）：
/// 1. 老人（输入方）失稳不可逆，Agent 治不了它，只能提前预警时间窗；
/// 2. 真正可管理的是照料者（输出方）——赡养是逆元逐渐缺失、趋向幺半群的结构；
/// 3. 当照料者自身 D_s 单调上升且高企时，预警对象必须是照料者；
/// 4. 对老人的不可逆失稳，逆元建议 = 接纳性（认知逆元），非对抗性。
pub fn 照料者预警(老人判定: &可逆性判定, 照料者d_s序列: &[f64]) -> 照料者预警 {
    let 照料者判定 = 判别可逆性(照料者d_s序列);
    let 当前d_s = 照料者d_s序列.last().copied().unwrap_or(0.0);
    // 耗竭风险 = 照料者自身恶化趋势 × 当前熵债占失稳阈值(0.6)比例
    let 相对熵债 = (当前d_s / 0.6).clamp(0.0, 1.0);
    let 趋势 = 照料者判定.趋势强度.clamp(0.0, 1.0);
    let 耗竭风险 = (趋势 * 相对熵债).clamp(0.0, 1.0);

    match 老人判定.可逆性 {
        可逆性::不可逆失稳 => {
            let 建议 = if 耗竭风险 > 0.5 {
                Some(逆元类型::接纳性逆元)
            } else {
                None
            };
            let 说明 = if 耗竭风险 > 0.5 {
                format!(
                    "老人失稳不可逆(趋势{:.2}), 照料者耗竭风险{:.2}高企: 停止对抗性耗散, \
                     把自由能转向照护质量/陪伴质量/自身缓冲; 逆元在跨代传导与意义层, 不在老人身上",
                    老人判定.趋势强度, 耗竭风险
                )
            } else {
                format!(
                    "老人失稳不可逆(趋势{:.2}), 照料者耗竭风险{:.2}尚低: 持续监测照料者自身 D_s 与 τ_surv",
                    老人判定.趋势强度, 耗竭风险
                )
            };
            照料者预警 {
                预警对象: "照料者(输出方)".to_string(),
                耗竭风险,
                逆元建议: 建议,
                说明,
            }
        }
        可逆性::可回归失稳 => 照料者预警 {
            预警对象: "照料者(输出方)".to_string(),
            耗竭风险,
            逆元建议: None,
            说明: format!(
                "老人失稳可回归(趋势{:.2}), 常规逆元通道; 照料者耗竭风险{:.2}",
                老人判定.趋势强度, 耗竭风险
            ),
        },
        可逆性::证据不足 => 照料者预警 {
            预警对象: "照料者(输出方)".to_string(),
            耗竭风险,
            逆元建议: None,
            说明: "老人侧基线序列不足, 无法判别可逆性; 先积累观测".to_string(),
        },
    }
}

