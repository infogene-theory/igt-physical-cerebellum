/// 可逆性 — 失稳的两类本质区别
///
/// 可回归失稳 = 点跑出椭圆（稳态锚点还在，逆元可拉回）；
/// 不可逆失稳 = 椭圆本身缩小下沉（锚点单调退化，回归目标已不存在）。
/// 对不可逆失稳套"失稳→逆元→回归"逻辑必然持续失败。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum 可逆性 {
    /// 锚点还在，逆元可拉回
    可回归失稳,
    /// 锚点单调下沉（椭圆缩小），接纳是最优逆元
    不可逆失稳,
    /// 基线序列过短（<6 点），无法判趋势
    证据不足,
}

/// 可逆性判定结果
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 可逆性判定 {
    pub 可逆性: 可逆性,
    /// Mann-Kendall S 归一化趋势强度（-1..1，正=恶化方向单调）
    pub 趋势强度: f64,
    /// 序列均值
    pub 基线均值: f64,
}

/// 判别可逆性 — 从熵债 D_s 基线时序检测锚点是否单调下沉
///
/// 输入：等间隔采样的 D_s 基线序列（上升 = 恶化）。
/// 方法：Mann-Kendall S 统计量（所有对 sign(x_j - x_i) 之和 / 对数，∈[-1,1]）
/// + 最小二乘斜率显著性（|斜率|/均值 > 0.05）。
/// len < 6 → 证据不足；S_norm > 0.6 且斜率显著 → 不可逆失稳；否则可回归失稳。
pub fn 判别可逆性(d_s_基线序列: &[f64]) -> 可逆性判定 {
    let n = d_s_基线序列.len();
    if n < 6 || d_s_基线序列.iter().any(|v| !v.is_finite() || *v < 0.0) {
        return 可逆性判定 {
            可逆性: 可逆性::证据不足,
            趋势强度: 0.0,
            基线均值: 均值(d_s_基线序列),
        };
    }
    // Mann-Kendall S（恶化方向 = 正）
    let 对数 = (n * (n - 1) / 2) as f64;
    let mut s = 0.0f64;
    for i in 0..n {
        for j in (i + 1)..n {
            s += (d_s_基线序列[j] - d_s_基线序列[i]).signum();
        }
    }
    let 趋势强度 = s / 对数;

    // 最小二乘斜率（x = 0..n-1）
    let mx = (n - 1) as f64 / 2.0;
    let my = 均值(d_s_基线序列);
    let mut 分子 = 0.0;
    let mut 分母 = 0.0;
    for (i, v) in d_s_基线序列.iter().enumerate() {
        分子 += (i as f64 - mx) * (v - my);
        分母 += (i as f64 - mx).powi(2);
    }
    let 斜率 = 分子 / 分母;
    let 相对斜率 = if my > 1e-9 { 斜率 / my } else { 0.0 };

    let 不可逆 = 趋势强度 > 0.6 && 相对斜率 > 0.05;
    可逆性判定 {
        可逆性: if 不可逆 {
            可逆性::不可逆失稳
        } else {
            可逆性::可回归失稳
        },
        趋势强度,
        基线均值: my,
    }
}

fn 均值(v: &[f64]) -> f64 {
    if v.is_empty() {
        0.0
    } else {
        v.iter().sum::<f64>() / v.len() as f64
    }
}

impl 逆元类型 {
    /// 第234批新增：接纳性逆元说明
    pub const 接纳性说明: &'static str =
        "接纳性逆元: 停止对抗性耗散, 把自由能转向还能维持的(不可逆失稳的最优逆元)";
}

/// 建议逆元 — 可逆性感知的逆元推荐
///
/// 不可逆失稳 → 接纳性逆元（不看扰动τ——对抗不可逆 = 加速失稳的高频扰动注入）；
/// 可回归失稳 → 按扰动τ分段匹配（第229批原逻辑）；
/// 证据不足 → None。
pub fn 建议逆元(扰动τ_秒: f64, 判定: &可逆性判定) -> Option<逆元类型> {
    match 判定.可逆性 {
        可逆性::不可逆失稳 => Some(逆元类型::接纳性逆元),
        可逆性::可回归失稳 => 匹配逆元类型(扰动τ_秒),
        可逆性::证据不足 => None,
    }
}

