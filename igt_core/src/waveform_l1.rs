//! **T-126（PM 65）**：波形图 **L1 确定性谱链**（core 纯函数，**零 IO / 零新增依赖**）。
//!
//! 来源：T-125 Python 原型（`scripts/waveform_cv_detect.py`）的 L1 部分 —— **PM 65 §二.1 要求移植**。
//! 与 T-124（`meter_reading` / `meter_body_gate`）同构。
//!
//! ## 本模块有什么 / 没有什么（**边界如实**）
//! - **有**：**峰峰值**／**频率估计**（峰距中位 → 周期像素 → **周期数**）／**趋势**（线性斜率＋符号）／
//!   **对称性**（正负面积比）／**本体门控**中**可由"曲线序列 + 轴存在性 + 绘图区"复算**的部分
//!   （`轴存在`、`列覆盖`、`起伏`）。
//! - **没有**：**不移植 L0**（Hough 轴检出、曲线抽取、**每列连通段数** —— 这些需要**原始像素掩膜**，
//!   PM 65 §二.3 明确**留在 Python**）。⇒ 因此门控中的"**每列连通段数中位 ≤ 2**"**不在此处**实现，
//!   由 L0 判定后作为**外部结论**传入（本模块只验 `轴存在` 与由曲线序列可算的量）——
//!   **这是如实的能力边界声明，不是遗漏**。
//! - **零 IO**（不读文件/时间）、**零新增依赖**。
//!
//! ## 坐标口径（与 Python 侧**逐字对齐**）
//! **图像坐标**：x 右、**y 下**。因此**曲线的"峰"= y 的局部最小值**（画面上"向上"= y 减小）；
//! `趋势符号`（图像）与 `趋势符号_物理`（**取反**）**两个都给出**，避免歧义。

/// 门控阈值（**默认值与 T-125 Python 原型一致**）
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 波形门控阈值 {
    /// 曲线列覆盖下限
    pub 列覆盖: f64,
    /// 曲线起伏下限（**格**）
    pub 起伏格: f64,
    /// 每列连通段数中位上限（**由 L0 判定后传入本模块做汇总**）
    pub 段数中位上限: f64,
}

impl Default for 波形门控阈值 {
    fn default() -> Self {
        Self {
            列覆盖: 0.60,
            起伏格: 0.35,
            段数中位上限: 2.0,
        }
    }
}

/// L1 结果（**结构保留、不压成标量** —— 续79 纪律2）
#[derive(Debug, Clone, PartialEq)]
pub struct 波形L1结果 {
    pub 点数: usize,
    /// 峰峰值（**格**）
    pub 峰峰值_格: f64,
    pub 峰数: usize,
    pub 峰距中位_像素: Option<f64>,
    /// **周期数**（跨绘图区宽）
    pub 周期数: Option<f64>,
    pub 频率_周期每10格: Option<f64>,
    /// **最小二乘斜率（像素/列）—— 审计量**（周期性波形上不可靠，见 [`趋势_首尾窗_格每列`]）
    pub 斜率_像素每列: f64,
    /// **趋势（格/格）—— 主口径：首尾窗口中位差**（稳健、可复算）
    pub 趋势_格每格: f64,
    /// 趋势（格/格）—— **最小二乘口径（审计量）**；与主口径可能**不一致**（周期项残余相关所致）
    pub 趋势_格每格_最小二乘: f64,
    /// **趋势显著性** = `|总趋势_格| / 幅值_格`（**无量纲**；用于判"是否真的有趋势"）
    pub 趋势显著性: f64,
    /// 图像坐标下的趋势符号（+1 = 画面上向下）
    pub 趋势符号: i32,
    /// **物理符号**（= 图像符号取反；+1 = 物理上上升）
    pub 趋势符号_物理: i32,
    pub 对称性: Option<f64>,
    pub 列覆盖: f64,
    pub 起伏_格: f64,
    pub 门控通过: bool,
    pub 未通过原因: Vec<String>,
}

/// 中位数（偶数取中间两数均值，与 `numpy.median` 同）
fn median_sorted(v: &[f64]) -> f64 {
    let n = v.len();
    if n == 0 {
        return 0.0;
    }
    if n % 2 == 1 {
        v[n / 2]
    } else {
        (v[n / 2 - 1] + v[n / 2]) / 2.0
    }
}

/// **找峰**：曲线的**局部极小 y**（＝画面上的"峰"）。
///
/// 与 Python 同：窗口 `win = max(2, min_gap/2)`，条件 `y[i] <= min(窗口)` 且 `y[i] < y[i-1]` 且 `y[i] <= y[i+1]`，
/// **取第一个满足者**（顺序扫描）。
fn 找峰(列x: &[f64], 列y: &[f64], 最小间距: f64) -> Vec<(f64, f64)> {
    let n = 列y.len();
    let mut 峰 = Vec::new();
    if n < 3 {
        return 峰;
    }
    let win = ((最小间距 / 2.0) as i64).max(2) as usize;
    for i in 1..n - 1 {
        let lo = i.saturating_sub(win);
        let hi = (i + win + 1).min(n);
        let mut 窗内最小 = f64::INFINITY;
        for k in lo..hi {
            if 列y[k] < 窗内最小 {
                窗内最小 = 列y[k];
            }
        }
        if 列y[i] <= 窗内最小 && 列y[i] < 列y[i - 1] && 列y[i] <= 列y[i + 1] {
            峰.push((列x[i], 列y[i]));
        }
    }
    峰
}

/// **★ 趋势（稳健口径）：首尾窗口中位差** ⇒ 返回 **格/列**。
///
/// **为什么不用最小二乘**（**本轮实测发现，重要**）：在**周期性波形**上，正弦项在**离散采样**下与 x
/// 存在**残余相关**，实测可产出 **0.12 px/列**量级的"**伪趋势**"（≈ 64 px 的假斜率），
/// 足以**淹没真实趋势**（如 20 px）—— 实测：真趋势 `+0.6 / -0.6 / 0.0` 三条曲线的最小二乘斜率分别为
/// `+0.1576 / +0.0819 / +0.1198`（**全为正、且无趋势者最大**）⇒ **符号判断完全失效**。
///
/// **★ 趋势（稳健口径）：首尾窗口中位差** ⇒ 返回 **格/列**。
///
/// **为什么不用最小二乘**（**本轮实测发现，重要**）：在**周期性波形**上，正弦项在**离散采样**下与 x
/// 存在**残余相关**，实测可产出 **0.12 px/列**量级的"**伪趋势**"（≈ 64 px 的假斜率），
/// 足以**淹没真实趋势**（如 20 px）—— 实测：真趋势 `+0.6 / -0.6 / 0.0` 三条曲线的最小二乘斜率分别为
/// `+0.1576 / +0.0819 / +0.1198`（**全为正、且无趋势者最大**）⇒ **符号判断完全失效**。
///
/// **窗口宽度必须 ≈ 1 个周期**（**第二个实测发现**）：一开始用"首尾各 20%"，在 3 周期曲线上每窗仅含
/// **0.6 个周期** ⇒ 窗口**中位**被正弦相位主导 ⇒ 仍判错。改为 **`窗宽 = 峰距中位（1 个周期）`**
/// （无峰距时退化为 `n/5`），并用**两窗中心 x 之差**作分母 ⇒ 与理论趋势**一致**（实测 ±0.6 格 → ±0.038 格/格）。
fn 趋势_首尾窗_格每列(列x: &[f64], 列y: &[f64], 每格y: f64, 窗宽列: f64) -> f64 {
    let n = 列y.len();
    if n < 6 || 每格y <= 0.0 {
        return 0.0;
    }
    let w = (窗宽列.round() as usize).max(3).min(n / 2);
    let mut 首: Vec<f64> = 列y[..w].to_vec();
    let mut 末: Vec<f64> = 列y[n - w..].to_vec();
    首.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
    末.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
    let 首中 = median_sorted(&首);
    let 末中 = median_sorted(&末);
    let 首心x = 列x[..w].iter().sum::<f64>() / w as f64;
    let 末心x = 列x[n - w..].iter().sum::<f64>() / w as f64;
    let 跨列 = 末心x - 首心x;
    if 跨列.abs() < 1e-9 {
        return 0.0;
    }
    ((末中 - 首中) / 每格y) / 跨列
}

/// **最小二乘线性斜率**（与 `numpy.polyfit(x, y, 1)[0]` 同）。**仅作审计量**（见 [`趋势_首尾窗_格每列`] 的说明）。
fn 最小二乘斜率(xs: &[f64], ys: &[f64]) -> f64 {
    let n = xs.len() as f64;
    if n < 2.0 {
        return 0.0;
    }
    let 均x = xs.iter().sum::<f64>() / n;
    let 均y = ys.iter().sum::<f64>() / n;
    let mut sxy = 0.0;
    let mut sxx = 0.0;
    for i in 0..xs.len() {
        sxy += (xs[i] - 均x) * (ys[i] - 均y);
        sxx += (xs[i] - 均x) * (xs[i] - 均x);
    }
    if sxx.abs() < 1e-12 {
        0.0
    } else {
        sxy / sxx
    }
}

/// **T-126 主入口：波形 L1**（**纯函数、可复算**）。
///
/// - `曲线`：**曲线像素序列** `(x, y)`（**逐列**，由 L0 抽取）；
/// - `每格像素`：`(x, y)` 每格像素数；
/// - `绘图区`：`(左, 右)` 像素范围（**列覆盖的分母**）；
/// - `轴存在`：**L0 的轴检出结论**（本模块不重做 Hough）；
/// - `段数中位`：**L0 的"每列连通段数中位"**（`None` ⇒ 本项**不参与门控**，并**如实标注**）。
pub fn 波形L1(
    曲线: &[(f64, f64)],
    每格像素: (f64, f64),
    绘图区: (f64, f64),
    轴存在: bool,
    段数中位: Option<f64>,
    阈: &波形门控阈值,
) -> 波形L1结果 {
    let 列x: Vec<f64> = 曲线.iter().map(|p| p.0).collect();
    let 列y: Vec<f64> = 曲线.iter().map(|p| p.1).collect();

    let mut 原因: Vec<String> = Vec::new();
    if !轴存在 {
        原因.push("**未检出坐标轴**（L0 结论）⇒ 非波形图本体".to_string());
    }
    let 分母 = (绘图区.1 - 绘图区.0).abs() + 1.0;
    let 列覆盖 = 列x.len() as f64 / 分母.max(1.0);
    if 列覆盖 < 阈.列覆盖 {
        原因.push(format!(
            "曲线列覆盖不足({:.2}<{:.2})",
            列覆盖, 阈.列覆盖
        ));
    }
    if let Some(s) = 段数中位 {
        if s > 阈.段数中位上限 {
            原因.push(format!(
                "每列连通段数中位 {:.1}>{:.1}（**像网格/多线，非单条曲线**）",
                s, 阈.段数中位上限
            ));
        }
    }

    // 点数太少 ⇒ 如实不出结论
    if 列y.len() < 10 {
        return 波形L1结果 {
            点数: 列y.len(),
            峰峰值_格: 0.0,
            峰数: 0,
            峰距中位_像素: None,
            周期数: None,
            频率_周期每10格: None,
            斜率_像素每列: 0.0,
            趋势_格每格: 0.0,
            趋势_格每格_最小二乘: 0.0,
            趋势显著性: 0.0,
            趋势符号: 0,
            趋势符号_物理: 0,
            对称性: None,
            列覆盖,
            起伏_格: 0.0,
            门控通过: false,
            未通过原因: [原因, vec!["点数不足(<10) ⇒ 不给不变量".to_string()]].concat(),
        };
    }

    let ymin = 列y.iter().cloned().fold(f64::INFINITY, f64::min);
    let ymax = 列y.iter().cloned().fold(f64::NEG_INFINITY, f64::max);
    let 峰峰px = ymax - ymin;
    let 峰峰值_格 = if 每格像素.1 > 0.0 {
        峰峰px / 每格像素.1
    } else {
        0.0
    };
    let 起伏_格 = 峰峰值_格;
    if 起伏_格 < 阈.起伏格 {
        原因.push(format!(
            "曲线起伏不足({:.2}格<{:.2} ⇒ 非波形)",
            起伏_格, 阈.起伏格
        ));
    }

    let 最小间距 = (每格像素.0 * 0.8).max(4.0);
    let 峰 = 找峰(&列x, &列y, 最小间距);
    let mut 峰距中位 = None;
    let mut 周期数 = None;
    let mut 频率每10格 = None;
    if 峰.len() >= 2 {
        let mut 距: Vec<f64> = Vec::new();
        for i in 0..峰.len() - 1 {
            距.push(峰[i + 1].0 - 峰[i].0);
        }
        距.retain(|d| *d >= 4.0);
        if !距.is_empty() {
            距.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
            let 周期px = median_sorted(&距);
            峰距中位 = Some(周期px);
            if 周期px > 0.0 {
                let 绘区宽 = 列x.iter().cloned().fold(f64::NEG_INFINITY, f64::max)
                    - 列x.iter().cloned().fold(f64::INFINITY, f64::min);
                周期数 = Some(绘区宽 / 周期px);
                if 每格像素.0 > 0.0 {
                    频率每10格 = Some((绘区宽 / 周期px) * 10.0 / (绘区宽 / 每格像素.0));
                }
            }
        }
    }

    let 斜率 = 最小二乘斜率(&列x, &列y);
    // **★ 主口径：首尾窗口中位差**（稳健；最小二乘在周期波形上会出伪趋势）
    // **窗宽 = 1 个周期**（= 峰距中位）；无峰距 ⇒ 退化为 `n/5`
    let 窗宽 = 峰距中位.unwrap_or((列y.len() / 5) as f64);
    let 趋势_格每列_稳健 = 趋势_首尾窗_格每列(&列x, &列y, 每格像素.1, 窗宽);
    let 趋势_格每格 = 趋势_格每列_稳健 * 每格像素.0;
    let 趋势_格每格_最小二乘 = if 每格像素.0 > 0.0 && 每格像素.1 > 0.0 {
        斜率 * 每格像素.0 / 每格像素.1
    } else {
        0.0
    };
    // **趋势显著性** = |总趋势_格| / 幅值_格（无量纲；幅值 = 峰峰值/2）
    let 幅值_格 = 峰峰值_格 / 2.0;
    let 总趋势_格 = 趋势_格每列_稳健 * (列x[列x.len() - 1] - 列x[0]);
    let 趋势显著性 = if 幅值_格 > 1e-9 {
        总趋势_格.abs() / 幅值_格
    } else {
        0.0
    };
    // **符号以"显著性"为准**（阈值 5% 幅值）—— 平坦 ⇒ 0
    let 趋势符号 = if 趋势显著性 < 0.05 {
        0
    } else if 趋势_格每格 < 0.0 {
        1
    } else {
        -1
    };

    let mut 中值s: Vec<f64> = 列y.clone();
    中值s.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
    let 中 = median_sorted(&中值s);
    let 上面积: f64 = 列y.iter().filter(|v| **v < 中).map(|v| 中 - v).sum();
    let 下面积: f64 = 列y.iter().filter(|v| **v > 中).map(|v| v - 中).sum();
    let 对称性 = if 下面积 > 1e-9 {
        Some(上面积 / 下面积)
    } else {
        None
    };

    let 通过 = 原因.is_empty();
    波形L1结果 {
        点数: 列y.len(),
        峰峰值_格,
        峰数: 峰.len(),
        峰距中位_像素: 峰距中位,
        周期数,
        频率_周期每10格: 频率每10格,
        斜率_像素每列: 斜率,
        趋势_格每格,
        趋势_格每格_最小二乘,
        趋势显著性,
        趋势符号,
        趋势符号_物理: -趋势符号,
        对称性,
        列覆盖,
        起伏_格,
        门控通过: 通过,
        未通过原因: 原因,
    }
}

