//! τ谱共振融合（第112批·F2，论文 Paper A《跨模态τ谱共振》工程落地）
//!
//! 理论核心（Paper A）:
//! - 每个模态/系统尺度有本征弛豫时间谱 τ谱 = {τ_1, τ_2, ...}
//! - 两个模态 τ_i/τ_j ≈ n/m（小整数比）→ 模式锁定（mode-locking）→ 共振融合
//! - 跨模态耦合强度: κ_ij = Σ_{n,m≤K} exp(-(τ_i/τ_j - n/m)² / (2σ²))
//! - 共振门控: κ_ij > κ_threshold(0.3) → 建立融合通道; 否则门控关闭
//! - 融合权重: w_m = Σ_{n≠m} κ_mn / Σ_k Σ_{n≠k} κ_kn（等价Cross-Attention softmax, 免学习）
//!
//! 生物证据（Paper A 表1）: G011三尺度τ(60/110/200ms)≈2:1级联,
//! G009/G010(190/350ms)≈2:1, G008(22/115ms)≈5:1。
//!
//! 工程优势: O(N²·k²·K²) 远小于 Cross-Attention O(N²·d²); 白盒可解释; 天然噪声门控。
//!
//! ## ⚠️ 第194批（Claw审计 R3）双κ边界声明
//!
//! 本模块 κ_fusion 与 `resonance_filter.rs` κ_filter 是**两套 κ**（阶段不同）:
//!   - **本模块 κ_fusion**: 融合权重——已入场模态间耦合强度
//!     - 语义: 如何加权融合多模态（耦合, 高斯核软判定）
//!     - 阶段: 进场后（融合侧）; 公式: κ_ij = Σexp(-(τ_i/τ_j-n/m)²/2σ²), 门控 κ>0.3
//!     - 调用方: 造波/谱蒸馏/第192批共振对接建议
//!   - **`resonance_filter.rs` κ_filter**: 滤波判定——LLM 输出入场闸门
//!     - 语义: 是否允许外部内容进入 τEngine 回路（准入, 硬判定, 不过即丢弃）
//!     - 阶段: 进场前（输入侧）; 公式: sinc+频率整数比硬判定+振幅/手性
//!     - 调用方: tau_engine_loop.rs
//!   - 边界: **滤波=进场前准入 / 融合=进场后耦合**——阶段不同, 不物理合并;
//!     命名统一 κ_filter(滤波) / κ_fusion(融合)。

use serde::{Deserialize, Serialize};

/// 最大考虑的小整数（K=5 对应 1:1 到 5:1，Paper A 定义）
pub const 最大整数比: usize = 5;
/// 锁相窗口宽度 σ（由系统噪声决定; 生物数据偏差8-9% → σ取0.1, 兼顾容差与门控锐度）
pub const 锁相窗口σ: f64 = 0.1;
/// 共振门控阈值（κ_ij > 阈值 → 建立融合通道; Paper A 定义 κ_threshold=0.3）
pub const 共振门控阈值: f64 = 0.3;

/// 单个模态/尺度的 τ 谱
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct τ谱 {
    /// 模态/尺度名称
    pub 名称: String,
    /// 本征弛豫时间集合（秒, 从小到大）
    pub τ集合: Vec<f64>,
}

/// 共振融合结果
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 共振融合结果 {
    /// 融合权重（每模态, 与输入顺序对齐）
    pub 权重: Vec<f64>,
    /// 耦合矩阵（N×N, 上三角有效; κ_ij）
    pub 耦合矩阵: Vec<Vec<f64>>,
    /// 通过门控的模态对（共振通道）
    pub 共振通道: Vec<(usize, usize)>,
    /// 被门控的模态对（不融合）
    pub 门控对: Vec<(usize, usize)>,
    /// 融合描述
    pub 描述: String,
}

/// 计算单对时间常数的共振贡献（双向最近整数比，κ ∈ [0,1]）
///
/// 检查 τ_a/τ_b 与 τ_b/τ_a 两个方向的最近小整数比：
/// - 若比值落在 K 范围内（1/5 ~ 5/1）的整数比窗口内 → 高斯核 κ≈1
/// - 若比值偏离所有小整数比（非锁相）→ κ→0（伪共振修复: 0.0318 vs 1/5 偏差0.168 在 σ=0.1 下核≈0.24<0.3）
pub fn 单对共振贡献(τ_a: f64, τ_b: f64) -> f64 {
    if τ_a <= 0.0 || τ_b <= 0.0 {
        return 0.0;
    }
    let 比 = τ_a / τ_b;
    let 反比 = τ_b / τ_a;
    let mut 最大 = 0.0;
    for n in 1..=最大整数比 {
        for m in 1..=最大整数比 {
            let 目标 = n as f64 / m as f64;
            // 两个方向都检查（n/m 与 m/n）
            for &方向 in &[比, 反比] {
                let 偏差 = 方向 - 目标;
                let 核 = (-偏差 * 偏差 / (2.0 * 锁相窗口σ * 锁相窗口σ)).exp();
                if 核 > 最大 {
                    最大 = 核;
                }
            }
        }
    }
    最大
}

/// 计算模态级耦合强度 κ_ij（取所有时间常数对的加权平均，κ ∈ [0,1]）
///
/// Paper A: "模态级耦合强度取所有时间常数对的最大值或加权和"
/// 这里取加权平均（每τ对贡献叠加求均值）——对多τ模态更鲁棒，且 κ ∈ [0,1]，
/// 使共振门控阈值 0.3 有物理意义。
fn 模态耦合强度(谱i: &τ谱, 谱j: &τ谱) -> f64 {
    let mut 总和 = 0.0;
    let mut 对数 = 0;
    for &τa in &谱i.τ集合 {
        for &τb in &谱j.τ集合 {
            总和 += 单对共振贡献(τa, τb);
            对数 += 1;
        }
    }
    if 对数 == 0 {
        0.0
    } else {
        总和 / 对数 as f64
    }
}

/// 共振融合主算法（Paper A §4）
///
/// # 参数
/// - `模态谱`: 各模态的 τ 谱列表（N个）
/// - `特征z`: 各模态的特征标量/向量（简化用 f64, 用于加权求和）
///
/// # 返回
/// 共振融合结果（权重/耦合矩阵/通道/门控对）
pub fn 共振融合(模态谱: &[τ谱], 特征z: &[f64]) -> 共振融合结果 {
    let n = 模态谱.len();
    let mut 耦合矩阵 = vec![vec![0.0; n]; n];
    let mut 共振通道 = Vec::new();
    let mut 门控对 = Vec::new();

    for i in 0..n {
        for j in (i + 1)..n {
            let κ = 模态耦合强度(&模态谱[i], &模态谱[j]);
            耦合矩阵[i][j] = κ;
            耦合矩阵[j][i] = κ;
            if κ > 共振门控阈值 {
                共振通道.push((i, j));
            } else {
                门控对.push((i, j));
            }
        }
    }

    // 融合权重 w_m = Σ_{n≠m} κ_mn / Σ_k Σ_{n≠k} κ_kn
    let mut 总耦合 = 0.0;
    let mut 权重 = vec![0.0; n];
    for i in 0..n {
        let 行和: f64 = 耦合矩阵[i].iter().sum();
        权重[i] = 行和;
        总耦合 += 行和;
    }
    if 总耦合 > 0.0 {
        for w in 权重.iter_mut() {
            *w /= 总耦合;
        }
    }

    // 融合特征 = Σ w_m · z_m
    let 融合值: f64 = 权重.iter().zip(特征z.iter()).map(|(w, z)| w * z).sum();
    let 共振数 = 共振通道.len();
    let 门控数 = 门控对.len();
    let 通道总数 = 共振数 + 门控数;

    共振融合结果 {
        权重,
        耦合矩阵,
        共振通道,
        门控对,
        描述: format!(
            "{}模态融合: 共振通道{}个, 门控{}个, 融合值={:.4}",
            通道总数, 共振数, 门控数, 融合值
        ),
    }
}

/// 便捷函数: 从 τ 测量结果构 τ 谱（取 τ₀ 和谱分量）
///
/// 输入: 每尺度 τ测量结果（含 τ0 和 谱分量 Vec<f64>）
pub fn 从τ测量构建谱(名称: &str, τ0: f64, 谱分量: &[f64]) -> τ谱 {
    let mut τ集合: Vec<f64> = 谱分量
        .iter()
        .filter(|t| **t > 0.0)
        .copied()
        .collect();
    if τ0 > 0.0 {
        τ集合.push(τ0);
    }
    if τ集合.is_empty() {
        τ集合.push(τ0.max(1e-6));
    }
    τ集合.sort_by(|a, b| a.partial_cmp(b).unwrap());
    τ谱 { 名称: 名称.to_string(), τ集合 }
}

// ==================== F6a 拍频桥（第116批，论文旗舰 v1.3 定理1/推论1）====================
//
// 定理1（拍频-τ比等价）: τ_1/τ_2 = n/m ⟺ f_1/f_2 = m/n ⟺ f_b = |f_1-f_2| = f_2·|m/n-1|
// 推论1（跨尺度捕获, 含 v1.3 修正的消歧）: 慢τ测量 + 拍频 f_b 可推断快τ候选,
// 但 f_1=f_2±f_b 两个候选分支需 M3相位/M1扫频/多拍频一致性消歧, 未消歧时标记"待验证"。
//
// [R1.1 澄清] 此处 f 指**振荡频率 ω/2π 的比值**（同 ω 共振频率比, ARCH-1 v2.1 §4
// 共振造波判据）, **非 τ=1/f 弛豫关系**（τ=1/γ 是衰减率维度, 与 ω 两维独立）。
// 数学形式（τ_1/τ_2 = n/m ⟺ f_1/f_2 = m/n）不变——本批仅注释澄清, 不改公式。

/// 拍频-τ比等价验证结果（定理1）
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 拍频验证结果 {
    /// 输入的 τ_a（秒）
    pub τ_a: f64,
    /// 输入的 τ_b（秒）
    pub τ_b: f64,
    /// 频率比 f_a/f_b = τ_b/τ_a
    pub 频率比: f64,
    /// 实际拍频 f_b = |f_a - f_b|
    pub 拍频: f64,
    /// 由最近整数比预测的期望拍频 f_b = f_a|m/n-1|（以 f_a=1/τ_a 为基频）
    pub 期望拍频: f64,
    /// 最近小整数比 (n, m) 对应 τ_a/τ_b ≈ n/m
    pub 最近整数比: Option<(u32, u32)>,
    /// 定理1三等价是否成立（偏差在窗口 σ 内）
    pub 等价成立: bool,
    /// 期望拍频与实际拍频的相对偏差
    pub 偏差: f64,
    /// 描述
    pub 描述: String,
}

/// 找使 |τ_a/τ_b - n/m| 最小的最近小整数比 (n,m), K=5
pub fn 最近整数比(τ_a: f64, τ_b: f64) -> Option<(u32, u32)> {
    if τ_a <= 0.0 || τ_b <= 0.0 {
        return None;
    }
    let 比 = τ_a / τ_b;
    let 反比 = τ_b / τ_a;
    let mut 最佳: Option<(u32, u32, f64)> = None; // (n, m, 偏差)
    for n in 1..=最大整数比 {
        for m in 1..=最大整数比 {
            let 目标 = n as f64 / m as f64;
            for &方向 in &[比, 反比] {
                let 偏差 = (方向 - 目标).abs();
                if 最佳.map_or(true, |(_, _, d)| 偏差 < d) {
                    最佳 = Some((n as u32, m as u32, 偏差));
                }
            }
        }
    }
    // 若最近比是反比方向命中, 则返回 (m,n) 使 τ_a/τ_b ≈ n/m 语义一致
    let (n, m, 偏差) = 最佳?;
    let 直接 = (比 - n as f64 / m as f64).abs();
    if 直接 <= 偏差 + 1e-12 {
        Some((n, m))
    } else {
        Some((m, n))
    }
}

/// 定理1 拍频-τ比等价验证（第116批·F6a）
///
/// 输入任意两时间常数, 验证三个等价条件是否同时成立:
/// 1. τ_a/τ_b ≈ n/m
/// 2. f_a/f_b ≈ m/n
/// 3. f_b = |f_a - f_b| ≈ f_a·|m/n-1|（实际拍频 vs 由整数比预测的期望拍频）
pub fn 拍频验证(τ_a: f64, τ_b: f64) -> 拍频验证结果 {
    if τ_a <= 0.0 || τ_b <= 0.0 {
        return 拍频验证结果 {
            τ_a,
            τ_b,
            频率比: 0.0,
            拍频: 0.0,
            期望拍频: 0.0,
            最近整数比: None,
            等价成立: false,
            偏差: f64::INFINITY,
            描述: "输入需为正τ".into(),
        };
    }
    let f_a = 1.0 / τ_a;
    let f_b = 1.0 / τ_b;
    let 频率比 = f_a / f_b;
    let 实际拍频 = (f_a - f_b).abs();
    // 定理1: τ_a/τ_b=n/m → f_a/f_b=m/n, 期望拍频 = f_b·|m/n-1|（以 f_b=1/τ_b 为基频）
    let 最近比 = 最近整数比(τ_a, τ_b);
    let (期望拍频, 偏差, 等价成立) = match 最近比 {
        Some((n, m)) => {
            let 期望 = f_b * ((m as f64 / n as f64) - 1.0).abs();
            let 偏差 = if 期望 > 0.0 { (实际拍频 - 期望).abs() / 期望 } else { 0.0 };
            // 等价判定: 整数比偏差在 σ 窗口内, 且拍频预测偏差也在容差内
            let 比偏差 = (频率比 - m as f64 / n as f64).abs() / (m as f64 / n as f64);
            let 成立 = 比偏差 <= 锁相窗口σ && 偏差 <= 锁相窗口σ;
            (期望, 偏差, 成立)
        }
        None => (0.0, f64::INFINITY, false),
    };
    let 描述 = format!(
        "τ_a/τ_b={:.4} f_a/f_b={:.4} f_b实际={:.4}Hz f_b期望={:.4}Hz → {}",
        τ_a / τ_b,
        频率比,
        实际拍频,
        期望拍频,
        if 等价成立 { "定理1等价成立" } else { "不满足整数比锁相" }
    );
    拍频验证结果 {
        τ_a,
        τ_b,
        频率比,
        拍频: 实际拍频,
        期望拍频,
        最近整数比: 最近比,
        等价成立,
        偏差,
        描述,
    }
}

/// 快τ推断结果（推论1, 含 v1.3 消歧状态）
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 快τ推断结果 {
    /// 候选快τ（秒, 从小到大）
    pub 候选快τ: Vec<f64>,
    /// 消歧状态: "已消歧"(单候选) / "需相位消歧"(双候选) / "无匹配"
    pub 消歧状态: String,
    /// 描述
    pub 描述: String,
}

/// 推论1 跨尺度捕获: 由慢τ测量 + 拍频 f_b 推断快τ候选
///
/// f_1 = f_2 ± f_b（v1.3 修正: 两个候选分支）:
/// - f_2 - f_b <= 0 → 仅 f_2+f_b 一个候选 → "已消歧"
/// - 两候选均正 → 需 M3相位/M1扫频/多拍频一致性消歧 → "需相位消歧"
pub fn 快τ推断(τ慢: f64, 拍频: f64) -> 快τ推断结果 {
    if τ慢 <= 0.0 || 拍频 <= 0.0 {
        return 快τ推断结果 {
            候选快τ: Vec::new(),
            消歧状态: "无匹配".into(),
            描述: "输入需为 正τ慢 + 正拍频".into(),
        };
    }
    let f2 = 1.0 / τ慢;
    let mut 候选: Vec<f64> = Vec::new();
    let 上分支 = f2 + 拍频;
    if 上分支 > 0.0 {
        候选.push(上分支);
    }
    let 下分支 = f2 - 拍频;
    if 下分支 > 0.0 {
        候选.push(下分支);
    }
    候选.sort_by(|a, b| a.partial_cmp(b).unwrap());
    let (消歧状态, 描述) = match 候选.len() {
        0 => ("无匹配".into(), "无正频率候选".into()),
        1 => (
            "已消歧".into(),
            format!("唯一候选 f1={:.4}Hz → τ快={:.4}s", 候选[0], 1.0 / 候选[0]),
        ),
        _ => (
            "需相位消歧".into(),
            format!(
                "双候选 f1∈{{{:.4}, {:.4}}}Hz → τ快∈{{{:.4}, {:.4}}}s, 需M3相位/M1扫频消歧",
                候选[0],
                候选[1],
                1.0 / 候选[1],
                1.0 / 候选[0]
            ),
        ),
    };
    快τ推断结果 {
        候选快τ: 候选.iter().map(|f| 1.0 / f).collect(),
        消歧状态,
        描述,
    }
}

