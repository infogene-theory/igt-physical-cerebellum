/// 干预点 — 联合谱中值得造波的候选位置
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 干预点 {
    /// 类型: 风险点(不稳定模) / 关键节点(耦合中心) / 主τ模式(共振)
    pub 类型: String,
    /// 联合谱中的模索引（关键节点用节点索引）
    pub 模态索引: usize,
    /// 名称/描述
    pub 名称: String,
    /// 优先级（效果/成本比排序; 风险点>关键节点>主τ）
    pub 优先级: f64,
    /// Re(λ)——增长率（实矩阵自然约定, 稳定判据 Re<0）
    pub 实部: f64,
    /// Im(λ)——振荡频率 ω（[T-21a] 实矩阵自然约定, 造波取 ω=|Im|; 见 inverse_builder 标注）
    pub 虚部: f64,
    /// 时间尺度 τ（秒）——只定持续（3τ 窗口）与匹配, 不决定频率（ARCH-1 v1.2 §9.1）
    pub τ: f64,
    /// 预计效果描述
    pub 效果估计: String,
}

