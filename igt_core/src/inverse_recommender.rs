/// 模拟前后对比 — 联合谱关键指标
#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
pub struct 模拟前后 {
    /// 联合稳定（全部 Re<0）
    pub 联合稳定: bool,
    /// 最大实部
    pub 最大实部: f64,
    /// 逆元形成度
    pub 逆元形成度: f64,
    /// 配对覆盖率
    pub 配对覆盖率: f64,
}

impl 模拟前后 {
    fn 从(r: &super::inverse_builder::逆元构建结果) -> Self {
        Self {
            联合稳定: r.联合稳定,
            最大实部: r.最大实部,
            逆元形成度: r.逆元形成度,
            配对覆盖率: r.配对覆盖率,
        }
    }
}

/// 模拟结果 — 单个方案的数值验证
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 模拟结果 {
    /// 被验证的方案
    pub 方案: 造波方案,
    /// 注入前
    pub 模拟前: 模拟前后,
    /// 注入后
    pub 模拟后: 模拟前后,
    /// 有效: 逆元形成度提升 >0 或 失稳→稳定
    pub 有效: bool,
    /// 形成度变化（后-前）
    pub 改善: f64,
    /// 副作用触发: 模拟后出现更不正实部模（失锁/放大）
    pub 副作用触发: bool,
    /// 结论
    pub 结论: String,
}

