//! 逆元建议器 — 第270批（2026-08-20）P22 §8 造波建议层闭环
//!
//! 理论依据:
//!   - P22_IGT_Engine_τ工程化架构与接口 §8 造波建议层:
//!     推荐干预点(8.2) → 造波方案(8.3) → 模拟验证(8.4) → 输出 InterventionPlan(8.5)
//!   - P20: 造波安全阈值 ε_wave < 0.3
//!   - 第209批 inverse_builder: 联合耗散算子 L_total=[[L_you,K],[K^T,L_engine]]
//!     + 模-反模配对 → 逆元形成度
//!
//! 核心定位: 把第209批的"形成度数字+优化建议文本"升级为可执行干预计划——
//!   ① 推荐干预点(风险点/关键节点/主τ模式, 按效果/成本比排序取 top3)
//!   ② 生成造波方案(扰动大小/频率/相位/持续时间/预期效果/副作用)
//!   ③ 模拟验证(矩阵级注入 ε_wave → 重算复谱 → 前后对比, 显式检失锁副作用)
//!   ④ 输出 InterventionPlan(最佳方案+监控指标+总体建议)
//!
//! 诚实标注: 相位简化为 0(引导语生成用); 模拟为线性响应近似(非线性失稳
//!   仍以 ε_wave<0.3 安全阈值 + 副作用显式检出兜底)。

