/// 逆元建议器 — 推荐干预点 → 生成方案 → 模拟验证 → 建议计划
#[derive(Debug, Clone, Copy)]
pub struct 逆元建议器 {
    /// 模-反模配对容差（透传 inverse_builder）
    pub 配对容差: f64,
    /// 造波安全上限 ε_wave（P20 = 0.3）
    pub ε_wave上限: f64,
}

impl Default for 逆元建议器 {
    fn default() -> Self {
        Self { 配对容差: 0.2, ε_wave上限: 0.3 }
    }
}

impl 逆元建议器 {
    /// 新建（默认配对容差 0.2, ε_wave 上限 0.3）
    pub fn 新建() -> Self {
        Self::default()
    }

    /// ① 推荐干预点（P22 §8.2）——按效果/成本比排序
    ///
    /// - 风险点: Re(λ)>0 的不稳定模（增长/反模, 最急, 优先级 1.0+Re 降序）
    /// - 关键节点: 耦合中心（K 行和/列和最大的节点, 优先级 0.5）
    /// - 主τ模式: 最慢稳定模（|Re| 最小 = τ 最大, 优先级 0.1）
    pub fn 推荐干预点(&self, 用户τ: &[f64], 引擎τ: &[f64], 耦合: &DMatrix<f64>) -> Vec<干预点> {
        let 构建器 = 逆元构建器 { 配对容差: self.配对容差 };
        let 结果 = 构建器.构建(用户τ, 引擎τ, 耦合);
        // T-181（统一令 §4.3）：ω/γ/τ 一律经 inverse_builder 边界统一换算，消费方不再各自 `-1/re`。
        let 权威谱 = 结果.权威谱();
        let mut 点列表 = Vec::new();

        // ① 风险点: Re>0 不稳定模
        for (i, (re, im)) in 结果.联合本征值.iter().enumerate() {
            if *re > 1e-9 {
                // 增长模 γ=−re<0（非稳定），统一入口 τ=None；此处 τ 字段记**增长率倒数**
                // （增长 e 折时间，非弛豫 τ），数值沿用旧口径（core 数值零改），显式标注消歧。
                let 增长时间常数 = 1.0 / re.max(1e-9);
                点列表.push(干预点 {
                    类型: "风险点(不稳定模)".to_string(),
                    模态索引: i,
                    名称: format!("增长模 #{} (Re={:.3}, Im={:.3})", i, re, im),
                    优先级: 1.0 + *re,
                    实部: *re,
                    虚部: *im,
                    τ: 增长时间常数,
                    效果估计: "注入逆元使 Re 转负 → 联合稳定".to_string(),
                });
            }
        }
        // ② 主τ模式: 最慢稳定模（τ 取统一换算的权威弛豫时间 1/γ = −1/re）
        if let Some((i, re, im)) = 结果
            .联合本征值
            .iter()
            .enumerate()
            .filter(|(_, (re, _))| *re < 0.0)
            .min_by(|(_, a), (_, b)| {
                a.0.abs()
                    .partial_cmp(&b.0.abs())
                    .unwrap_or(std::cmp::Ordering::Equal)
            })
            .map(|(i, (re, im))| (i, *re, *im))
        {
            let τ主 = 权威谱[i].τ.unwrap_or(-1.0 / re); // 稳定模必 Some；兜底保留旧式
            点列表.push(干预点 {
                类型: "主τ模式(共振)".to_string(),
                模态索引: i,
                名称: format!("主τ模 #{} (τ={:.1}s, 身份时间)", i, τ主),
                优先级: 0.1,
                实部: re,
                虚部: im,
                τ: τ主,
                效果估计: "共振扰动延长主τ（系统身份时间）".to_string(),
            });
        }
        // ③ 关键节点: 耦合中心（K 行和/列和最大）
        let n = 用户τ.len();
        let m = 引擎τ.len();
        let mut 中心: Option<(usize, f64)> = None; // (节点索引, 耦合度)
        for i in 0..n.min(耦合.nrows()) {
            let 度: f64 = (0..m.min(耦合.ncols())).map(|j| 耦合[(i, j)].abs()).sum();
            if 中心.map_or(true, |(_, d)| 度 > d) {
                中心 = Some((i, 度));
            }
        }
        for j in 0..m.min(耦合.ncols()) {
            let 度: f64 = (0..n.min(耦合.nrows())).map(|i| 耦合[(i, j)].abs()).sum();
            if 中心.map_or(true, |(_, d)| 度 > d) {
                中心 = Some((n + j, 度));
            }
        }
        if let Some((节点, 度)) = 中心 {
            if 度 > 1e-9 {
                点列表.push(干预点 {
                    类型: "关键节点(耦合中心)".to_string(),
                    模态索引: 节点,
                    名称: format!("耦合中心 节点#{} (耦合度={:.3})", 节点, 度),
                    优先级: 0.5,
                    实部: 0.0,
                    虚部: 0.0,
                    τ: 0.0,
                    效果估计: "增强耦合促进模-反模配对（配对覆盖率提升）".to_string(),
                });
            }
        }
        // 效果/成本比排序（风险点 > 关键节点 > 主τ）
        点列表.sort_by(|a, b| {
            b.优先级
                .partial_cmp(&a.优先级)
                .unwrap_or(std::cmp::Ordering::Equal)
        });
        点列表
    }

    /// ② 生成造波方案（P22 §8.3）
    ///
    /// - 风险点: ε_wave = clamp(Re×1.2+0.02, 0.02, 上限)（单次无法转负→需多次造波）; 频率=ω_n=|Im(λ)|
    /// - 关键节点: ε_wave=0.1（耦合增强 10%）; 频率: 耦合中心无直接本征值→**ω 不可得→不输出频率建议**（禁止用 τ/γ 冒充, ARCH-1 v1.2 §9.3）
    /// - 主τ模式: ε_wave=0.05（共振微扰）; 频率=ω_n=|Im(λ)|（T-21a 修复: 原 1/τ 违例）
    /// - **持续 = 3τ 窗口**（τ 只定持续与匹配, 不决定频率——ARCH-1 v1.2 §9.1 ω/γ 两维独立）
    /// - Re/Im 存储约定: 实矩阵对角化自然约定 Re=增长率/Im=ω（见 inverse_builder 标注）
    pub fn 生成方案(&self, 点: &干预点, 用户τ: &[f64], 引擎τ: &[f64]) -> 造波方案 {
        let ε上限 = self.ε_wave上限.max(0.05).min(0.5);
        match 点.类型.as_str() {
            "风险点(不稳定模)" => {
                let 扰动大小 = (点.实部 * 1.2 + 0.02).clamp(0.02, ε上限);
                // T-181（统一令 §4.3）：ω 经 inverse_builder 边界统一换算（=|Im|），不再就地 .abs()。
                let 模 = super::inverse_builder::权威本征模::从状态空间本征值(点.实部, 点.虚部);
                let 频率 = if 模.ω > 1e-9 {
                    模.ω
                } else {
                    // 诚实降级: ω 不可得（纯实特征值/数据缺失）→ 不输出频率建议,
                    // **禁止 1/τ 冒充 ω**（ARCH-1 v1.2 §9.3: 谱不正不输出同ω建议）
                    0.0
                };
                // 3τ 窗口: 持续 = 3 × 时间尺度（T-21a 修正: 原 3/频率 错误耦合持续与振荡周期）
                let 持续 = 3.0 * 点.τ.max(1e-6);
                造波方案 {
                    干预点: 点.clone(),
                    扰动大小,
                    扰动频率: 频率,
                    扰动相位: 0.0,
                    持续时间: 持续,
                    预期效果: if 点.实部 <= 扰动大小 {
                        if 频率 > 1e-9 {
                            format!(
                                "注入逆元 ε_wave={:.3}, f={:.3}Hz, 最大实部 {:.3}→≤0（联合稳定）",
                                扰动大小, 频率, 点.实部
                            )
                        } else {
                            format!(
                                "注入逆元 ε_wave={:.3}, 最大实部 {:.3}→≤0（联合稳定）; 注: 该模 ω≈0, 频率建议缺失",
                                扰动大小, 点.实部
                            )
                        }
                    } else {
                        if 频率 > 1e-9 {
                            format!(
                                "注入逆元 ε_wave={:.3}（受 P20 安全阈值钳制）, f={:.3}Hz, 最大实部 {:.3} 单次无法完全转负, 需多次造波",
                                扰动大小, 频率, 点.实部
                            )
                        } else {
                            format!(
                                "注入逆元 ε_wave={:.3}（受 P20 安全阈值钳制）, 最大实部 {:.3} 单次无法完全转负, 需多次造波; 注: 该模 ω≈0, 频率建议缺失",
                                扰动大小, 点.实部
                            )
                        }
                    },
                    副作用: "过度注入可能使增长模过阻尼, 抑制可用的增益（反馈延迟风险）".to_string(),
                }
            }
            "关键节点(耦合中心)" => {
                let 慢τ = if 点.模态索引 < 用户τ.len() {
                    用户τ.get(点.模态索引).copied().unwrap_or(1.0)
                } else {
                    引擎τ.get(点.模态索引 - 用户τ.len()).copied().unwrap_or(1.0)
                }
                .abs()
                .max(1.0);
                // T-21a 诚实降级: 耦合中心无直接本征值（联合谱不映射到节点）, ω 不可得——
                // 不输出频率建议（**禁止 1/慢τ 冒充 ω**; ARCH-1 v1.2 §9.3 谱不正不输出同ω建议）
                造波方案 {
                    干预点: 点.clone(),
                    扰动大小: 0.1,
                    扰动频率: 0.0,
                    扰动相位: 0.0,
                    持续时间: 3.0 * 慢τ,
                    预期效果: "增强耦合 10%（ε_wave=0.1）, 促进模-反模配对, 配对覆盖率提升; 注: 耦合中心无直接本征值, ω 不可得, 频率建议缺失".to_string(),
                    副作用: "过度耦合可能触发失锁（|κ|τ>10 判据）".to_string(),
                }
            }
            _ => {
                let τ = 点.τ.max(1.0);
                // T-181（统一令 §4.3）：ω 经 inverse_builder 边界统一换算（=|Im|）。
                let 频率 = super::inverse_builder::权威本征模::从状态空间本征值(点.实部, 点.虚部).ω;
                造波方案 {
                    干预点: 点.clone(),
                    扰动大小: 0.05,
                    扰动频率: 频率,
                    扰动相位: 0.0,
                    持续时间: 3.0 * τ,
                    预期效果: if 频率 > 1e-9 {
                        format!("共振扰动（ε_wave=0.05, f={:.3}Hz）延长主τ ≈ {:.0}s", 频率, 点.τ)
                    } else {
                        format!("共振扰动（ε_wave=0.05, ω≈0 无振荡频率）延长主τ ≈ {:.0}s", 点.τ)
                    },
                    副作用: "共振可能放大已有振荡（需监控 ω 幅度）".to_string(),
                }
            }
        }
    }

    /// ③ 模拟验证（P22 §8.4）——矩阵级注入 ε_wave 后重算联合谱
    ///
    /// 注入方式（按干预点类型）:
    /// - 风险点: 引擎侧最负 τ 节点（增长源）对角注入阻尼 -= ε_wave
    /// - 关键节点: 耦合中心所在行/列耦合 ×(1+ε_wave)
    /// - 主τ模式: 耦合全块 ×(1+ε_wave)
    ///
    /// 有效 = 形成度提升 >0 或 失稳→稳定; 副作用触发 = 后.最大实部 > 前.最大实部。
    pub fn 模拟验证(
        &self,
        方案: &造波方案,
        用户τ: &[f64],
        引擎τ: &[f64],
        耦合: &DMatrix<f64>,
    ) -> 模拟结果 {
        let 构建器 = 逆元构建器 { 配对容差: self.配对容差 };
        let 前 = 构建器.构建(用户τ, 引擎τ, 耦合);
        let 矩阵 = 逆元构建器::嵌套转矩阵(&前.联合算子.联合矩阵);
        let n = 用户τ.len();
        let 总 = n + 引擎τ.len();
        let mut 改 = 矩阵.clone();
        let ε = 方案.扰动大小;
        match 方案.干预点.类型.as_str() {
            "风险点(不稳定模)" => {
                // 引擎侧最负 τ 节点 = 增长源 → 注入阻尼
                let j0 = 引擎τ
                    .iter()
                    .enumerate()
                    .min_by(|(_, a), (_, b)| {
                        a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal)
                    })
                    .map(|(j, _)| j)
                    .unwrap_or(0);
                if n + j0 < 总 {
                    改[(n + j0, n + j0)] -= ε;
                }
            }
            "关键节点(耦合中心)" => {
                let 节点 = 方案.干预点.模态索引;
                if 节点 < n {
                    for j in 0..引擎τ.len() {
                        if 改[(节点, n + j)].abs() > 1e-12 {
                            改[(节点, n + j)] *= 1.0 + ε;
                            改[(n + j, 节点)] = 改[(节点, n + j)];
                        }
                    }
                } else if 节点 < 总 {
                    let j0 = 节点 - n;
                    for i in 0..n {
                        if 改[(i, n + j0)].abs() > 1e-12 {
                            改[(i, n + j0)] *= 1.0 + ε;
                            改[(n + j0, i)] = 改[(i, n + j0)];
                        }
                    }
                }
            }
            _ => {
                // 主τ模式: 均匀增强耦合
                for i in 0..n {
                    for j in 0..引擎τ.len() {
                        if 改[(i, n + j)].abs() > 1e-12 {
                            改[(i, n + j)] *= 1.0 + ε;
                            改[(n + j, i)] = 改[(i, n + j)];
                        }
                    }
                }
            }
        }
        let 后 = 构建器.从矩阵分析(&改, n, 引擎τ.len(), 前.联合算子.耦合强度);

        let 改善 = 后.逆元形成度 - 前.逆元形成度;
        let 有效 = 改善 > 1e-9 || (!前.联合稳定 && 后.联合稳定);
        let 副作用触发 = 后.最大实部 > 前.最大实部 + 1e-9;
        let 结论 = match (有效, 副作用触发) {
            (true, false) => "推荐执行: 逆元注入有效且无副作用".to_string(),
            (true, true) => {
                "部分有效: 形成度/稳定改善但伴随新正实部模, 需降低 ε_wave 或换干预点".to_string()
            }
            (false, _) => "不建议: 该干预点模拟未改善联合谱".to_string(),
        };

        模拟结果 {
            方案: 方案.clone(),
            模拟前: 模拟前后::从(&前),
            模拟后: 模拟前后::从(&后),
            有效,
            改善,
            副作用触发,
            结论,
        }
    }

    /// ⑤ 多档 ε 扫描（第350批 P22 §8.4 深化）——对同一方案做扰动强度扫描
    ///
    /// 单一 ε_wave 只给"该档是否有效"; 扫描给出改善-ε 曲线,
    /// 供上层挑选"有效∧无副作用∧改善最大"的最优扰动强度（P20 安全阈值 ε<0.3 内）。
    pub fn 扫描ε(
        &self,
        方案: &造波方案,
        用户τ: &[f64],
        引擎τ: &[f64],
        耦合: &DMatrix<f64>,
        档位: &[f64],
    ) -> Vec<ε档结果> {
        档位
            .iter()
            .map(|ε| {
                let mut 改 = 方案.clone();
                改.扰动大小 = *ε;
                let 模拟 = self.模拟验证(&改, 用户τ, 引擎τ, 耦合);
                ε档结果 {
                    扰动大小: *ε,
                    有效: 模拟.有效,
                    改善: 模拟.改善,
                    副作用触发: 模拟.副作用触发,
                }
            })
            .collect()
    }

    /// ④ 逆元建议计划（P22 §8.5 InterventionPlan）——全流程
    pub fn 建议(&self, 用户τ: &[f64], 引擎τ: &[f64], 耦合: &DMatrix<f64>) -> 逆元建议计划 {
        let 全部干预点 = self.推荐干预点(用户τ, 引擎τ, 耦合);
        let 干预点列表: Vec<干预点> = 全部干预点.into_iter().take(3).collect();
        let mut 方案列表 = Vec::new();
        let mut 模拟列表 = Vec::new();
        for 点 in &干预点列表 {
            let 方案 = self.生成方案(点, 用户τ, 引擎τ);
            let 模拟 = self.模拟验证(&方案, 用户τ, 引擎τ, 耦合);
            方案列表.push(方案);
            模拟列表.push(模拟);
        }
        // 最佳方案: 有效中改善最大; 副作用触发者减分
        let 最佳方案 = 模拟列表
            .iter()
            .filter(|s| s.有效)
            .max_by(|a, b| {
                let 得分 = |s: &&模拟结果| if s.副作用触发 { s.改善 - 0.5 } else { s.改善 };
                得分(a).partial_cmp(&得分(b)).unwrap_or(std::cmp::Ordering::Equal)
            })
            .cloned();

        let 前稳定 = 模拟列表.first().map(|s| s.模拟前.联合稳定).unwrap_or(true);
        let 前形成度 = 模拟列表.first().map(|s| s.模拟前.逆元形成度).unwrap_or(0.0);
        let 总体建议 = if 模拟列表.is_empty() {
            "联合谱为空, 无法生成逆元建议".to_string()
        } else if 前稳定 && 前形成度 >= 0.7 {
            "逆元已形成良好（联合稳定+形成度≥0.7）, 无需干预——维持当前稳态".to_string()
        } else if let Some(最佳) = &最佳方案 {
            format!("建议执行[{}]方案: {}", 最佳.方案.干预点.类型, 最佳.结论)
        } else {
            "当前逆元形成度不足且模拟无有效方案——建议先修复数据源/增大耦合矩阵 K 再评估".to_string()
        };

        逆元建议计划 {
            干预点列表,
            方案列表,
            模拟列表,
            最佳方案,
            监控指标: vec![
                "最大实部 Re_max（>0 需干预）".to_string(),
                "逆元形成度（0.5×稳定度+0.5×配对覆盖率）".to_string(),
                "配对覆盖率（模-反模配对/本征值对数）".to_string(),
                "ε_wave < 0.3（P20 造波安全阈值）".to_string(),
                "D_s^(2D) 椭圆区域（谱级健康预警）".to_string(),
            ],
            总体建议,
        }
    }
}

