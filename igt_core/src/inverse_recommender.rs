/// 造波方案 — 单个干预点的具体扰动参数
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 造波方案 {
    /// 干预点
    pub 干预点: 干预点,
    /// 扰动大小 ε_wave（P20 安全阈值 <0.3）
    pub 扰动大小: f64,
    /// 扰动频率（Hz, 与目标τ匹配）
    pub 扰动频率: f64,
    /// 扰动相位（rad, 引导语生成用; 简化为 0）
    pub 扰动相位: f64,
    /// 持续时间（秒）
    pub 持续时间: f64,
    /// 预期效果
    pub 预期效果: String,
    /// 可能的副作用
    pub 副作用: String,
}

