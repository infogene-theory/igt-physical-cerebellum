    /// 生成正弦波信号
    fn 生成正弦波(频率: f64, 采样率: f64, 时长: f64, 振幅: f64) -> Vec<f64> {
        let n = (采样率 * 时长) as usize;
        (0..n).map(|i| {
            let t = i as f64 / 采样率;
            振幅 * (2.0 * std::f64::consts::PI * 频率 * t).sin()
        }).collect()
    }

    /// 生成阻尼振荡信号: A·e^{-σt}·sin(2πf₀t)
    fn 生成阻尼振荡(f0: f64, sigma: f64, 采样率: f64, 时长: f64, 振幅: f64) -> Vec<f64> {
        let n = (采样率 * 时长) as usize;
        (0..n).map(|i| {
            let t = i as f64 / 采样率;
            振幅 * (-sigma * t).exp() * (2.0 * std::f64::consts::PI * f0 * t).sin()
        }).collect()
    }

