/// STFT 配置——短时傅里叶变换参数
#[derive(Debug, Clone)]
pub struct STFT配置 {
    /// 采样率 (Hz)
    pub 采样率: f64,
    /// 窗长（样本数）——对应 τ_slow/10
    pub 窗长: usize,
    /// 跳跃长度（样本数）——窗长/2 实现 50% 重叠
    pub 跳跃: usize,
    /// 峰值检测的最小振幅阈值 A_min
    pub 振幅阈值: f64,
    /// 频率分辨率（Hz）——由窗长决定: df = 采样率/窗长
    pub 频率分辨率: f64,
}

impl Default for STFT配置 {
    fn default() -> Self {
        let 采样率 = 1000.0; // 1kHz 默认
        let 窗长 = 100;     // 100 样本 = 100ms = τ_slow/10 (τ_slow=1s)
        STFT配置 {
            采样率,
            窗长,
            跳跃: 窗长 / 2,  // 50% 重叠
            振幅阈值: 0.05,
            频率分辨率: 采样率 / 窗长 as f64,
        }
    }
}

impl STFT配置 {
    pub fn 新建(采样率: f64, 窗长: usize) -> Self {
        let 频率分辨率 = 采样率 / 窗长 as f64;
        STFT配置 {
            采样率,
            窗长,
            跳跃: 窗长 / 2,
            振幅阈值: 0.05,
            频率分辨率,
        }
    }
}

/// 从时序信号通过 STFT 提取弛豫频谱
///
/// 工程映射层 Gap 1 补全——实现理论要求的:
/// 1. 滑窗 STFT——Hann 窗——50% 重叠
/// 2. 提取每个显著峰值的 {f_i, σ_i, φ_i}
/// 3. 合并所有窗口的峰值——去重——排序
///
/// 复杂度: O(N · T · log T)——N=窗口数, T=窗长
pub fn 从时序提取(信号: &[f64], 配置: &STFT配置) -> 弛豫频谱 {
    if 信号.len() < 配置.窗长 {
        return 弛豫频谱::新建(vec![]);
    }

    let mut 所有峰值: Vec<频谱分量> = Vec::new();
    let mut 窗口序号 = 0usize;

    // 滑窗 STFT
    let mut 起始 = 0usize;
    while 起始 + 配置.窗长 <= 信号.len() {
        // 提取窗口信号
        let 窗口信号 = &信号[起始..起始 + 配置.窗长];

        // 应用 Hann 窗
        let 加窗信号 = 加hann窗(窗口信号);

        // DFT 计算幅度谱和相位谱
        let (幅度谱, 相位谱) = 离散傅里叶变换(&加窗信号);

        // 峰值检测
        let 峰值 = 检测峰值(&幅度谱, &相位谱, 配置);
        所有峰值.extend(峰值);

        窗口序号 += 1;
        起始 += 配置.跳跃;
    }

    // 合并去重——同一频率的峰值取振幅加权平均
    let 合并峰值 = 合并峰值(所有峰值, 配置.频率分辨率);

    弛豫频谱::新建(合并峰值)
}

/// Hann 窗函数
fn 加hann窗(信号: &[f64]) -> Vec<f64> {
    let n = 信号.len();
    信号.iter().enumerate().map(|(i, &x)| {
        let w = 0.5 * (1.0 - (2.0 * std::f64::consts::PI * i as f64 / n as f64).cos());
        x * w
    }).collect()
}

/// 离散傅里叶变换——返回 (幅度谱, 相位谱)
///
/// 仅计算前 N/2 个频率分量（实信号对称性）
fn 离散傅里叶变换(信号: &[f64]) -> (Vec<f64>, Vec<f64>) {
    let n = 信号.len();
    let half = n / 2;
    let mut 幅度谱 = vec![0.0; half];
    let mut 相位谱 = vec![0.0; half];

    for k in 0..half {
        let mut re = 0.0;
        let mut im = 0.0;
        for t in 0..n {
            let angle = -2.0 * std::f64::consts::PI * k as f64 * t as f64 / n as f64;
            re += 信号[t] * angle.cos();
            im += 信号[t] * angle.sin();
        }
        幅度谱[k] = (re * re + im * im).sqrt() / n as f64 * 2.0; // 归一化
        相位谱[k] = im.atan2(re);
    }

    (幅度谱, 相位谱)
}

/// 峰值检测——局部极大值且超过振幅阈值
fn 检测峰值(幅度谱: &[f64], 相位谱: &[f64], 配置: &STFT配置) -> Vec<频谱分量> {
    let mut 峰值 = Vec::new();
    let n = 幅度谱.len();

    for k in 1..n.saturating_sub(1) {
        // 局部极大值判定
        if 幅度谱[k] > 幅度谱[k - 1] && 幅度谱[k] > 幅度谱[k + 1] {
            if 幅度谱[k] > 配置.振幅阈值 {
                let 频率 = k as f64 * 配置.频率分辨率;
                let 振幅 = 幅度谱[k];
                let 相位 = 相位谱[k];

                // 衰减系数估计: 用峰值在相邻窗口的振幅比拟合 e^{-σt}
                // 简化: 用峰值的频率宽度估计 σ（半高宽法）
                // σ ≈ Δf / 2 (Hz 转 1/s)
                let 半高宽 = 估计半高宽(幅度谱, k);
                let 衰减系数 = 半高宽 * 配置.频率分辨率 / 2.0;

                峰值.push(频谱分量 {
                    频率,
                    振幅,
                    衰减系数: 衰减系数.max(1e-6),
                    相位,
                });
            }
        }
    }

    峰值
}

/// 估计峰值的半高宽（bins 数）
fn 估计半高宽(幅度谱: &[f64], 峰值位置: usize) -> f64 {
    let n = 幅度谱.len();
    let 峰值 = 幅度谱[峰值位置];
    let 半高 = 峰值 / 2.0;

    // 向左搜索
    let mut 左边界 = 峰值位置;
    while 左边界 > 0 && 幅度谱[左边界] > 半高 {
        左边界 -= 1;
    }

    // 向右搜索
    let mut 右边界 = 峰值位置;
    while 右边界 < n - 1 && 幅度谱[右边界] > 半高 {
        右边界 += 1;
    }

    (右边界 - 左边界) as f64
}

/// 合并峰值——同一频率 bin 内的峰值取振幅加权平均
fn 合并峰值(峰值: Vec<频谱分量>, 频率分辨率: f64) -> Vec<频谱分量> {
    if 峰值.is_empty() {
        return vec![];
    }

    // 按频率排序
    let mut 排序峰值 = 峰值;
    排序峰值.sort_by(|a, b| a.频率.partial_cmp(&b.频率).unwrap_or(std::cmp::Ordering::Equal));

    let mut 合并结果: Vec<频谱分量> = Vec::new();
    let mut 当前组: Vec<频谱分量> = vec![排序峰值[0]];

    for 峰值 in 排序峰值.iter().skip(1) {
        let 组中心 = 当前组.iter().map(|p| p.频率).sum::<f64>() / 当前组.len() as f64;
        if (峰值.频率 - 组中心).abs() < 频率分辨率 {
            // 同一频率 bin——加入当前组
            当前组.push(*峰值);
        } else {
            // 新频率 bin——合并当前组
            合并结果.push(合并一组(当前组));
            当前组 = vec![*峰值];
        }
    }
    合并结果.push(合并一组(当前组));

    合并结果
}

/// 合并一组峰值——振幅加权平均
fn 合并一组(组: Vec<频谱分量>) -> 频谱分量 {
    let 总振幅: f64 = 组.iter().map(|p| p.振幅).sum();
    if 总振幅 < 1e-12 {
        return 组[0];
    }

    let 加权频率: f64 = 组.iter().map(|p| p.频率 * p.振幅).sum::<f64>() / 总振幅;
    let 加权相位: f64 = 组.iter().map(|p| p.相位 * p.振幅).sum::<f64>() / 总振幅;
    let 平均衰减: f64 = 组.iter().map(|p| p.衰减系数).sum::<f64>() / 组.len() as f64;
    let 最大振幅: f64 = 组.iter().map(|p| p.振幅).fold(0.0, f64::max);

    频谱分量 {
        频率: 加权频率,
        振幅: 最大振幅,
        衰减系数: 平均衰减,
        相位: 加权相位,
    }
}

