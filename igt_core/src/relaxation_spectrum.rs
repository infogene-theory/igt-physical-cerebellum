/// RS 的时域演化状态
///
/// 公理二: 任何形变必然耗散回归 UTGS。
/// 在 RS 框架中 = 每个频谱分量的振幅按 exp(-σ·t) 衰减。
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RS演化状态 {
    /// 当前时刻的 RS
    pub 当前频谱: 弛豫频谱,

    /// 从初始态到当前的耗散比例
    pub 耗散比例: f64,

    /// 预计完全回归 UTGS 的剩余时间 (s)
    pub 预计剩余时间: f64,
}

impl RS演化状态 {
    /// 推进 RS 演化一个时间步 Δt
    ///
    /// 每个分量: A(t+Δt) = A(t) × exp(-σ × Δt)
    pub fn 演化步(&mut self, delta_t: f64) {
        let 衰减分量: Vec<频谱分量> = self
            .当前频谱
            .分量列表
            .iter()
            .map(|c| 频谱分量 {
                频率: c.频率,
                振幅: c.振幅 * (-c.衰减系数 * delta_t).exp(),
                衰减系数: c.衰减系数,
                相位: c.相位,
            })
            .filter(|c| c.振幅 > 1e-10) // 滤除已完全衰减的分量
            .collect();

        self.当前频谱 = 弛豫频谱::新建(衰减分量);
        self.耗散比例 = 1.0 - self.当前频谱.总能量 / (self.当前频谱.总能量 + 1e-10);

        // 估算剩余时间（基于最慢衰减分量）
        self.预计剩余时间 = self
            .当前频谱
            .分量列表
            .iter()
            .map(|c| if c.衰减系数 > 0.0 { 1.0 / c.衰减系数 } else { f64::INFINITY })
            .fold(f64::INFINITY, f64::min);
    }
}

