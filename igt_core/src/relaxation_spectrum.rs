/// 单个频谱分量: (频率, 振幅, 衰减系数)
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct 频谱分量 {
    /// 瞬时频率 f (Hz)
    pub 频率: f64,
    /// 振幅 A（归一化，[0, 1]）
    pub 振幅: f64,
    /// 衰减系数 σ (1/s) —— 该频率成分向 UTGS 的耗散速率
    pub 衰减系数: f64,
    /// 相位 φ (弧度)
    pub 相位: f64,
}

/// 弛豫频谱 — V8 定义7
///
/// RS = { (f_i, A_i, σ_i, φ_i) } 有序集合，按频率降序排列。
///
/// RS 是 V8 体系中最核心的可观测量:
/// - 定理3: 不同尺度的 RS 被自然分离为四个频段（四种力）
/// - 定理5: 观测结果 = 被观测系统 RS × 观测者 SRT 传递函数
/// - L3-04: 共振总线的 8 个标准频段
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 弛豫频谱 {
    /// 频谱分量列表（按频率降序排列）
    pub 分量列表: Vec<频谱分量>,

    /// 频谱的总能量（各分量振幅平方和）
    pub 总能量: f64,

    /// 频谱的独立频率成分数 C_RS
    pub 独立成分数: usize,

    /// 主导频率（最大振幅对应的频率）
    pub 主导频率: f64,

    /// 频谱的有效带宽（频率范围的对数比）
    pub 有效带宽: f64,
}

impl 弛豫频谱 {
    /// 从分量列表构建 RS（自动排序 + 计算统计量）
    pub fn 新建(分量: Vec<频谱分量>) -> Self {
        let mut 分量列表 = 分量;
        分量列表.sort_by(|a, b| b.频率.partial_cmp(&a.频率).unwrap_or(std::cmp::Ordering::Equal));

        let 总能量: f64 = 分量列表.iter().map(|c| c.振幅 * c.振幅).sum();
        let 独立成分数 = 分量列表.len();

        let 主导频率 = 分量列表
            .iter()
            .max_by(|a, b| a.振幅.partial_cmp(&b.振幅).unwrap_or(std::cmp::Ordering::Equal))
            .map(|c| c.频率)
            .unwrap_or(0.0);

        let 最低频率 = 分量列表.last().map(|c| c.频率).unwrap_or(1.0);
        let 最高频率 = 分量列表.first().map(|c| c.频率).unwrap_or(1.0);
        let 有效带宽 = if 最低频率 > 0.0 {
            (最高频率 / 最低频率).ln()
        } else {
            0.0
        };

        弛豫频谱 {
            分量列表,
            总能量,
            独立成分数,
            主导频率,
            有效带宽,
        }
    }

    /// 计算频谱在给定观测窗口中的投影
    ///
    /// 观测窗口 τ_O 决定了哪些频段可被该观测者感知。
    /// 频率远高于 1/τ_O 的分量 → "太快看不见"
    /// 频率远低于 1/τ_O 的分量 → "太慢感受不到"
    ///
    /// 定理5: 观测结果 = 被观测系统 RS × 观测者 SRT 传递函数
    pub fn 观测投影(&self, tau_o: f64) -> 弛豫频谱 {
        let f_min = 1.0 / (tau_o * 10.0); // 慢于10倍τ_O → 不可感知
        let f_max = 10.0 / tau_o; // 快于0.1倍τ_O → 不可感知

        let 可见分量: Vec<频谱分量> = self
            .分量列表
            .iter()
            .filter(|c| c.频率 >= f_min && c.频率 <= f_max)
            .cloned()
            .collect();

        if 可见分量.is_empty() {
            return 弛豫频谱::新建(vec![]);
        }

        弛豫频谱::新建(可见分量)
    }

    /// 提取指定数量级范围内的频谱分量
    ///
    /// 用于定理3的频段分离——同一尺度的分量自然聚在一起。
    pub fn 频段提取(&self, 频率下限: f64, 频率上限: f64) -> 弛豫频谱 {
        let 区间分量: Vec<频谱分量> = self
            .分量列表
            .iter()
            .filter(|c| c.频率 >= 频率下限 && c.频率 <= 频率上限)
            .cloned()
            .collect();
        弛豫频谱::新建(区间分量)
    }

    /// 两个 RS 的耦合匹配度评估
    ///
    /// 匹配度 = (在对方频段中有共振峰的分数)
    /// 用于定理4（跨层级共振耦合）的数值实现。
    pub fn 耦合匹配度(&self, 其他: &弛豫频谱) -> f64 {
        if self.分量列表.is_empty() || 其他.分量列表.is_empty() {
            return 0.0;
        }

        let mut 匹配数 = 0;
        for a in &self.分量列表 {
            for b in &其他.分量列表 {
                let ratio = a.频率 / b.频率;
                // 检查是否接近小整数比
                for m in 1..=8 {
                    for n in 1..=8 {
                        let expected = m as f64 / n as f64;
                        if (ratio - expected).abs() < 0.01 {
                            匹配数 += 1;
                        }
                    }
                }
            }
        }

        let max_pairs = self.分量列表.len().min(其他.分量列表.len());
        if max_pairs == 0 {
            0.0
        } else {
            (匹配数 as f64 / max_pairs as f64).min(1.0)
        }
    }

    /// 频谱复杂度 C_RS
    ///
    /// C_RS = 独立成分数 × log(1 + 有效带宽)
    pub fn 复杂度(&self) -> f64 {
        self.独立成分数 as f64 * (1.0 + self.有效带宽).ln()
    }
}

