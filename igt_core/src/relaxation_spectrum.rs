/// 定理5：观测基准相对性
///
/// 所有可观测物理量均为相对值——由被观测系统的拓扑状态与观测者自身
/// 的 SRT 基准共同决定。不存在"绝对测量"。
///
/// 观测结果 = 被观测系统 RS × 观测者 SRT 传递函数
///
/// 此函数计算观测投影:
///   RS_observed = RS_system.观测投影(τ_O)
/// 其中 τ_O 为观测者的特征时间窗口。
pub fn 定理5_观测投影(系统RS: &弛豫频谱, tau_o: f64) -> 弛豫频谱 {
    系统RS.观测投影(tau_o)
}

/// 计算两个观测者对同一系统的测量差异度
///
/// 测量差异度 = 1 - (两个观测投影的耦合匹配度)
pub fn 定理5_观测差异度(系统RS: &弛豫频谱, tau_a: f64, tau_b: f64) -> f64 {
    let 投影A = 定理5_观测投影(系统RS, tau_a);
    let 投影B = 定理5_观测投影(系统RS, tau_b);
    1.0 - 投影A.耦合匹配度(&投影B)
}

