//! **T-124（PM 61）**：指针仪表 **L1 读数确定式**（core 纯函数，**零 IO / 零新增依赖**）。
//!
//! 来源：T-123 Python 原型（`scripts/meter_cv_detect.py`）的 L1 部分 —— **PM 61 §二.1 要求移植**。
//!
//! ## 本模块有什么 / 没有什么（**边界如实**）
//! - **有**：**读数确定式** `读数 = 下限 + (上限−下限) × ((指针角−刻度起) mod 360) / 张角`
//!   —— **可复算**（续79 纪律3：**锚点只许 core 纯函数可复算量**）；
//! - **有**：**刻度起止角与张角的表示/校验**（由 `meter_body_gate` 从像素估得，本模块只做几何计算）；
//! - **没有**：**不做 L0 检出**（Hough 圆 / 指针检测 **留在 Python**，PM 61 §二.3 明确**不移植**）；
//! - **没有**：**GB 无 IO**（不读文件、不读时间、不持状态）；**不加依赖**。
//!
//! ## 角度口径（与 Python 侧**逐字对齐**）
//! 一律**图像角**：`atan2(dy, dx)`，x 右 = 0°、**y 下 = 90°**、顺时针增；角度取 `[0, 360)`。
//! 仪表按**标准 270° 扇形**（0% 在 135°＝左下 ⇒ 顺时针经左/上/右 ⇒ 100% 在 45°＝右下）。

/// 量程（下限/上限）。**默认 `0..100`**（与 T-123 原型一致）。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 量程 {
    pub 下限: f64,
    pub 上限: f64,
}

impl Default for 量程 {
    fn default() -> Self {
        Self { 下限: 0.0, 上限: 100.0 }
    }
}

impl 量程 {
    pub fn new(下限: f64, 上限: f64) -> Self {
        Self { 下限, 上限 }
    }
    /// 跨度（`上限 − 下限`）
    pub fn 跨度(&self) -> f64 {
        self.上限 - self.下限
    }
}

/// **角度归一化**到 `[0, 360)`（与 `numpy % 360` 同语义：**非负**）
pub fn 归一角度(a: f64) -> f64 {
    let r = a % 360.0;
    if r < 0.0 {
        r + 360.0
    } else {
        r
    }
}

/// **两角最小夹角**（`[0, 180]`）—— 与 T-123 的 `abs(((d+180) % 360) - 180)` 同式。
pub fn 角差(a: f64, b: f64) -> f64 {
    let d = 归一角度(a - b);
    if d > 180.0 {
        360.0 - d
    } else {
        d
    }
}

/// 读数结果（**结构保留，不压成标量** —— 续79 纪律2）
#[derive(Debug, Clone, PartialEq)]
pub struct 读数结果 {
    /// 估计读数（**不在量程角内 ⇒ `None`，如实不给，不硬凑**）
    pub 读数: Option<f64>,
    /// 指针相对刻度起点的**位移角**（deg，`[0,360)`）
    pub 位移角: f64,
    /// 刻度张角（deg）
    pub 张角: f64,
    /// **指针是否落在刻度张角内**（角度关系不变量）
    pub 在量程内: bool,
    /// 说明（面板/审计可见；**可复算过程写清**）
    pub 说明: String,
}

/// **T-124 主函数：读数确定式**（**纯函数、可复算**）。
///
/// ```text
/// 位移 = (指针角 − 刻度起) mod 360
/// 若 位移 > 张角 (+1e-6)  ⇒ 读数 = None（**指针不在量程角内 ⇒ 如实不给**）
/// 否则 读数 = 下限 + (上限−下限) × 位移 / 张角
/// ```
///
/// - `指针角` / `刻度起`：**图像角**（deg）；
/// - `张角`：刻度覆盖角（deg，标准 270）；
/// - **`张角 <= 1e-6` ⇒ `None`**（退化输入**不产出**，防静默造数）。
pub fn 读数确定式(指针角: f64, 刻度起: f64, 张角: f64, 量程: &量程) -> 读数结果 {
    let 位移 = 归一角度(指针角 - 刻度起);
    if 张角 <= 1e-6 {
        return 读数结果 {
            读数: None,
            位移角: 位移,
            张角: 张角,
            在量程内: false,
            说明: format!(
                "**张角退化（{:.6}° ≤ 0）⇒ 不给读数**（如实报，不臆造）",
                张角
            ),
        };
    }
    let 在量程内 = 位移 <= 张角 + 1e-6;
    if !在量程内 {
        return 读数结果 {
            读数: None,
            位移角: 位移,
            张角: 张角,
            在量程内: false,
            说明: format!(
                "**指针不在刻度张角内 ⇒ 不给读数**：位移 {:.2}° > 张角 {:.2}°（如实报，不硬凑）",
                位移, 张角
            ),
        };
    }
    let 读数 = 量程.下限 + 量程.跨度() * (位移 / 张角);
    读数结果 {
        读数: Some(读数),
        位移角: 位移,
        张角: 张角,
        在量程内: true,
        说明: format!(
            "读数 = {:.1} + {:.1} × ({:.2}°/{:.2}°) = **{:.4}**（由指针角与刻度起止**确定式**给出，可复算）",
            量程.下限,
            量程.跨度(),
            位移,
            张角,
            读数
        ),
    }
}

/// **由"刻度起始/终止角"相容地取张角**（`终止 → 起始` 顺时针张角）。
pub fn 张角由起止(刻度起: f64, 刻度止: f64) -> f64 {
    归一角度(刻度止 - 刻度起)
}

