#[cfg(test)]
mod tests {
    use super::*;

    /// **正例**：标准 270° 扇形，指针在 50% 处（读数 50）
    /// 50% ⇒ 角 = 135 + 270×0.5 = 270.0（正上方）⇒ 位移 = 135°。
    #[test]
    fn t124_读数_正例_中点() {
        let r = 读数确定式(270.0, 135.0, 270.0, &量程::default());
        println!("\n[T-124] {}", r.说明);
        assert!(r.在量程内);
        assert!((r.位移角 - 135.0).abs() < 1e-9);
        assert!((r.读数.unwrap() - 50.0).abs() < 1e-9);
    }

    /// **正例**：起止角（0% / 100%）
    #[test]
    fn t124_读数_两端() {
        let a = 读数确定式(135.0, 135.0, 270.0, &量程::default());
        assert!((a.位移角 - 0.0).abs() < 1e-9);
        assert!((a.读数.unwrap() - 0.0).abs() < 1e-9);
        let b = 读数确定式(45.0, 135.0, 270.0, &量程::default());
        assert!((b.位移角 - 270.0).abs() < 1e-9);
        assert!((b.读数.unwrap() - 100.0).abs() < 1e-9);
    }

    /// **负例**：指针落在刻度张角**之外**⇒ **不给读数**（**不硬凑**）
    #[test]
    fn t124_读数_张角外不给() {
        // 位移 = (300-135) mod 360 = 165 ✓ 在量程内；取 20° ⇒ 位移 = 245 ✓ 仍在；
        // 取 100° ⇒ 位移 = (100-135) mod 360 = 325 > 270 ⇒ 不给
        let r = 读数确定式(100.0, 135.0, 270.0, &量程::default());
        println!("\n[T-124] 张角外 ⇒ {}", r.说明);
        assert!(!r.在量程内);
        assert!(r.读数.is_none(), "不在量程角内必须不给读数");
    }

    /// **边界**：退化张角 ⇒ `None`（防静默造数）
    #[test]
    fn t124_读数_退化张角() {
        let r = 读数确定式(180.0, 135.0, 0.0, &量程::default());
        assert!(r.读数.is_none());
        assert!(r.说明.contains("退化"));
        let r2 = 读数确定式(180.0, 135.0, 1e-9, &量程::default());
        assert!(r2.读数.is_none());
    }

    /// **边界**：非默认量程（如 −40..120）与**跨 0° 的起止**
    #[test]
    fn t124_读数_非默认量程与跨零起止() {
        let 量 = 量程::new(-40.0, 120.0);
        // 起 300°、张 270° ⇒ 止 = 210°
        let r = 读数确定式(300.0, 300.0, 270.0, &量);
        assert!((r.读数.unwrap() - (-40.0)).abs() < 1e-9);
        let mid = 读数确定式(75.0, 300.0, 270.0, &量); // 位移 = 135 ⇒ 50%
        assert!((mid.读数.unwrap() - 40.0).abs() < 1e-9);
    }

    /// **角度工具**：归一化与角差（含负角、跨零）
    #[test]
    fn t124_角度工具() {
        assert!((归一角度(-90.0) - 270.0).abs() < 1e-9);
        assert!((归一角度(450.0) - 90.0).abs() < 1e-9);
        assert!((角差(10.0, 350.0) - 20.0).abs() < 1e-9);
        assert!((角差(0.0, 180.0) - 180.0).abs() < 1e-9);
        assert!((张角由起止(135.0, 45.0) - 270.0).abs() < 1e-9);
    }
}
