/// 扰动通道观测 — 一个扰动源的 τ 特征与 τ 变化序列
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 通道观测 {
    /// 通道名（如 运动/咖啡/会议）
    pub 名称: String,
    /// 该扰动通道的特征 τ（秒）
    pub τ扰动: f64,
    /// τ 谱变化序列（时间戳秒, 变化幅度）
    pub 变化序列: Vec<时序点>,
}

/// 单通道归因贡献
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 通道贡献 {
    pub 名称: String,
    /// 贡献占比（全部通道 Σ=1；无有效归因时全 0）
    pub 贡献占比: f64,
    /// 共振耦合度 κ_ij
    pub κ: f64,
    /// 最优滞后下的 Pearson 相关（0..1；无效 0）
    pub 相关: f64,
    /// 最优滞后（秒，扰动先于响应）
    pub 最优滞后s: u64,
}

/// 归因报告
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct 归因报告 {
    /// 各通道贡献（按占比降序）
    pub 各通道: Vec<通道贡献>,
    /// 是否有效（至少一条通道有正权重）
    pub 有效: bool,
    pub 说明: String,
}

/// 归因分解 — HRV τ 谱变化分解到各扰动通道
///
/// 每通道权重 = κ_ij × max(相关, 0)，全通道归一化 → 贡献占比。
/// 全零（无相关/数据不足）→ 各占比 0 + 有效=false。
pub fn 归因分解(
    通道: &[通道观测],
    hrv_τ: f64,
    hrv_变化序列: &[时序点],
    最大滞后s: u64,
    步长s: u64,
) -> 归因报告 {
    let mut 贡献: Vec<通道贡献> = vec![];
    let mut 权重和 = 0.0f64;

    for c in 通道 {
        let κ = 共振耦合度(c.τ扰动, hrv_τ);
        let (滞后, 相关) = match 最优滞后相关(&c.变化序列, hrv_变化序列, 最大滞后s, 步长s) {
            Some((l, r)) => (l, r.max(0.0)),
            None => (0, 0.0),
        };
        let 权重 = κ * 相关;
        权重和 += 权重;
        贡献.push(通道贡献 {
            名称: c.名称.clone(),
            贡献占比: 0.0, // 归一化后回填
            κ,
            相关,
            最优滞后s: 滞后,
        });
    }

    if 权重和 <= 1e-12 {
        return 归因报告 {
            各通道: 贡献,
            有效: false,
            说明: "数据不足：无通道与 HRV 变化形成正相关的 τ 结构共振".to_string(),
        };
    }
    for c in 贡献.iter_mut() {
        c.贡献占比 = (c.κ * c.相关) / 权重和;
    }
    贡献.sort_by(|a, b| b.贡献占比.partial_cmp(&a.贡献占比).unwrap_or(std::cmp::Ordering::Equal));

    let 说明 = format!(
        "首要归因: {}（贡献 {:.0}%，κ={:.2}，滞后 {}s）",
        贡献[0].名称,
        贡献[0].贡献占比 * 100.0,
        贡献[0].κ,
        贡献[0].最优滞后s
    );
    归因报告 {
        各通道: 贡献,
        有效: true,
        说明,
    }
}

