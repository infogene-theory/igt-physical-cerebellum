//! prediction 域 — 扰动归因算法：κ 共振耦合 + 时间对齐 + 贡献分解（第232批）
//!
//! 理论依据: docs/理论扩展/个人Agent多模态扰动识别补充方案 §3.2
//! 不归因于语义（"他说了什么话"），而归因于 τ 结构：
//!   1. 时间相关性 — 各通道 τ 变化与 HRV τ 变化的滞后互相关
//!   2. κ 耦合度 — κ_ij = Σ exp(-(τ扰动/τ_HRV - n/m)²/(2σ²))
//!   3. 归因分解 — D_s 升高分解到各扰动通道的贡献占比
//!
//! 定位: 纯计算，无 IO——Agent 侧供数据（打卡通道/HRV 时序），本模块只做数学。
//! Agent 接入需 HRV 时序存储，留后续批；本批合成数据单测先行。

use serde::{Deserialize, Serialize};

// ============================================================================
// 共振耦合度 κ
// ============================================================================

/// κ 共振阶数上限（n, m 各取 1..=4，共振比覆盖 1/4..4，共 16 项）
pub const 阶数上限: u32 = 4;

/// κ 展宽 σ（高斯宽度，无量纲共振比空间）
pub const 展宽σ: f64 = 0.1;

/// 共振耦合度 κ_ij — 扰动 τ 与 HRV 本征 τ 的共振强度
///
/// κ = Σ_{n=1..N, m=1..M} exp(-((τ扰动/τ_HRV - n/m)²)/(2σ²))
///
/// τ扰动/τ_HRV 精确落在共振比 n/m 上时该项贡献 1；σ 控制失谐衰减。
/// 文档原式为 Σ（非 max），多阶叠加可 >1，归因时归一化消背景。
pub fn 共振耦合度(τ扰动: f64, τ_HRV: f64) -> f64 {
    if τ扰动 <= 0.0 || τ_HRV <= 0.0 || !τ扰动.is_finite() || !τ_HRV.is_finite() {
        return 0.0;
    }
    let r = τ扰动 / τ_HRV;
    let mut κ = 0.0;
    for n in 1..=阶数上限 {
        for m in 1..=阶数上限 {
            let 共振比 = n as f64 / m as f64;
            κ += (-((r - 共振比).powi(2)) / (2.0 * 展宽σ * 展宽σ)).exp();
        }
    }
    κ
}

// ============================================================================
// 时间对齐 — 滞后互相关
// ============================================================================

/// 带时间戳的标量序列（时间戳秒，值）
pub type 时序点 = (u64, f64);

/// Pearson 相关系数（样本 <2 或零方差返回 None）
fn pearson(x: &[f64], y: &[f64]) -> Option<f64> {
    let n = x.len();
    if n < 3 || n != y.len() {
        return None;
    }
    let mx = x.iter().sum::<f64>() / n as f64;
    let my = y.iter().sum::<f64>() / n as f64;
    let mut 协方差 = 0.0;
    let mut 方差x = 0.0;
    let mut 方差y = 0.0;
    for i in 0..n {
        let dx = x[i] - mx;
        let dy = y[i] - my;
        协方差 += dx * dy;
        方差x += dx * dx;
        方差y += dy * dy;
    }
    if 方差x <= 1e-12 || 方差y <= 1e-12 {
        return None;
    }
    Some(协方差 / (方差x * 方差y).sqrt())
}

/// 就近配对 — 响应序列上找与 t 容差内最近的时间戳值
fn 就近取值(序列: &[时序点], t: u64, 容差: u64) -> Option<f64> {
    序列
        .iter()
        .filter(|(ts, _)| ts.abs_diff(t) <= 容差)
        .min_by_key(|(ts, _)| ts.abs_diff(t))
        .map(|(_, v)| *v)
}

/// 最优滞后相关 — 扰动序列平移 lag 后与响应序列的 Pearson 相关
///
/// 扫描 lag ∈ [0, 最大滞后]，步长固定；取正相关最大的 lag。
/// 返回 (最优滞后秒, 相关值 0..1)；任何 lag 下都无法有效配对 → None。
pub fn 最优滞后相关(
    扰动序列: &[时序点],
    响应序列: &[时序点],
    最大滞后s: u64,
    步长s: u64,
) -> Option<(u64, f64)> {
    if 扰动序列.len() < 3 || 响应序列.len() < 3 || 最大滞后s == 0 || 步长s == 0 {
        return None;
    }
    let mut 最优: Option<(u64, f64)> = None;
    let mut lag = 0u64;
    while lag <= 最大滞后s {
        // 响应 t 对扰动 t-lag（扰动先于响应 lag 秒）：公共时间戳配对
        let mut xs: Vec<f64> = vec![];
        let mut ys: Vec<f64> = vec![];
        for (ts, v) in 响应序列 {
            let t = ts.saturating_sub(lag);
            if let Some(d) = 就近取值(扰动序列, t, 步长s) {
                xs.push(d);
                ys.push(*v);
            }
        }
        if let Some(c) = pearson(&xs, &ys) {
            if c > 0.0 {
                match 最优 {
                    Some((_, c0)) if c0 >= c => {}
                    _ => 最优 = Some((lag, c)),
                }
            }
        }
        lag += 步长s;
    }
    最优
}

