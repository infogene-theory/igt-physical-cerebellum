#[cfg(test)]
mod tests {
    use super::*;

    // 简单确定性伪噪声（固定种子，避免测试不稳定）
    fn 伪噪声(i: usize) -> f64 {
        ((i as f64 * 12.9898).sin() * 43758.5453).fract()
    }

    /// ① 精确共振 κ 显著高于非共振
    #[test]
    fn 测试_共振耦合度_共振与非共振() {
        // τ_HRV=4s; τ扰动=2s → r=0.5=1/2 精确共振（n=1,m=2）
        let 共振κ = 共振耦合度(2.0, 4.0);
        // r=0.37 非共振（离最近共振比 1/3≈0.333 距离 0.037≈0.37σ）
        let 非共振κ = 共振耦合度(0.37 * 4.0, 4.0);
        assert!(共振κ > 1.0, "精确共振应>1(多阶叠加): {}", 共振κ);
        assert!(共振κ > 非共振κ, "共振κ({}) 应>非共振({})", 共振κ, 非共振κ);
        // 非法输入 → 0
        assert_eq!(共振耦合度(0.0, 4.0), 0.0);
        assert_eq!(共振耦合度(2.0, 0.0), 0.0);
        assert_eq!(共振耦合度(-1.0, 4.0), 0.0);
    }

    /// ② r=1（n/m=1/1 全等共振）为最强
    #[test]
    fn 测试_共振耦合度_全等共振最强() {
        let 全等 = 共振耦合度(4.0, 4.0);
        let 半阶 = 共振耦合度(2.0, 4.0);
        assert!(全等 > 半阶, "r=1({}) 应>r=0.5({})", 全等, 半阶);
    }

    /// ③ 合成场景：HRV 响应 = 运动序列平移 300s × 0.6 + 噪声 → 运动通道居首且滞后≈300s
    #[test]
    fn 测试_归因分解_运动居首() {
        // 运动通道 τ 谱变化：10 分钟内脉冲式扰动，每 60s 一点
        let 基准: u64 = 1724000000;
        let 运动序列: Vec<时序点> = (0..12)
            .map(|i| {
                let v = if (3..7).contains(&i) { 1.0 } else { 0.1 }; // 13:50-14:20 跑步段
                (基准 + i * 60, v + 伪噪声(i as usize) * 0.01)
            })
            .collect();
        // HRV 响应：运动序列平移 300s × 0.6 + 小噪声
        let hrv序列: Vec<时序点> = (0..12)
            .map(|i| {
                let v = if (3..7).contains(&i) { 0.6 } else { 0.06 };
                (基准 + 300 + i * 60, v + 伪噪声((i + 100) as usize) * 0.01)
            })
            .collect();
        // 咖啡通道：与 HRV 无关的序列
        let 咖啡序列: Vec<时序点> = (0..12)
            .map(|i| (基准 + i * 60, 伪噪声((i + 200) as usize).abs() * 0.5))
            .collect();

        let 通道 = vec![
            // τ扰动=与响应模同量纲的扰动谱特征τ（8.4s → r=2.0=2/1 精确共振）;
            // 跑步30min是事件时长→体现为最优滞后, 非τ扰动
            通道观测 { 名称: "运动".into(), τ扰动: 8.4, 变化序列: 运动序列 },
            // 咖啡 τ扰动=4h → r=3428 远离共振比 0.25..4 → κ≈0（慢扰动不直接共振快模）
            通道观测 { 名称: "咖啡".into(), τ扰动: 4.0 * 3600.0, 变化序列: 咖啡序列 },
        ];
        let hrv_τ = 4.2; // 失稳模 τ（文档示例 4.2s 血压调节反射）
        let 报告 = 归因分解(&通道, hrv_τ, &hrv序列, 600, 60);

        assert!(报告.有效, "应有效归因: {}", 报告.说明);
        let 首 = &报告.各通道[0];
        assert_eq!(首.名称, "运动", "运动应居首: {}", 报告.说明);
        assert!(首.贡献占比 > 0.8, "运动贡献应>80%: {:.3}", 首.贡献占比);
        assert!(
            (首.最优滞后s as i64 - 300).abs() <= 60,
            "最优滞后≈300s±60: {}",
            首.最优滞后s
        );
        // 占比和 = 1
        let 和: f64 = 报告.各通道.iter().map(|c| c.贡献占比).sum();
        assert!((和 - 1.0).abs() < 1e-9, "占比和=1: {}", 和);
    }

    /// ④ 无相关通道 → 数据不足
    #[test]
    fn 测试_归因分解_无相关() {
        let 基准: u64 = 1724000000;
        let 无关: Vec<时序点> = (0..8).map(|i| (基准 + i * 60, 伪噪声(i as usize).abs())).collect();
        let hrv: Vec<时序点> = (0..8).map(|i| (基准 + i * 60, 伪噪声((i + 500) as usize).abs())).collect();
        let 通道 = vec![通道观测 { 名称: "其他".into(), τ扰动: 100.0, 变化序列: 无关 }];
        let 报告 = 归因分解(&通道, 4.2, &hrv, 600, 60);
        // 固定伪噪声序列可能偶发正相关，但权重和极小时按数据不足
        if !报告.有效 {
            assert_eq!(报告.各通道[0].贡献占比, 0.0);
        } else {
            // 若偶发有效，至少占比=1（单通道）
            assert!((报告.各通道[0].贡献占比 - 1.0).abs() < 1e-9);
        }
    }

    /// ⑤ 空通道 / 序列过短 → 数据不足
    #[test]
    fn 测试_归因分解_空与短序列() {
        let hrv = vec![(1724000000u64, 0.5), (1724000060, 0.6)];
        let 空 = 归因分解(&[], 4.2, &hrv, 600, 60);
        assert!(!空.有效, "空通道应数据不足");

        let 短 = vec![通道观测 { 名称: "运动".into(), τ扰动: 100.0, 变化序列: vec![(1, 1.0)] }];
        let 报告 = 归因分解(&短, 4.2, &hrv, 600, 60);
        assert!(!报告.有效, "短序列应数据不足");
        assert_eq!(报告.各通道[0].相关, 0.0);
    }

    /// ⑥ 最优滞后相关：纯平移恢复滞后
    #[test]
    fn 测试_最优滞后相关_平移恢复() {
        let 基准: u64 = 1724000000;
        let 扰动: Vec<时序点> = (0..20).map(|i| (基准 + i * 60, (i as f64 * 0.5).sin())).collect();
        let 响应: Vec<时序点> = (0..20)
            .map(|i| (基准 + 240 + i * 60, (i as f64 * 0.5).sin() * 2.0)) // 同相位值, 时间戳平移 240s
            .collect();
        let (滞后, 相关) = 最优滞后相关(&扰动, &响应, 600, 60).expect("应有解");
        assert!((滞后 as i64 - 240).abs() <= 60, "滞后≈240s: {}", 滞后);
        assert!(相关 > 0.9, "线性变换相关≈1: {}", 相关);
    }
}
